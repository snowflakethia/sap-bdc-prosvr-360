-- name: pf_portfolio
-- binds: fy0, fy1, s, s
SELECT p.PROJECT_ID, p.PROJECT_NAME, p.MD_GROUP_ID, g.MD_GROUP_NAME, g.MANAGING_DIRECTOR_NAME, c.CUSTOMER_NAME, p.SIZE_CLASS,
       p.CONTRACT_TYPE, p.STATUS_AS_OF, p.CONTRACT_VALUE, COALESCE(r.REVENUE, 0) AS REVENUE, COALESCE(r.MARGIN, 0) AS MARGIN,
       h.CPI, h.SPI, ROUND(100 * h.FORECAST_MARGIN_PCT, 1) AS FORECAST_MARGIN_PCT, h.LD_EXPOSURE, p.IS_STORY_PROJECT,
       CASE WHEN h.PROJECT_ID IS NULL THEN p.STATUS_AS_OF WHEN h.FORECAST_MARGIN_PCT < 0 OR h.CPI < 0.8 THEN 'RED'
            WHEN h.FORECAST_MARGIN_PCT < 0.10 OR h.CPI < 0.95 OR h.SPI < 0.95 THEN 'AMBER' ELSE 'GREEN' END AS RAG
FROM ACOCO_L2.ONTOLOGY.ENT_PROJECT p
JOIN ACOCO_L2.ONTOLOGY.ENT_MD_GROUP g ON g.MD_GROUP_ID = p.MD_GROUP_ID
LEFT JOIN ACOCO_L2.ONTOLOGY.ENT_CUSTOMER c ON c.CUSTOMER_ID = p.CUSTOMER_ID
LEFT JOIN ACOCO_L2.SERVING.VW_PROJECT_HEALTH_NOW h ON h.PROJECT_ID = p.PROJECT_ID
LEFT JOIN (SELECT PROJECT_ID, SUM(REVENUE) AS REVENUE, SUM(MARGIN) AS MARGIN FROM ACOCO_L2.SERVING.VW_PROJECT_REVENUE_FY
           WHERE FISCAL_YEAR BETWEEN ? AND ? GROUP BY PROJECT_ID) r ON r.PROJECT_ID = p.PROJECT_ID
WHERE (r.PROJECT_ID IS NOT NULL OR p.STATUS_AS_OF <> 'CLOSED') AND (p.SIZE_CLASS = ? OR ? = 'ALL')
ORDER BY g.SORT_ORDER, REVENUE DESC, p.PROJECT_ID;

