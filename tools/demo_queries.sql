-- name: as_fy
-- binds: g, g, fy0, fy1
SELECT FISCAL_YEAR, SUM(CLOSED_PROJECTS) AS CLOSED_PROJECTS, SUM(HARVESTED) AS HARVESTED,
       ROUND(100 * SUM(HARVESTED) / NULLIF(SUM(CLOSED_PROJECTS), 0), 1) AS HARVEST_RATE_PCT,
       ROUND(AVG(REUSE_RATE_PCT), 1) AS REUSE_RATE_PCT,
       ROUND(AVG(MEDIAN_CPI_WITH_REUSE), 3) AS CPI_WITH_REUSE, ROUND(AVG(MEDIAN_CPI_WITHOUT_REUSE), 3) AS CPI_WITHOUT_REUSE
FROM ACOCO_L2.SERVING.VW_ASSET_FY
WHERE (MD_GROUP_ID = ? OR ? = 'ALL') AND FISCAL_YEAR BETWEEN ? AND ?
GROUP BY FISCAL_YEAR ORDER BY FISCAL_YEAR;

