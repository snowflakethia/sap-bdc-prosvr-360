"""Generate, lint, create and reconcile the L1 data-domain views from tools/l1_map.yml (PRD 7.1).

  .venv/bin/python tools/gen_l1.py --render       write sql/02_l1/<domain>/<object>.sql + sql/02_l1/_all.sql
  .venv/bin/python tools/gen_l1.py --lint         check the L1 rules (no SQL executed)
  .venv/bin/python tools/gen_l1.py --create       render + lint + create ACOCO_L1 and every view
  .venv/bin/python tools/gen_l1.py --reconcile    per object and source: L1 rows vs base L0 rows, key uniqueness
"""
import argparse
import json
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import sf  # noqa: E402

MAP = yaml.safe_load((ROOT / "tools" / "l1_map.yml").read_text())
OUT = ROOT / "sql" / "02_l1"
FORBIDDEN = [r"\bGROUP\s+BY\b", r"\bSUM\s*\(", r"\bCOUNT\s*\(", r"\bAVG\s*\(", r"\bCURRENT_DATE\b",
             r"\bCURRENT_TIMESTAMP\b", r"\bSYSDATE\b", r'"__', r"load_type_", r"run_id_"]
REF = re.compile(r"\b([A-Z][A-Z0-9_]*_V1)\b|\b(ACOCO_SIM\.[A-Z_]+(?:\.[A-Z_]+)?)\b|\b(ACOCO_DB\.[A-Z_]+)\b|\b(ACOCO_L[12])\b")


def objects():
    for dom, d in MAP["domains"].items():
        for name, o in d["objects"].items():
            yield dom, name, o, d


def render_object(dom, name, o):
    cols = o["columns"]
    parts = []
    for s in o["sources"]:
        sel = []
        for c, t in cols.items():
            expr = s.get("select", {}).get(c)
            sel.append(f"    CAST({expr if expr is not None else 'NULL'} AS {t}) AS {c}")
        sel.append(f"    '{s['system']}' AS SOURCE_SYSTEM")
        q = "  SELECT\n" + ",\n".join(sel) + f"\n  FROM {s['from']}"
        if s.get("joins"):
            q += "\n  " + s["joins"].strip().replace("\n", "\n  ")
        if s.get("where"):
            q += f"\n  WHERE {s['where']}"
        parts.append(q)
    body = "\n  UNION ALL\n".join(parts)
    comment = f"L1 {dom}.{name}: one row per business object; sources " + ", ".join(
        sorted({s['system'] for s in o['sources']})) + ". Generated from tools/l1_map.yml - do not edit."
    return (f"CREATE OR REPLACE VIEW ACOCO_L1.{dom}.{name}\n  COMMENT = '{comment}'\nAS\n{body};\n")


def render():
    OUT.mkdir(parents=True, exist_ok=True)
    allsql = ["-- Generated by tools/gen_l1.py from tools/l1_map.yml. Do not edit by hand.",
              "USE ROLE ACCOUNTADMIN;", "USE WAREHOUSE WH_ACOCO_BUILD;",
              "CREATE DATABASE IF NOT EXISTS ACOCO_L1 COMMENT = 'ACoCo L1: data domains (views only) over L0 CLDs and ACOCO_SIM';"]
    for dom in MAP["domains"]:
        allsql.append(f"CREATE SCHEMA IF NOT EXISTS ACOCO_L1.{dom} COMMENT = 'L1 data domain {dom}';")
    for dom, name, o, _ in objects():
        sql = render_object(dom, name, o)
        p = OUT / dom.lower() / f"{name.lower()}.sql"
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(sql)
        allsql.append(sql)
    (OUT / "_all.sql").write_text("\n".join(allsql) + "\n")
    return OUT / "_all.sql"


def lint():
    errors = []
    cfg = MAP["defaults"]["config"]
    for dom, name, o, d in objects():
        allowed = d["allowed"] + cfg
        if not o["sources"]:
            errors.append(f"{dom}.{name}: no sources")
        for s in o["sources"]:
            text = " ".join(str(s.get(k, "")) for k in ("from", "joins", "where")) + " " + " ".join(
                str(v) for v in s.get("select", {}).values())
            for pat in FORBIDDEN:
                if re.search(pat, text, re.I):
                    errors.append(f"{dom}.{name} [{s['system']}]: forbidden pattern {pat}")
            for m in REF.finditer(text):
                ref = next(g for g in m.groups() if g)
                if ref.startswith("ACOCO_L"):
                    errors.append(f"{dom}.{name}: reads {ref} (L1 may read only L0 and OPS config)")
                elif not any(ref == a or ref.startswith(a + ".") or a.startswith(ref + ".") and ref.count(".") >= 1
                             or ref.split(".")[0] == a for a in allowed):
                    errors.append(f"{dom}.{name} [{s['system']}]: reference {ref} outside domain sources {allowed}")
            extra = set(s.get("select", {})) - set(o["columns"])
            if extra:
                errors.append(f"{dom}.{name} [{s['system']}]: select keys not in columns {sorted(extra)}")
            if s["system"] not in ("BDC_CLD", "SIMULATED", "ACOCO_CONFIG"):
                errors.append(f"{dom}.{name}: unknown SOURCE_SYSTEM {s['system']}")
    return errors


def reconcile():
    rows = []
    for dom, name, o, _ in objects():
        view = sf.query(f"SELECT SOURCE_SYSTEM s, COUNT(*) n FROM ACOCO_L1.{dom}.{name} GROUP BY 1")
        vcount = {r["S"]: r["N"] for r in view}
        by_sys = {}
        for s in o["sources"]:
            q = f"SELECT COUNT(*) n FROM {s['from']}" + (f" WHERE {s['where']}" if s.get("where") else "")
            by_sys[s["system"]] = by_sys.get(s["system"], 0) + sf.query(q)[0]["N"]
        dup = None
        if o.get("key"):
            k = ", ".join(o["key"])
            dup = sf.query(f"SELECT COUNT(*) n FROM (SELECT {k} FROM ACOCO_L1.{dom}.{name} GROUP BY {k} HAVING COUNT(*) > 1)")[0]["N"]
        for sys_, n in by_sys.items():
            rows.append(dict(object=f"{dom}.{name}", source_system=sys_, l0_rows=n, l1_rows=vcount.get(sys_, 0),
                             duplicate_keys=dup, ok=(n == vcount.get(sys_, 0) and not dup)))
    return rows


def main():
    ap = argparse.ArgumentParser()
    for f in ("render", "lint", "create", "reconcile"):
        ap.add_argument(f"--{f}", action="store_true")
    a = ap.parse_args()
    if a.render or a.create:
        print("rendered", render())
    if a.lint or a.create:
        errs = lint()
        (ROOT / "logs" / "l1_lint.json").write_text(json.dumps({"errors": errs}, indent=1))
        print(f"lint: {len(errs)} errors")
        for e in errs:
            print("  ", e)
        if errs:
            sys.exit(1)
    if a.create:
        sf.run_file(str(OUT / "_all.sql"))
        print("created ACOCO_L1 views:", sum(1 for _ in objects()))
    if a.reconcile:
        rows = reconcile()
        (ROOT / "logs" / "l1_reconcile.json").write_text(json.dumps(rows, indent=1))
        bad = [r for r in rows if not r["ok"]]
        for r in rows:
            print(f"{'PASS' if r['ok'] else 'FAIL'}  {r['object']:<45} {r['source_system']:<12} L0 {r['l0_rows']:>10,}  "
                  f"L1 {r['l1_rows']:>10,}  dup_keys {r['duplicate_keys']}")
        print(f"reconcile: {len(rows) - len(bad)}/{len(rows)} PASS")
        sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
