-- CP-01 / 01 - Control plane: database, warehouses, compute pool (suspended), image repository.
-- PRD 5.4. Exact names only; IF NOT EXISTS so a re-run never replaces anything another demo owns.
USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS ACOCO_DB COMMENT = 'ACoCo ProServe360 control plane: OPS config/maps, AGENT, APP';
CREATE SCHEMA IF NOT EXISTS ACOCO_DB.OPS   COMMENT = 'Configuration, generator parameters and mapping tables';
CREATE SCHEMA IF NOT EXISTS ACOCO_DB.AGENT COMMENT = 'Cortex Agent ACOCO_ADVISOR';
CREATE SCHEMA IF NOT EXISTS ACOCO_DB.APP   COMMENT = 'Image repository and SPCS service';

CREATE WAREHOUSE IF NOT EXISTS WH_ACOCO_BUILD
  WAREHOUSE_SIZE = MEDIUM AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 3600
  COMMENT = 'ACoCo build: generator loads, dynamic-table refresh';
CREATE WAREHOUSE IF NOT EXISTS WH_ACOCO_APP
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 300
  COMMENT = 'ACoCo Command Center queries';

CREATE COMPUTE POOL IF NOT EXISTS ACOCO_POOL
  MIN_NODES = 1 MAX_NODES = 1 INSTANCE_FAMILY = CPU_X64_XS
  AUTO_RESUME = TRUE AUTO_SUSPEND_SECS = 3600 INITIALLY_SUSPENDED = TRUE
  COMMENT = 'ACoCo Command Center SPCS service';
ALTER COMPUTE POOL ACOCO_POOL SUSPEND;

CREATE IMAGE REPOSITORY IF NOT EXISTS ACOCO_DB.APP.IMAGES;
