-- CP-10: Command Center on Snowpark Container Services (PRD 8.5).
-- A service cannot be owned by ACCOUNTADMIN, so ACOCO_APP_ROLE owns it. The role reads ACOCO_L2 only
-- (no CLD / ACOCO_SIM / ACOCO_L1 grant): SERVING, SEMANTIC and ONTOLOGY for the app, the mart tables the
-- Semantic Views resolve to, the two Cortex Search services, and the ACOCO_ADVISOR agent.
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS ACOCO_APP_ROLE COMMENT = 'Owner of ACOCO_DB.APP.ACOCO_COMMAND_CENTER (CP-10)';
GRANT ROLE ACOCO_APP_ROLE TO ROLE ACCOUNTADMIN;
GRANT ROLE ACOCO_APP_ROLE TO USER <YOUR_USER>;

-- Container platform
GRANT BIND SERVICE ENDPOINT ON ACCOUNT TO ROLE ACOCO_APP_ROLE;
GRANT USAGE, MONITOR, OPERATE ON COMPUTE POOL ACOCO_POOL TO ROLE ACOCO_APP_ROLE;
GRANT USAGE ON WAREHOUSE WH_ACOCO_APP TO ROLE ACOCO_APP_ROLE;
GRANT USAGE ON DATABASE ACOCO_DB TO ROLE ACOCO_APP_ROLE;
GRANT USAGE, CREATE SERVICE ON SCHEMA ACOCO_DB.APP TO ROLE ACOCO_APP_ROLE;
GRANT READ ON IMAGE REPOSITORY ACOCO_DB.APP.IMAGES TO ROLE ACOCO_APP_ROLE;

-- Agent and Cortex
GRANT USAGE ON SCHEMA ACOCO_DB.AGENT TO ROLE ACOCO_APP_ROLE;
GRANT USAGE ON AGENT ACOCO_DB.AGENT.ACOCO_ADVISOR TO ROLE ACOCO_APP_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE ACOCO_APP_ROLE;

-- ACOCO_L2 read access (views run with owner's rights; SVs and agent tools resolve to mart tables)
GRANT USAGE ON DATABASE ACOCO_L2 TO ROLE ACOCO_APP_ROLE;
GRANT USAGE ON ALL SCHEMAS IN DATABASE ACOCO_L2 TO ROLE ACOCO_APP_ROLE;
GRANT SELECT ON ALL TABLES IN DATABASE ACOCO_L2 TO ROLE ACOCO_APP_ROLE;
GRANT SELECT ON ALL VIEWS IN DATABASE ACOCO_L2 TO ROLE ACOCO_APP_ROLE;
GRANT SELECT ON ALL DYNAMIC TABLES IN DATABASE ACOCO_L2 TO ROLE ACOCO_APP_ROLE;
GRANT SELECT ON ALL SEMANTIC VIEWS IN SCHEMA ACOCO_L2.SEMANTIC TO ROLE ACOCO_APP_ROLE;
-- tools/build_l2.py re-creates every L2 object (CREATE OR REPLACE drops grants): future grants keep the app readable
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE ACOCO_L2 TO ROLE ACOCO_APP_ROLE;
GRANT SELECT ON FUTURE TABLES IN DATABASE ACOCO_L2 TO ROLE ACOCO_APP_ROLE;
GRANT SELECT ON FUTURE VIEWS IN DATABASE ACOCO_L2 TO ROLE ACOCO_APP_ROLE;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN DATABASE ACOCO_L2 TO ROLE ACOCO_APP_ROLE;
GRANT USAGE ON CORTEX SEARCH SERVICE ACOCO_L2.REASONING.CSS_PROJECT_COMMENTARY TO ROLE ACOCO_APP_ROLE;
GRANT USAGE ON CORTEX SEARCH SERVICE ACOCO_L2.REASONING.CSS_ASSET_LIBRARY TO ROLE ACOCO_APP_ROLE;

ALTER COMPUTE POOL ACOCO_POOL RESUME IF SUSPENDED;

USE ROLE ACOCO_APP_ROLE;
CREATE SERVICE IF NOT EXISTS ACOCO_DB.APP.ACOCO_COMMAND_CENTER
  IN COMPUTE POOL ACOCO_POOL
  QUERY_WAREHOUSE = WH_ACOCO_APP
  MIN_INSTANCES = 1 MAX_INSTANCES = 1
  COMMENT = 'ACoCo ProServe360 Partner MD Command Center (CP-10)'
  FROM SPECIFICATION $$
spec:
  containers:
  - name: app
    image: /acoco_db/app/images/acoco_command_center:v7
    env:
      PORT: "8080"
      SNOWFLAKE_WAREHOUSE: WH_ACOCO_APP
      ACOCO_AS_OF: "2026-10-01"
    resources:
      requests: { memory: 1Gi, cpu: 500m }
      limits: { memory: 2Gi, cpu: 1000m }
    readinessProbe:
      port: 8080
      path: /healthcheck
  endpoints:
  - name: ui
    port: 8080
    public: true
$$;

-- Endpoint access for presenters whose default role is ACCOUNTADMIN (the owner role has it already).
GRANT SERVICE ROLE ACOCO_DB.APP.ACOCO_COMMAND_CENTER!ALL_ENDPOINTS_USAGE TO ROLE ACCOUNTADMIN;
