CREATE OR REPLACE VIEW ACOCO_L1.ORGANISATION.MD_GROUP
  COMMENT = 'L1 ORGANISATION.MD_GROUP: one row per business object; sources ACOCO_CONFIG. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(g.MD_GROUP_ID AS VARCHAR) AS MD_GROUP_ID,
    CAST(g.MD_GROUP_NAME AS VARCHAR) AS MD_GROUP_NAME,
    CAST(g.SORT_ORDER AS NUMBER) AS SORT_ORDER,
    'ACOCO_CONFIG' AS SOURCE_SYSTEM
  FROM ACOCO_DB.OPS.MD_GROUP g;
