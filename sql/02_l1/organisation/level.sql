CREATE OR REPLACE VIEW ACOCO_L1.ORGANISATION.LEVEL
  COMMENT = 'L1 ORGANISATION.LEVEL: one row per business object; sources ACOCO_CONFIG. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(l.LEVEL AS VARCHAR) AS LEVEL,
    CAST(l.LEVEL_SORT AS NUMBER) AS LEVEL_SORT,
    CAST(l.BILL_CODE_LO AS NUMBER) AS BILL_CODE_LO,
    CAST(l.BILL_CODE_HI AS NUMBER) AS BILL_CODE_HI,
    CAST(l.COST_PER_DAY AS NUMBER(10,2)) AS COST_PER_DAY,
    CAST(l.BILL_RATE_BASE AS NUMBER(10,2)) AS BILL_RATE_BASE,
    CAST(l.BILL_RATE_STEP AS NUMBER(10,2)) AS BILL_RATE_STEP,
    CAST(t.DELIVERY AS NUMBER(5,1)) AS TARGET_DELIVERY_PCT,
    CAST(t.BID AS NUMBER(5,1)) AS TARGET_BID_PCT,
    CAST(t.LEARNING AS NUMBER(5,1)) AS TARGET_LEARNING_PCT,
    CAST(t.ADMIN AS NUMBER(5,1)) AS TARGET_ADMIN_PCT,
    CAST(t.BENCH AS NUMBER(5,1)) AS TARGET_BENCH_PCT,
    'ACOCO_CONFIG' AS SOURCE_SYSTEM
  FROM ACOCO_DB.OPS.LEVEL l
  LEFT JOIN ACOCO_DB.OPS.GEN_PARAMS_TIME_TARGET t ON t.LEVEL = l.LEVEL;
