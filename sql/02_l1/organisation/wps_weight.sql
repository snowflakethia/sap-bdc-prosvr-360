CREATE OR REPLACE VIEW ACOCO_L1.ORGANISATION.WPS_WEIGHT
  COMMENT = 'L1 ORGANISATION.WPS_WEIGHT: one row per business object; sources ACOCO_CONFIG. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(i.LEVEL AS VARCHAR) AS LEVEL,
    CAST(i.PILLAR AS VARCHAR) AS PILLAR,
    CAST(i.INPUT AS VARCHAR) AS INPUT,
    CAST(DECODE(i.PILLAR, 'VC', w.VC, 'OE', w.OE, 'PD', w.PD, 'TM', w.TM) AS NUMBER(5,1)) AS PILLAR_WEIGHT,
    CAST(i.WEIGHT AS NUMBER(5,1)) AS INPUT_WEIGHT,
    'ACOCO_CONFIG' AS SOURCE_SYSTEM
  FROM ACOCO_DB.OPS.WPS_INPUT_WEIGHTS i
  JOIN ACOCO_DB.OPS.WPS_WEIGHTS w ON w.LEVEL = i.LEVEL;
