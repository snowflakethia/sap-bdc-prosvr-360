CREATE OR REPLACE VIEW ACOCO_L1.SALES.OPPORTUNITY_TEAM
  COMMENT = 'L1 SALES.OPPORTUNITY_TEAM: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(t.OPPORTUNITY_ID AS VARCHAR) AS OPPORTUNITY_ID,
    CAST(t.USER_ID AS VARCHAR) AS PERSON_ID,
    CAST(t.TEAM_ROLE AS VARCHAR) AS TEAM_ROLE,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.CRM.OPPORTUNITY_TEAM t;
