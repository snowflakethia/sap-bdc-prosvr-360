CREATE OR REPLACE VIEW ACOCO_L1.SALES.OPPORTUNITY
  COMMENT = 'L1 SALES.OPPORTUNITY: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(o.OPPORTUNITY_ID AS VARCHAR) AS OPPORTUNITY_ID,
    CAST(o.CUSTOMER AS VARCHAR) AS CUSTOMER_ID,
    CAST(o.MD_GROUP_ID AS VARCHAR) AS MD_GROUP_ID,
    CAST(o.SIZE_CLASS AS VARCHAR) AS SIZE_CLASS,
    CAST(o.WORK_TYPE AS VARCHAR) AS WORK_TYPE,
    CAST(o.ESTIMATED_VALUE AS NUMBER(18,2)) AS ESTIMATED_VALUE,
    CAST(o.IS_FIXED_PRICE AS BOOLEAN) AS IS_FIXED_PRICE,
    CAST(TRY_TO_DATE(o.CREATED_DATE::VARCHAR) AS DATE) AS CREATED_DATE,
    CAST(TRY_TO_DATE(o.EXPECTED_CLOSE_DATE::VARCHAR) AS DATE) AS EXPECTED_CLOSE_DATE,
    CAST(TRY_TO_DATE(o.CLOSED_DATE::VARCHAR) AS DATE) AS CLOSED_DATE,
    CAST(o.STAGE AS VARCHAR) AS STAGE,
    CAST(o.PROBABILITY AS NUMBER) AS PROBABILITY_PCT,
    CAST(o.OUTCOME::VARCHAR AS VARCHAR) AS OUTCOME,
    CAST(o.REQUIRED_AI_SKILL_LEVEL AS NUMBER) AS REQUIRED_AI_SKILL_LEVEL,
    CAST(o.INTERNAL_ORDER AS VARCHAR) AS ORDER_ID,
    CAST(o.PRESALES_HOURS_PLANNED AS NUMBER(10,1)) AS PRESALES_HOURS_PLANNED,
    CAST(o.PROJECT_ID::VARCHAR AS VARCHAR) AS PROJECT_ID,
    CAST(TRY_TO_DATE(o.EXPECTED_START_DATE::VARCHAR) AS DATE) AS EXPECTED_START_DATE,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.CRM.OPPORTUNITY o;
