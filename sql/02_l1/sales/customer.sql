CREATE OR REPLACE VIEW ACOCO_L1.SALES.CUSTOMER
  COMMENT = 'L1 SALES.CUSTOMER: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(a.CUSTOMER AS VARCHAR) AS CUSTOMER_ID,
    CAST(a.ACCOUNT_NAME AS VARCHAR) AS CUSTOMER_NAME,
    CAST(a.MD_GROUP_ID AS VARCHAR) AS MD_GROUP_ID,
    CAST(a.INDUSTRY AS VARCHAR) AS INDUSTRY,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.CRM.ACCOUNT a;
