CREATE OR REPLACE VIEW ACOCO_L1.SALES.OPPORTUNITY_SKILL_REQUIREMENT
  COMMENT = 'L1 SALES.OPPORTUNITY_SKILL_REQUIREMENT: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(s.OPPORTUNITY_ID AS VARCHAR) AS OPPORTUNITY_ID,
    CAST(s.SKILL_ID AS VARCHAR) AS SKILL_ID,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.CRM.OPPORTUNITY_SKILL s;
