CREATE OR REPLACE VIEW ACOCO_L1.WORKFORCE.MD_ROLE
  COMMENT = 'L1 WORKFORCE.MD_ROLE: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(r.USER_ID AS VARCHAR) AS PERSON_ID,
    CAST(r.MD_GROUP_ID AS VARCHAR) AS MD_GROUP_ID,
    CAST(r.ROLE AS VARCHAR) AS ROLE,
    CAST(r.VALID_FROM AS DATE) AS VALID_FROM,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.DIRECTORY.MD_ROLE r;
