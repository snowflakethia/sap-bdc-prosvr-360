CREATE OR REPLACE VIEW ACOCO_L1.WORKFORCE.WORKFORCE_JOB
  COMMENT = 'L1 WORKFORCE.WORKFORCE_JOB: one row per business object; sources BDC_CLD, SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(w."userId" AS VARCHAR) AS PERSON_ID,
    CAST(w."startDate" AS DATE) AS VALID_FROM,
    CAST(w."endDate" AS DATE) AS VALID_TO,
    CAST(w."employmentStatus" AS VARCHAR) AS EMPLOYMENT_STATUS,
    CAST(w."eventReasonCode" AS VARCHAR) AS EVENT_REASON,
    CAST(w."moveOutReason" AS VARCHAR) AS MOVE_OUT_REASON,
    CAST(COALESCE(w."terminations", 0) > 0 AS BOOLEAN) AS IS_TERMINATION,
    CAST(COALESCE(w."externalHires", 0) > 0 AS BOOLEAN) AS IS_HIRE,
    CAST(COALESCE(w."payGrade", 61) AS NUMBER) AS PAY_GRADE,
    CAST(w."payGrade" IS NULL AS BOOLEAN) AS PAY_GRADE_IMPUTED,
    CAST(pg.LEVEL AS VARCHAR) AS LEVEL,
    CAST(pg.BILL_CODE AS NUMBER) AS BILL_CODE,
    CAST(COALESCE(w."costCenter"::VARCHAR, 'UNASSIGNED') AS VARCHAR) AS SF_COST_CENTER,
    CAST(sc.COST_CENTER AS VARCHAR) AS COST_CENTER_ID,
    CAST(sc.MD_GROUP_ID AS VARCHAR) AS MD_GROUP_ID,
    CAST(w."managerId" AS VARCHAR) AS MANAGER_ID,
    CAST(w."fte" AS NUMBER(5,2)) AS FTE,
    CAST(TRY_TO_NUMBER(w."organizationalTenure") AS NUMBER) AS TENURE_MONTHS,
    CAST(w."tenureStartDate" AS DATE) AS TENURE_START,
    CAST(w."annualSalary" AS NUMBER(14,2)) AS ANNUAL_SALARY,
    CAST(w."midPoint" AS NUMBER(14,2)) AS SALARY_MIDPOINT,
    CAST(w."gender" AS VARCHAR) AS GENDER,
    'BDC_CLD' AS SOURCE_SYSTEM
  FROM COREWORKFORCEDATA_V1."coreworkforcedata"."coreworkforce_standardfields" w
  LEFT JOIN ACOCO_DB.OPS.MAP_PAYGRADE_LEVEL pg ON pg.PAY_GRADE = COALESCE(w."payGrade", 61)
  LEFT JOIN ACOCO_DB.OPS.MAP_SF_COSTCENTER sc ON sc.SF_COST_CENTER = COALESCE(w."costCenter"::VARCHAR, 'UNASSIGNED')
  UNION ALL
  SELECT
    CAST(w."userId" AS VARCHAR) AS PERSON_ID,
    CAST(w."startDate" AS DATE) AS VALID_FROM,
    CAST(w."endDate" AS DATE) AS VALID_TO,
    CAST(w."employmentStatus" AS VARCHAR) AS EMPLOYMENT_STATUS,
    CAST(w."eventReasonCode" AS VARCHAR) AS EVENT_REASON,
    CAST(w."moveOutReason" AS VARCHAR) AS MOVE_OUT_REASON,
    CAST(COALESCE(w."terminations", 0) > 0 AS BOOLEAN) AS IS_TERMINATION,
    CAST(COALESCE(w."externalHires", 0) > 0 AS BOOLEAN) AS IS_HIRE,
    CAST(w."payGrade" AS NUMBER) AS PAY_GRADE,
    CAST(FALSE AS BOOLEAN) AS PAY_GRADE_IMPUTED,
    CAST(pg.LEVEL AS VARCHAR) AS LEVEL,
    CAST(pg.BILL_CODE AS NUMBER) AS BILL_CODE,
    CAST(w."costCenter" AS VARCHAR) AS SF_COST_CENTER,
    CAST(sc.COST_CENTER AS VARCHAR) AS COST_CENTER_ID,
    CAST(sc.MD_GROUP_ID AS VARCHAR) AS MD_GROUP_ID,
    CAST(NULL AS VARCHAR) AS MANAGER_ID,
    CAST(w."fte" AS NUMBER(5,2)) AS FTE,
    CAST(TRY_TO_NUMBER(w."organizationalTenure") AS NUMBER) AS TENURE_MONTHS,
    CAST(w."tenureStartDate" AS DATE) AS TENURE_START,
    CAST(w."annualSalary" AS NUMBER(14,2)) AS ANNUAL_SALARY,
    CAST(w."midPoint" AS NUMBER(14,2)) AS SALARY_MIDPOINT,
    CAST(w."gender" AS VARCHAR) AS GENDER,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.COREWORKFORCE.COREWORKFORCE_STANDARDFIELDS w
  LEFT JOIN ACOCO_DB.OPS.MAP_PAYGRADE_LEVEL pg ON pg.PAY_GRADE = w."payGrade"
  LEFT JOIN ACOCO_DB.OPS.MAP_SF_COSTCENTER sc ON sc.SF_COST_CENTER = w."costCenter";
