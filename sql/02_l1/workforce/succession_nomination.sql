CREATE OR REPLACE VIEW ACOCO_L1.WORKFORCE.SUCCESSION_NOMINATION
  COMMENT = 'L1 WORKFORCE.SUCCESSION_NOMINATION: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(n.USER_ID AS VARCHAR) AS PERSON_ID,
    CAST(n.NOMINATION_TYPE AS VARCHAR) AS NOMINATION_TYPE,
    CAST(n.HAS_READY_SUCCESSOR AS BOOLEAN) AS HAS_READY_SUCCESSOR,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.SUCCESSION.NOMINATION n;
