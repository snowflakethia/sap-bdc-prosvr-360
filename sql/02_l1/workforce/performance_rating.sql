CREATE OR REPLACE VIEW ACOCO_L1.WORKFORCE.PERFORMANCE_RATING
  COMMENT = 'L1 WORKFORCE.PERFORMANCE_RATING: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(r.USER_ID AS VARCHAR) AS PERSON_ID,
    CAST(r.FISCAL_YEAR AS NUMBER) AS FISCAL_YEAR,
    CAST(r.RATING_DATE AS DATE) AS RATING_DATE,
    CAST(r.PERFORMANCE_RATING AS NUMBER) AS PERFORMANCE_RATING,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.PERFORMANCE.PERFORMANCE_RATING r;
