CREATE OR REPLACE VIEW ACOCO_L1.WORKFORCE.COMPENSATION_SUMMARY
  COMMENT = 'L1 WORKFORCE.COMPENSATION_SUMMARY: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(c.USER_ID AS VARCHAR) AS PERSON_ID,
    CAST(c.LEVEL AS VARCHAR) AS LEVEL,
    CAST(c.PAY_BAND AS VARCHAR) AS PAY_BAND,
    CAST(c.COMPA_RATIO AS NUMBER(6,3)) AS COMPA_RATIO,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.COMPENSATION.COMPENSATION_SUMMARY c;
