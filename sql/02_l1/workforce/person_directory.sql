CREATE OR REPLACE VIEW ACOCO_L1.WORKFORCE.PERSON_DIRECTORY
  COMMENT = 'L1 WORKFORCE.PERSON_DIRECTORY: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(n.USER_ID AS VARCHAR) AS PERSON_ID,
    CAST(n.FIRST_NAME AS VARCHAR) AS FIRST_NAME,
    CAST(n.LAST_NAME AS VARCHAR) AS LAST_NAME,
    CAST(n.FIRST_NAME || ' ' || n.LAST_NAME AS VARCHAR) AS DISPLAY_NAME,
    CAST(n.USER_ID LIKE 'S9%' AS BOOLEAN) AS IS_SIMULATED_PERSON,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.DIRECTORY.PERSON_NAME n;
