CREATE OR REPLACE VIEW ACOCO_L1.FINANCE.INTERNAL_ORDER
  COMMENT = 'L1 FINANCE.INTERNAL_ORDER: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(o."OrderID" AS VARCHAR) AS ORDER_ID,
    CAST(o."OrderType" AS VARCHAR) AS ORDER_TYPE,
    CAST(o."OpportunityID"::VARCHAR AS VARCHAR) AS OPPORTUNITY_ID,
    CAST(o."CompanyCode" AS VARCHAR) AS COMPANY_CODE,
    CAST(o."ResponsibleCostCenter" AS VARCHAR) AS RESPONSIBLE_COST_CENTER_ID,
    CAST(TRY_TO_DATE(o."CreatedDate"::VARCHAR) AS DATE) AS CREATED_DATE,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.INTERNALORDER.INTERNAL_ORDER o;
