CREATE OR REPLACE VIEW ACOCO_L1.FINANCE.PLAN_ITEM
  COMMENT = 'L1 FINANCE.PLAN_ITEM: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(p."PlanningCategory" AS VARCHAR) AS PLANNING_CATEGORY,
    CAST(p."CompanyCode" AS VARCHAR) AS COMPANY_CODE,
    CAST(p."WBSElement" AS VARCHAR) AS WBS_ID,
    CAST(TRY_TO_NUMBER(p."FiscalYear") AS NUMBER) AS FISCAL_YEAR,
    CAST(TRY_TO_NUMBER(p."FiscalPeriod") AS NUMBER) AS FISCAL_PERIOD,
    CAST(p."GLAccount" AS VARCHAR) AS GL_ACCOUNT,
    CAST(p."AmountInCompanyCodeCurrency" AS NUMBER(18,2)) AS PLAN_AMOUNT,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.FINANCE_ACOCO.FINANCIALPLANNINGENTRYITEM p;
