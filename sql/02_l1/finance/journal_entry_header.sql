CREATE OR REPLACE VIEW ACOCO_L1.FINANCE.JOURNAL_ENTRY_HEADER
  COMMENT = 'L1 FINANCE.JOURNAL_ENTRY_HEADER: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(h."CompanyCode" AS VARCHAR) AS COMPANY_CODE,
    CAST(TRY_TO_NUMBER(h."FiscalYear") AS NUMBER) AS FISCAL_YEAR,
    CAST(h."AccountingDocument" AS VARCHAR) AS ACCOUNTING_DOCUMENT,
    CAST(h."AccountingDocumentType" AS VARCHAR) AS DOCUMENT_TYPE,
    CAST(h."PostingDate" AS DATE) AS POSTING_DATE,
    CAST(h."IsReversal" AS BOOLEAN) AS IS_REVERSAL,
    CAST(h."IsReversed" AS BOOLEAN) AS IS_REVERSED,
    CAST(h."ReversalReferenceDocument"::VARCHAR AS VARCHAR) AS REVERSAL_OF_DOCUMENT,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.FINANCE_ACOCO.JOURNALENTRY h;
