CREATE OR REPLACE VIEW ACOCO_L1.TALENT.LEARNING_COMPLETION
  COMMENT = 'L1 TALENT.LEARNING_COMPLETION: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(c.USER_ID AS VARCHAR) AS PERSON_ID,
    CAST(c.LEARNING_ITEM_ID AS VARCHAR) AS LEARNING_ITEM_ID,
    CAST(c.COMPLETION_DATE AS DATE) AS COMPLETION_DATE,
    CAST(c.COMPLETION_STATUS AS VARCHAR) AS COMPLETION_STATUS,
    CAST(c.LEARNING_HOURS AS NUMBER(6,1)) AS LEARNING_HOURS,
    CAST(c.ASSESSMENT_SCORE AS NUMBER(5,1)) AS ASSESSMENT_SCORE,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.LEARNING.LEARNING_COMPLETION c;
