CREATE OR REPLACE VIEW ACOCO_L1.TALENT.LEARNING_ITEM
  COMMENT = 'L1 TALENT.LEARNING_ITEM: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(i.LEARNING_ITEM_ID AS VARCHAR) AS LEARNING_ITEM_ID,
    CAST(i.LEARNING_ITEM_TITLE AS VARCHAR) AS LEARNING_ITEM_TITLE,
    CAST(i.CURRICULUM AS VARCHAR) AS CURRICULUM,
    CAST(i.IS_AI_CURRICULUM AS BOOLEAN) AS IS_AI_CURRICULUM,
    CAST(i.TARGET_SKILL_ID AS VARCHAR) AS TARGET_SKILL_ID,
    CAST(i.TARGET_PROFICIENCY_LEVEL AS NUMBER) AS TARGET_PROFICIENCY_LEVEL,
    CAST(i.LEARNING_HOURS AS NUMBER(6,1)) AS LEARNING_HOURS,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.LEARNING.LEARNING_ITEM i;
