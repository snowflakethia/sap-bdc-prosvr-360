CREATE OR REPLACE VIEW ACOCO_L1.TALENT.SKILL
  COMMENT = 'L1 TALENT.SKILL: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(s.SKILL_ID AS VARCHAR) AS SKILL_ID,
    CAST(s.SKILL_NAME AS VARCHAR) AS SKILL_NAME,
    CAST(s.SKILL_FAMILY AS VARCHAR) AS SKILL_FAMILY,
    CAST(s.SKILL_FAMILY = 'AGENTIC_AI' AS BOOLEAN) AS IS_AGENTIC_AI,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.SKILLS.SKILL s;
