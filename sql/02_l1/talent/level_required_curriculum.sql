CREATE OR REPLACE VIEW ACOCO_L1.TALENT.LEVEL_REQUIRED_CURRICULUM
  COMMENT = 'L1 TALENT.LEVEL_REQUIRED_CURRICULUM: one row per business object; sources ACOCO_CONFIG. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(r.LEVEL AS VARCHAR) AS LEVEL,
    CAST(r.CURRICULUM AS VARCHAR) AS CURRICULUM,
    'ACOCO_CONFIG' AS SOURCE_SYSTEM
  FROM ACOCO_DB.OPS.LEVEL_REQUIRED_CURRICULUM r;
