CREATE OR REPLACE VIEW ACOCO_L1.TALENT.PERSON_SKILL
  COMMENT = 'L1 TALENT.PERSON_SKILL: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(p.USER_ID AS VARCHAR) AS PERSON_ID,
    CAST(p.SKILL_ID AS VARCHAR) AS SKILL_ID,
    CAST(p.ASSESSED_DATE AS DATE) AS ASSESSED_DATE,
    CAST(p.PROFICIENCY AS NUMBER) AS PROFICIENCY,
    CAST(p.ASSESSMENT_SOURCE AS VARCHAR) AS ASSESSMENT_SOURCE,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.SKILLS.PERSON_SKILL p;
