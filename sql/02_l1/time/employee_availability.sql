CREATE OR REPLACE VIEW ACOCO_L1.TIME.EMPLOYEE_AVAILABILITY
  COMMENT = 'L1 TIME.EMPLOYEE_AVAILABILITY: one row per business object; sources BDC_CLD, SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(e."assignmentId" AS VARCHAR) AS ASSIGNMENT_ID,
    CAST(m.USER_ID AS VARCHAR) AS PERSON_ID,
    CAST(IFF(m.USER_ID IS NULL, 'UNMATCHED', 'INFERRED_' || m.MATCH_METHOD) AS VARCHAR) AS PERSON_LINK,
    CAST(e."workDate" AS DATE) AS WORK_DATE,
    CAST(COALESCE(e."plannedWorkHours", 0) AS NUMBER(6,2)) AS PLANNED_HOURS,
    CAST(COALESCE(e."dailyAbsenceHours", 0) AS NUMBER(6,2)) AS ABSENCE_HOURS,
    CAST(GREATEST(COALESCE(e."plannedWorkHours", 0) - COALESCE(e."dailyAbsenceHours", 0), 0) AS NUMBER(6,2)) AS AVAILABLE_HOURS,
    CAST(e."isPublicHoliday" AS BOOLEAN) AS IS_PUBLIC_HOLIDAY,
    CAST(e."isWeeklyOff" AS BOOLEAN) AS IS_WEEKLY_OFF,
    CAST(e."absenceType" AS VARCHAR) AS ABSENCE_TYPE,
    CAST(e."availabilityStatus" AS VARCHAR) AS AVAILABILITY_STATUS,
    'BDC_CLD' AS SOURCE_SYSTEM
  FROM EMPLOYEEAVAILABILITY_V1."employeeavailability"."employeeavailability" e
  LEFT JOIN ACOCO_DB.OPS.MAP_ASSIGNMENT_USER m ON m.ASSIGNMENT_ID = e."assignmentId"
  UNION ALL
  SELECT
    CAST(e."assignmentId" AS VARCHAR) AS ASSIGNMENT_ID,
    CAST(COALESCE(m.USER_ID, SUBSTR(e."assignmentId", 4)) AS VARCHAR) AS PERSON_ID,
    CAST(IFF(m.USER_ID IS NULL, 'SIMULATED_PERSON', 'INFERRED_' || m.MATCH_METHOD) AS VARCHAR) AS PERSON_LINK,
    CAST(e."workDate" AS DATE) AS WORK_DATE,
    CAST(e."plannedWorkHours" AS NUMBER(6,2)) AS PLANNED_HOURS,
    CAST(e."dailyAbsenceHours" AS NUMBER(6,2)) AS ABSENCE_HOURS,
    CAST(GREATEST(e."plannedWorkHours" - e."dailyAbsenceHours", 0) AS NUMBER(6,2)) AS AVAILABLE_HOURS,
    CAST(e."isPublicHoliday" AS BOOLEAN) AS IS_PUBLIC_HOLIDAY,
    CAST(e."isWeeklyOff" AS BOOLEAN) AS IS_WEEKLY_OFF,
    CAST(e."absenceType" AS VARCHAR) AS ABSENCE_TYPE,
    CAST(e."availabilityStatus" AS VARCHAR) AS AVAILABILITY_STATUS,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.EMPLOYEEAVAILABILITY.EMPLOYEEAVAILABILITY e
  LEFT JOIN ACOCO_DB.OPS.MAP_ASSIGNMENT_USER m ON m.ASSIGNMENT_ID = e."assignmentId";
