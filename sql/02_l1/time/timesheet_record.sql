CREATE OR REPLACE VIEW ACOCO_L1.TIME.TIMESHEET_RECORD
  COMMENT = 'L1 TIME.TIMESHEET_RECORD: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(t.TIMESHEET_RECORD AS VARCHAR) AS TIMESHEET_RECORD_ID,
    CAST(t.USER_ID AS VARCHAR) AS PERSON_ID,
    CAST(UPPER(TRIM(t.COST_CENTER)) AS VARCHAR) AS COST_CENTER_ID,
    CAST(t.WEEK_START AS DATE) AS WEEK_START,
    CAST(t.FISCAL_YEAR AS NUMBER) AS FISCAL_YEAR,
    CAST(t.CATEGORY AS VARCHAR) AS TIME_CATEGORY,
    CAST(t.WBS_ELEMENT::VARCHAR AS VARCHAR) AS WBS_ID,
    CAST(t.INTERNAL_ORDER AS VARCHAR) AS ORDER_ID,
    CAST(t.HOURS AS NUMBER(8,1)) AS HOURS,
    CAST(t.ZZ_EARNED_HOURS AS NUMBER(8,1)) AS EARNED_HOURS,
    CAST(t.ZZ_AI_ASSISTED_HOURS AS NUMBER(8,1)) AS AI_ASSISTED_HOURS,
    CAST(t.ZZ_AI_HOURS_SAVED AS NUMBER(8,1)) AS AI_HOURS_SAVED,
    CAST(t.BILLABLE_CONTROL AS VARCHAR) AS BILLABLE_CONTROL,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.TIMESHEET.TIMESHEET t;
