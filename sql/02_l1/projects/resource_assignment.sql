CREATE OR REPLACE VIEW ACOCO_L1.PROJECTS.RESOURCE_ASSIGNMENT
  COMMENT = 'L1 PROJECTS.RESOURCE_ASSIGNMENT: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(a.ASSIGNMENT_ID AS VARCHAR) AS ASSIGNMENT_ID,
    CAST(a.USER_ID AS VARCHAR) AS PERSON_ID,
    CAST(a.PROJECT_ID AS VARCHAR) AS PROJECT_ID,
    CAST(a.WBS_ELEMENT::VARCHAR AS VARCHAR) AS WBS_ID,
    CAST(a.ASSIGNMENT_START AS DATE) AS ASSIGNMENT_START,
    CAST(a.ASSIGNMENT_END AS DATE) AS ASSIGNMENT_END,
    CAST(a.ALLOCATION AS NUMBER(5,3)) AS ALLOCATION,
    CAST(a.ROLE AS VARCHAR) AS ASSIGNMENT_ROLE,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.RESOURCEASSIGNMENT.RESOURCE_ASSIGNMENT a;
