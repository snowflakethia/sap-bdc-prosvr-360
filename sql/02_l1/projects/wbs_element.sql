CREATE OR REPLACE VIEW ACOCO_L1.PROJECTS.WBS_ELEMENT
  COMMENT = 'L1 PROJECTS.WBS_ELEMENT: one row per business object; sources BDC_CLD, SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(w."WBSElement" AS VARCHAR) AS WBS_ID,
    CAST(NULL AS VARCHAR) AS PROJECT_ID,
    CAST(w."WBSDescription" AS VARCHAR) AS WBS_NAME,
    CAST(NULL AS VARCHAR) AS WORK_TYPE,
    CAST(NULL AS VARCHAR) AS OWNER_PERSON_ID,
    CAST(NULL AS NUMBER(12,1)) AS PLANNED_HOURS,
    CAST(NULL AS DATE) AS PLANNED_START,
    CAST(NULL AS DATE) AS PLANNED_END,
    CAST(NULL AS DATE) AS FORECAST_END,
    CAST(NULL AS DATE) AS ACTUAL_END,
    CAST(NULL AS NUMBER(6,3)) AS TEAM_PRODUCTIVITY,
    CAST(NULL AS VARCHAR) AS REUSED_ASSET_ID,
    CAST(NULL AS BOOLEAN) AS IS_CRITICAL_PATH,
    'BDC_CLD' AS SOURCE_SYSTEM
  FROM PROJECT_V1."project"."workbreakdownstructureelement" w
  WHERE w."CompanyCode" = 'USC1'
  UNION ALL
  SELECT
    CAST(w.WBS_ELEMENT AS VARCHAR) AS WBS_ID,
    CAST(w.PROJECT_ID AS VARCHAR) AS PROJECT_ID,
    CAST(w.WORK_PACKAGE_NAME AS VARCHAR) AS WBS_NAME,
    CAST(w.WORK_TYPE AS VARCHAR) AS WORK_TYPE,
    CAST(w.OWNER_USER_ID AS VARCHAR) AS OWNER_PERSON_ID,
    CAST(w.PLANNED_HOURS AS NUMBER(12,1)) AS PLANNED_HOURS,
    CAST(w.PLANNED_START AS DATE) AS PLANNED_START,
    CAST(w.PLANNED_END AS DATE) AS PLANNED_END,
    CAST(w.FORECAST_END AS DATE) AS FORECAST_END,
    CAST(TRY_TO_DATE(w.ACTUAL_END::VARCHAR) AS DATE) AS ACTUAL_END,
    CAST(w.TEAM_PRODUCTIVITY AS NUMBER(6,3)) AS TEAM_PRODUCTIVITY,
    CAST(w.REUSED_ASSET_ID AS VARCHAR) AS REUSED_ASSET_ID,
    CAST(w.IS_CRITICAL_PATH AS BOOLEAN) AS IS_CRITICAL_PATH,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.CUSTOMERPROJECT.WORK_PACKAGE w;
