CREATE OR REPLACE VIEW ACOCO_L1.PROJECTS.WBS_LEVEL_PLAN
  COMMENT = 'L1 PROJECTS.WBS_LEVEL_PLAN: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(p.WBS_ELEMENT AS VARCHAR) AS WBS_ID,
    CAST(p.LEVEL AS VARCHAR) AS LEVEL,
    CAST(p.PLANNED_HOURS AS NUMBER(12,1)) AS PLANNED_HOURS,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.CUSTOMERPROJECT.WORK_PACKAGE_LEVEL_PLAN p;
