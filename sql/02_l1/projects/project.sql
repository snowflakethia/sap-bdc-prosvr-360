CREATE OR REPLACE VIEW ACOCO_L1.PROJECTS.PROJECT
  COMMENT = 'L1 PROJECTS.PROJECT: one row per business object; sources BDC_CLD, SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(p."Project" AS VARCHAR) AS PROJECT_ID,
    CAST(p."ProjectDescription" AS VARCHAR) AS PROJECT_NAME,
    CAST(NULL AS VARCHAR) AS OPPORTUNITY_ID,
    CAST(NULL AS VARCHAR) AS CUSTOMER_ID,
    CAST(NULL AS VARCHAR) AS MD_GROUP_ID,
    CAST(p."CompanyCode" AS VARCHAR) AS COMPANY_CODE,
    CAST(NULL AS VARCHAR) AS SIZE_CLASS,
    CAST(NULL AS VARCHAR) AS WORK_TYPE,
    CAST(NULL AS VARCHAR) AS CONTRACT_TYPE,
    CAST(NULL AS NUMBER(18,2)) AS CONTRACT_VALUE,
    CAST(NULL AS NUMBER(18,2)) AS SOLD_COST,
    CAST(NULL AS NUMBER(6,3)) AS LD_RATE_PCT_PER_WEEK,
    CAST(NULL AS VARCHAR) AS DELIVERY_MODEL,
    CAST(TRY_TO_DATE(p."PlannedStartDate"::VARCHAR) AS DATE) AS PLANNED_START,
    CAST(TRY_TO_DATE(p."PlannedEndDate"::VARCHAR) AS DATE) AS PLANNED_END,
    CAST(NULL AS VARCHAR) AS SEEDED_STORY,
    'BDC_CLD' AS SOURCE_SYSTEM
  FROM PROJECT_V1."project"."project" p
  WHERE p."CompanyCode" = 'USC1'
  UNION ALL
  SELECT
    CAST(p.PROJECT_ID AS VARCHAR) AS PROJECT_ID,
    CAST(p.WORK_TYPE || ' - ' || p.PROJECT_ID AS VARCHAR) AS PROJECT_NAME,
    CAST(p.OPPORTUNITY_ID AS VARCHAR) AS OPPORTUNITY_ID,
    CAST(p.CUSTOMER AS VARCHAR) AS CUSTOMER_ID,
    CAST(p.MD_GROUP_ID AS VARCHAR) AS MD_GROUP_ID,
    CAST('USC1' AS VARCHAR) AS COMPANY_CODE,
    CAST(p.SIZE_CLASS AS VARCHAR) AS SIZE_CLASS,
    CAST(p.WORK_TYPE AS VARCHAR) AS WORK_TYPE,
    CAST(p.CONTRACT_TYPE AS VARCHAR) AS CONTRACT_TYPE,
    CAST(p.CONTRACT_VALUE AS NUMBER(18,2)) AS CONTRACT_VALUE,
    CAST(p.SOLD_COST AS NUMBER(18,2)) AS SOLD_COST,
    CAST(p.LD_RATE_PCT_PER_WEEK AS NUMBER(6,3)) AS LD_RATE_PCT_PER_WEEK,
    CAST(p.DELIVERY_MODEL AS VARCHAR) AS DELIVERY_MODEL,
    CAST(p.PLANNED_START AS DATE) AS PLANNED_START,
    CAST(p.PLANNED_END AS DATE) AS PLANNED_END,
    CAST(p.SEEDED_STORY AS VARCHAR) AS SEEDED_STORY,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.CUSTOMERPROJECT.CUSTOMER_PROJECT p;
