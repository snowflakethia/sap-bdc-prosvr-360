CREATE OR REPLACE VIEW ACOCO_L1.PROJECTS.WORK_PACKAGE_SKILL_REQUIREMENT
  COMMENT = 'L1 PROJECTS.WORK_PACKAGE_SKILL_REQUIREMENT: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(s.WBS_ELEMENT AS VARCHAR) AS WBS_ID,
    CAST(s.SKILL_ID AS VARCHAR) AS SKILL_ID,
    CAST(s.REQUIRED_PROFICIENCY AS NUMBER) AS REQUIRED_PROFICIENCY,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.CUSTOMERPROJECT.WORK_PACKAGE_SKILL s;
