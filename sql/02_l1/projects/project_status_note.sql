CREATE OR REPLACE VIEW ACOCO_L1.PROJECTS.PROJECT_STATUS_NOTE
  COMMENT = 'L1 PROJECTS.PROJECT_STATUS_NOTE: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(n.NOTE_ID AS VARCHAR) AS NOTE_ID,
    CAST(n.PROJECT_ID AS VARCHAR) AS PROJECT_ID,
    CAST(n.NOTE_DATE AS DATE) AS NOTE_DATE,
    CAST(n.RAG_STATUS AS VARCHAR) AS RAG_STATUS,
    CAST(n.NOTE_TEXT AS VARCHAR) AS NOTE_TEXT,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.PROJECTCOMMENTARY.STATUS_NOTE n;
