CREATE OR REPLACE VIEW ACOCO_L1.AI_TELEMETRY.AI_MODEL
  COMMENT = 'L1 AI_TELEMETRY.AI_MODEL: one row per business object; sources ACOCO_CONFIG. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(m.VENDOR AS VARCHAR) AS AI_TOOL_ID,
    CAST(m.PRODUCT AS VARCHAR) AS PRODUCT,
    CAST(m.MODEL AS VARCHAR) AS MODEL,
    CAST(m.MODEL_FAMILY AS VARCHAR) AS MODEL_FAMILY,
    CAST(m.INPUT_USD_PER_MTOK AS NUMBER(8,3)) AS INPUT_USD_PER_MTOK,
    CAST(m.OUTPUT_USD_PER_MTOK AS NUMBER(8,3)) AS OUTPUT_USD_PER_MTOK,
    CAST(m.AVAILABLE_FROM AS DATE) AS AVAILABLE_FROM,
    CAST(m.AVAILABLE_TO AS DATE) AS AVAILABLE_TO,
    'ACOCO_CONFIG' AS SOURCE_SYSTEM
  FROM ACOCO_DB.OPS.AI_MODEL_PRICE m;
