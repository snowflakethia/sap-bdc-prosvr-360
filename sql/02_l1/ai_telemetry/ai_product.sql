CREATE OR REPLACE VIEW ACOCO_L1.AI_TELEMETRY.AI_PRODUCT
  COMMENT = 'L1 AI_TELEMETRY.AI_PRODUCT: one row per business object; sources ACOCO_CONFIG. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(p.PRODUCT AS VARCHAR) AS PRODUCT,
    CAST(p.VENDOR AS VARCHAR) AS AI_TOOL_ID,
    CAST(p.PRODUCT_NAME AS VARCHAR) AS PRODUCT_NAME,
    CAST(p.PRODUCT_KIND AS VARCHAR) AS PRODUCT_KIND,
    CAST(p.AVAILABLE_FROM AS DATE) AS AVAILABLE_FROM,
    CAST(p.AVAILABLE_TO AS DATE) AS AVAILABLE_TO,
    'ACOCO_CONFIG' AS SOURCE_SYSTEM
  FROM ACOCO_DB.OPS.AI_PRODUCT p;
