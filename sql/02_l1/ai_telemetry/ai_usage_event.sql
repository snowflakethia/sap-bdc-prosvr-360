CREATE OR REPLACE VIEW ACOCO_L1.AI_TELEMETRY.AI_USAGE_EVENT
  COMMENT = 'L1 AI_TELEMETRY.AI_USAGE_EVENT: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST('OPENAI' AS VARCHAR) AS AI_TOOL_ID,
    CAST(u.USAGE_DATE AS DATE) AS USAGE_DATE,
    CAST(u.USER_KEY::VARCHAR AS VARCHAR) AS PERSON_ID,
    CAST(u.PROJECT_KEY::VARCHAR AS VARCHAR) AS WBS_ID,
    CAST(u.SESSIONS AS NUMBER) AS SESSIONS,
    CAST(u.TOKENS AS NUMBER) AS TOKENS,
    CAST(u.COST_USD AS NUMBER(12,4)) AS COST_USD,
    CAST(u.PRODUCT AS VARCHAR) AS PRODUCT,
    CAST(u.MODEL AS VARCHAR) AS MODEL,
    CAST(u.INPUT_TOKENS AS NUMBER) AS INPUT_TOKENS,
    CAST(u.OUTPUT_TOKENS AS NUMBER) AS OUTPUT_TOKENS,
    CAST(u.USE_CASE AS VARCHAR) AS USE_CASE,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.TELEMETRY.OPENAI_USAGE u
  UNION ALL
  SELECT
    CAST('ANTHROPIC' AS VARCHAR) AS AI_TOOL_ID,
    CAST(u.USAGE_DATE AS DATE) AS USAGE_DATE,
    CAST(u.USER_KEY::VARCHAR AS VARCHAR) AS PERSON_ID,
    CAST(u.PROJECT_KEY::VARCHAR AS VARCHAR) AS WBS_ID,
    CAST(u.SESSIONS AS NUMBER) AS SESSIONS,
    CAST(u.TOKENS AS NUMBER) AS TOKENS,
    CAST(u.COST_USD AS NUMBER(12,4)) AS COST_USD,
    CAST(u.PRODUCT AS VARCHAR) AS PRODUCT,
    CAST(u.MODEL AS VARCHAR) AS MODEL,
    CAST(u.INPUT_TOKENS AS NUMBER) AS INPUT_TOKENS,
    CAST(u.OUTPUT_TOKENS AS NUMBER) AS OUTPUT_TOKENS,
    CAST(u.USE_CASE AS VARCHAR) AS USE_CASE,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.TELEMETRY.ANTHROPIC_USAGE u
  UNION ALL
  SELECT
    CAST('CORTEX' AS VARCHAR) AS AI_TOOL_ID,
    CAST(u.USAGE_DATE AS DATE) AS USAGE_DATE,
    CAST(u.USER_KEY::VARCHAR AS VARCHAR) AS PERSON_ID,
    CAST(u.PROJECT_KEY::VARCHAR AS VARCHAR) AS WBS_ID,
    CAST(u.SESSIONS AS NUMBER) AS SESSIONS,
    CAST(u.TOKENS AS NUMBER) AS TOKENS,
    CAST(u.COST_USD AS NUMBER(12,4)) AS COST_USD,
    CAST(u.PRODUCT AS VARCHAR) AS PRODUCT,
    CAST(u.MODEL AS VARCHAR) AS MODEL,
    CAST(u.INPUT_TOKENS AS NUMBER) AS INPUT_TOKENS,
    CAST(u.OUTPUT_TOKENS AS NUMBER) AS OUTPUT_TOKENS,
    CAST(u.USE_CASE AS VARCHAR) AS USE_CASE,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.TELEMETRY.CORTEX_USAGE u;
