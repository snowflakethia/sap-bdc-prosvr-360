CREATE OR REPLACE VIEW ACOCO_L1.AI_TELEMETRY.AI_IDENTITY_MAP
  COMMENT = 'L1 AI_TELEMETRY.AI_IDENTITY_MAP: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(i.USER_ID AS VARCHAR) AS PERSON_ID,
    CAST(i.OPENAI_USER_ID AS VARCHAR) AS OPENAI_USER_ID,
    CAST(i.ANTHROPIC_ACTOR_EMAIL AS VARCHAR) AS ANTHROPIC_ACTOR_EMAIL,
    CAST(i.SNOWFLAKE_USER_NAME AS VARCHAR) AS SNOWFLAKE_USER_NAME,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.TELEMETRY.AI_IDENTITY_MAP i;
