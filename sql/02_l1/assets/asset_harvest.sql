CREATE OR REPLACE VIEW ACOCO_L1.ASSETS.ASSET_HARVEST
  COMMENT = 'L1 ASSETS.ASSET_HARVEST: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(h.ASSET_ID AS VARCHAR) AS ASSET_ID,
    CAST(h.SOURCE_PROJECT_ID::VARCHAR AS VARCHAR) AS SOURCE_PROJECT_ID,
    CAST(TRY_TO_DATE(h.HARVEST_DATE::VARCHAR) AS DATE) AS HARVEST_DATE,
    CAST(h.HARVESTED_BY_USER_ID::VARCHAR AS VARCHAR) AS HARVESTED_BY_PERSON_ID,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.ASSETS.ASSET_HARVEST h;
