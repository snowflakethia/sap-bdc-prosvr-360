CREATE OR REPLACE VIEW ACOCO_L1.ASSETS.ASSET
  COMMENT = 'L1 ASSETS.ASSET: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(a.ASSET_ID AS VARCHAR) AS ASSET_ID,
    CAST(a.ASSET_TITLE AS VARCHAR) AS ASSET_TITLE,
    CAST(a.ASSET_TYPE AS VARCHAR) AS ASSET_TYPE,
    CAST(a.WORK_TYPE AS VARCHAR) AS WORK_TYPE,
    CAST(a.SKILL_TAGS AS VARCHAR) AS SKILL_TAGS,
    CAST(a.CATALOGUED_EFFORT_SAVING_HOURS AS NUMBER(10,1)) AS EFFORT_SAVING_HOURS,
    CAST(TRY_TO_DATE(a.HARVESTED_DATE::VARCHAR) AS DATE) AS HARVESTED_DATE,
    CAST(a.DESCRIPTION AS VARCHAR) AS DESCRIPTION,
    CAST(a.STATUS AS VARCHAR) AS ASSET_STATUS,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.ASSETS.ASSET a;
