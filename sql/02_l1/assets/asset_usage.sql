CREATE OR REPLACE VIEW ACOCO_L1.ASSETS.ASSET_USAGE
  COMMENT = 'L1 ASSETS.ASSET_USAGE: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(u.ASSET_ID AS VARCHAR) AS ASSET_ID,
    CAST(u.PROJECT_ID AS VARCHAR) AS PROJECT_ID,
    CAST(u.WBS_ELEMENT AS VARCHAR) AS WBS_ID,
    CAST(u.OPPORTUNITY_ID::VARCHAR AS VARCHAR) AS OPPORTUNITY_ID,
    CAST(TRY_TO_DATE(u.USE_DATE::VARCHAR) AS DATE) AS USE_DATE,
    CAST(u.HOURS_SAVED_ESTIMATED AS NUMBER(10,1)) AS HOURS_SAVED_ESTIMATED,
    CAST(u.USED_BY_USER_ID::VARCHAR AS VARCHAR) AS USED_BY_PERSON_ID,
    CAST(u.RATING AS NUMBER) AS RATING,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.ASSETS.ASSET_USAGE u;
