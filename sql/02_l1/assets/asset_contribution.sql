CREATE OR REPLACE VIEW ACOCO_L1.ASSETS.ASSET_CONTRIBUTION
  COMMENT = 'L1 ASSETS.ASSET_CONTRIBUTION: one row per business object; sources SIMULATED. Generated from tools/l1_map.yml - do not edit.'
AS
  SELECT
    CAST(c.ASSET_ID AS VARCHAR) AS ASSET_ID,
    CAST(c.USER_ID::VARCHAR AS VARCHAR) AS PERSON_ID,
    CAST(c.CONTRIBUTION_ROLE AS VARCHAR) AS CONTRIBUTION_ROLE,
    CAST(c.HOURS AS NUMBER(8,1)) AS HOURS,
    CAST(TRY_TO_DATE(c.CONTRIBUTION_DATE::VARCHAR) AS DATE) AS CONTRIBUTION_DATE,
    'SIMULATED' AS SOURCE_SYSTEM
  FROM ACOCO_SIM.ASSETS.ASSET_CONTRIBUTION c;
