-- CP-04  L2 ONTOLOGY entities (PRD 5.3, 7.2): one row per key, built from the owning L1 domain (not from facts).
-- Reads ACOCO_L1 and ACOCO_L2.CORE only. "Today" = CORE.VW_AS_OF. TARGET_LAG 1 hour (Semantic Views read these).
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_ACOCO_BUILD;

-- Person: latest job record on or before the as-of date (level, bill code, MD group, manager, tenure).
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.ONTOLOGY.ENT_PERSON
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Entity Person (owner: SAP People Intelligence Core Workforce). Key PERSON_ID. Latest job record <= as-of'
AS
WITH a AS (SELECT AS_OF_DATE FROM ACOCO_L2.CORE.VW_AS_OF),
j AS (
  SELECT w.* FROM ACOCO_L1.WORKFORCE.WORKFORCE_JOB w, a WHERE w.VALID_FROM <= a.AS_OF_DATE
),
latest AS (
  SELECT * FROM j
  QUALIFY ROW_NUMBER() OVER (PARTITION BY PERSON_ID
                             ORDER BY VALID_FROM DESC, VALID_TO DESC, IFF(SOURCE_SYSTEM = 'BDC_CLD', 0, 1)) = 1
),
life AS (
  SELECT PERSON_ID,
         MIN(VALID_FROM)                                  AS FIRST_RECORD_DATE,
         MIN(IFF(IS_HIRE, VALID_FROM, NULL))              AS HIRE_RECORD_DATE,
         MAX(IFF(IS_TERMINATION, VALID_TO, NULL))         AS TERMINATION_DATE,
         MAX(IFF(SOURCE_SYSTEM = 'BDC_CLD', 1, 0)) = 1    AS HAS_CLD_RECORD
  FROM j GROUP BY PERSON_ID
)
SELECT l.PERSON_ID,
       d.DISPLAY_NAME,
       d.FIRST_NAME,
       d.LAST_NAME,
       l.LEVEL,
       lv.LEVEL_SORT,
       l.BILL_CODE,
       l.PAY_GRADE,
       l.PAY_GRADE_IMPUTED,
       l.MD_GROUP_ID,
       l.COST_CENTER_ID,
       l.MANAGER_ID,
       l.GENDER,
       COALESCE(l.TENURE_START, f.HIRE_RECORD_DATE, f.FIRST_RECORD_DATE)          AS HIRE_DATE,
       f.TERMINATION_DATE,
       DATEDIFF(month, COALESCE(l.TENURE_START, f.HIRE_RECORD_DATE, f.FIRST_RECORD_DATE),
                LEAST(COALESCE(f.TERMINATION_DATE, a.AS_OF_DATE), a.AS_OF_DATE))  AS TENURE_MONTHS,
       l.EMPLOYMENT_STATUS = 'A' AND (f.TERMINATION_DATE IS NULL OR f.TERMINATION_DATE >= a.AS_OF_DATE) AS IS_ACTIVE_AS_OF,
       r.MD_GROUP_ID IS NOT NULL                                                  AS IS_MANAGING_DIRECTOR,
       r.MD_GROUP_ID                                                              AS MANAGING_DIRECTOR_OF,
       l.ANNUAL_SALARY,
       l.VALID_FROM                                                               AS JOB_RECORD_FROM,
       l.SOURCE_SYSTEM                                                            AS JOB_RECORD_SOURCE,
       IFF(f.HAS_CLD_RECORD, 'BDC_CLD', 'SIMULATED')                              AS SOURCE_SYSTEM
FROM latest l
JOIN life f ON f.PERSON_ID = l.PERSON_ID
CROSS JOIN a
LEFT JOIN ACOCO_L1.WORKFORCE.PERSON_DIRECTORY d ON d.PERSON_ID = l.PERSON_ID
LEFT JOIN ACOCO_L1.WORKFORCE.MD_ROLE r ON r.PERSON_ID = l.PERSON_ID
LEFT JOIN ACOCO_L1.ORGANISATION.LEVEL lv ON lv.LEVEL = l.LEVEL;

-- Level / bill code band: People Intelligence pay grade bands + S/4 activity type (ML-10x) per level.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.ONTOLOGY.ENT_LEVEL
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Entity Level (owner: People Intelligence payGrade + S/4 activity type). Key LEVEL'
AS
SELECT l.LEVEL, l.LEVEL_SORT, l.BILL_CODE_LO, l.BILL_CODE_HI, l.COST_PER_DAY, l.BILL_RATE_BASE, l.BILL_RATE_STEP,
       l.TARGET_DELIVERY_PCT, l.TARGET_BID_PCT, l.TARGET_LEARNING_PCT, l.TARGET_ADMIN_PCT, l.TARGET_BENCH_PCT,
       t.ACTIVITY_TYPE, t.ACTIVITY_TYPE_NAME,
       l.SOURCE_SYSTEM
FROM ACOCO_L1.ORGANISATION.LEVEL l
LEFT JOIN ACOCO_L1.ORGANISATION.ACTIVITY_TYPE t ON t.LEVEL = l.LEVEL;

CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.ONTOLOGY.ENT_MD_GROUP
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Entity MD group (owner: S/4 cost centre hierarchy). Key MD_GROUP_ID. Managing Director = role held by one Principal'
AS
SELECT g.MD_GROUP_ID, g.MD_GROUP_NAME, g.SORT_ORDER,
       r.PERSON_ID AS MANAGING_DIRECTOR_ID, d.DISPLAY_NAME AS MANAGING_DIRECTOR_NAME, r.VALID_FROM AS MD_SINCE,
       (SELECT COUNT(*) FROM ACOCO_L1.ORGANISATION.COST_CENTER c
         WHERE c.MD_GROUP_ID = g.MD_GROUP_ID AND c.VALID_TO >= (SELECT AS_OF_DATE FROM ACOCO_L2.CORE.VW_AS_OF)) AS COST_CENTERS,
       g.SOURCE_SYSTEM
FROM ACOCO_L1.ORGANISATION.MD_GROUP g
LEFT JOIN ACOCO_L1.WORKFORCE.MD_ROLE r ON r.MD_GROUP_ID = g.MD_GROUP_ID
LEFT JOIN ACOCO_L1.WORKFORCE.PERSON_DIRECTORY d ON d.PERSON_ID = r.PERSON_ID;

