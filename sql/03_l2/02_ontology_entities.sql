FROM ACOCO_L1.SALES.CUSTOMER;

CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.ONTOLOGY.ENT_PROJECT
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Entity Project (owner: S/4 Project). Key PROJECT_ID. STATUS_AS_OF from planned start and latest work-package forecast end'
AS
WITH a AS (SELECT AS_OF_DATE FROM ACOCO_L2.CORE.VW_AS_OF),
wp AS (SELECT PROJECT_ID, MAX(COALESCE(FORECAST_END, PLANNED_END)) AS FORECAST_END, COUNT(*) AS WORK_PACKAGES,
              SUM(PLANNED_HOURS) AS PLANNED_HOURS
       FROM ACOCO_L1.PROJECTS.WBS_ELEMENT GROUP BY PROJECT_ID)
SELECT p.PROJECT_ID, p.PROJECT_NAME, p.OPPORTUNITY_ID, p.CUSTOMER_ID, p.MD_GROUP_ID, p.COMPANY_CODE,
       p.SIZE_CLASS, p.WORK_TYPE, p.CONTRACT_TYPE, p.CONTRACT_TYPE = 'FIXED_PRICE' AS IS_FIXED_PRICE,
       p.CONTRACT_VALUE, p.SOLD_COST, p.CONTRACT_VALUE - p.SOLD_COST AS SOLD_MARGIN,
       IFF(p.CONTRACT_VALUE > 0, (p.CONTRACT_VALUE - p.SOLD_COST) / p.CONTRACT_VALUE, NULL) AS SOLD_MARGIN_PCT,
       p.LD_RATE_PCT_PER_WEEK, p.DELIVERY_MODEL, p.PLANNED_START, p.PLANNED_END, wp.FORECAST_END, p.ACTUAL_END,
       DATEDIFF(week, p.PLANNED_END, wp.FORECAST_END) AS FORECAST_SLIP_WEEKS,
       wp.WORK_PACKAGES, wp.PLANNED_HOURS,
       CASE WHEN p.PLANNED_START > a.AS_OF_DATE THEN 'NOT_STARTED'
            WHEN COALESCE(wp.FORECAST_END, p.PLANNED_END) < a.AS_OF_DATE THEN 'CLOSED'
            ELSE 'ACTIVE' END AS STATUS_AS_OF,
       p.SEEDED_STORY IS NOT NULL AS IS_STORY_PROJECT, p.SEEDED_STORY,
       p.SOURCE_SYSTEM
FROM ACOCO_L1.PROJECTS.PROJECT p
CROSS JOIN a
LEFT JOIN wp ON wp.PROJECT_ID = p.PROJECT_ID;

CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.ONTOLOGY.ENT_WORK_PACKAGE
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Entity Work package (owner: S/4 Project WBS element). Key WBS_ID'
AS
SELECT WBS_ID, PROJECT_ID, WBS_NAME, WORK_TYPE, OWNER_PERSON_ID, PLANNED_HOURS, PLANNED_START, PLANNED_END,
       FORECAST_END, ACTUAL_END, DATEDIFF(week, PLANNED_END, FORECAST_END) AS FORECAST_SLIP_WEEKS, TEAM_PRODUCTIVITY,
       REUSED_ASSET_ID, REUSED_ASSET_ID IS NOT NULL AS REUSES_ASSET, IS_CRITICAL_PATH, SOURCE_SYSTEM
FROM ACOCO_L1.PROJECTS.WBS_ELEMENT;

CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.ONTOLOGY.ENT_OPPORTUNITY
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Entity Opportunity (owner: CRM, non-SAP). Key OPPORTUNITY_ID. STATUS_AS_OF = OPEN / WON / LOST / NOT_CREATED'
AS
WITH a AS (SELECT AS_OF_DATE FROM ACOCO_L2.CORE.VW_AS_OF)
SELECT o.OPPORTUNITY_ID, o.CUSTOMER_ID, o.MD_GROUP_ID, o.SIZE_CLASS, o.WORK_TYPE, o.ESTIMATED_VALUE, o.IS_FIXED_PRICE,
       o.CREATED_DATE, o.EXPECTED_CLOSE_DATE, o.CLOSED_DATE, o.EXPECTED_START_DATE, o.STAGE, o.PROBABILITY_PCT,
       o.OUTCOME, o.REQUIRED_AI_SKILL_LEVEL, o.ORDER_ID, o.PRESALES_HOURS_PLANNED, o.PROJECT_ID,
       CASE WHEN o.CREATED_DATE > a.AS_OF_DATE THEN 'NOT_CREATED'
            WHEN o.CLOSED_DATE IS NOT NULL AND o.CLOSED_DATE <= a.AS_OF_DATE THEN o.OUTCOME
            ELSE 'OPEN' END AS STATUS_AS_OF,
       o.CREATED_DATE <= a.AS_OF_DATE AND (o.CLOSED_DATE IS NULL OR o.CLOSED_DATE > a.AS_OF_DATE) AS IS_OPEN_AS_OF,
       o.SOURCE_SYSTEM
FROM ACOCO_L1.SALES.OPPORTUNITY o CROSS JOIN a;

