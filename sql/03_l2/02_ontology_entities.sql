-- Learning category (curriculum): the pillar each curriculum is meant to move (P6 spec 4.2).
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.ONTOLOGY.ENT_LEARNING_CATEGORY
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Entity Learning category / curriculum (owner: People Intelligence Learning). Key CURRICULUM. Target pillar per P6 spec 4.2'
AS
WITH c AS (
  SELECT CURRICULUM, BOOLOR_AGG(IS_AI_CURRICULUM) AS IS_AI_CURRICULUM, ANY_VALUE(PROVIDER) AS PROVIDER,
         COUNT(*) AS LEARNING_ITEMS, ANY_VALUE(SOURCE_SYSTEM) AS SOURCE_SYSTEM
  FROM ACOCO_L1.TALENT.LEARNING_ITEM GROUP BY CURRICULUM
),
req AS (
  SELECT c.CURRICULUM, LISTAGG(r.LEVEL, ', ') WITHIN GROUP (ORDER BY l.LEVEL_SORT) AS REQUIRED_AT_LEVELS
  FROM c
  JOIN ACOCO_L1.TALENT.LEVEL_REQUIRED_CURRICULUM r
    ON r.CURRICULUM = c.CURRICULUM OR (r.CURRICULUM = 'AI_ANY' AND c.IS_AI_CURRICULUM)
  JOIN ACOCO_L1.ORGANISATION.LEVEL l ON l.LEVEL = r.LEVEL
  GROUP BY c.CURRICULUM
)
SELECT c.CURRICULUM,
       INITCAP(REPLACE(c.CURRICULUM, '_', ' ')) AS CURRICULUM_NAME,
       c.IS_AI_CURRICULUM,
       DECODE(c.CURRICULUM, 'AGENTIC_AI_BUILD', 'OE', 'PROMPT_COPILOT', 'OE', 'CORTEX_DATA', 'OE', 'SAP_FUNCTIONAL', 'PD',
              'PROJECT_MGMT', 'OE', 'COMMERCIAL_BID', 'VC', 'LEADERSHIP', 'TM', 'INDUSTRY', 'VC') AS TARGET_PILLAR,
       DECODE(c.CURRICULUM, 'AGENTIC_AI_BUILD', 'EFF', 'PROMPT_COPILOT', 'EFF', 'CORTEX_DATA', 'EFF', 'SAP_FUNCTIONAL', 'BILL',
              'PROJECT_MGMT', 'SCHED', 'COMMERCIAL_BID', 'WIN', 'LEADERSHIP', 'TEAM', 'INDUSTRY', 'WIN') AS TARGET_INPUT,
       c.PROVIDER, c.LEARNING_ITEMS, req.REQUIRED_AT_LEVELS, c.SOURCE_SYSTEM
FROM c LEFT JOIN req ON req.CURRICULUM = c.CURRICULUM;

CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.ONTOLOGY.ENT_ASSET
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Entity Asset (owner: asset library, non-SAP). Key ASSET_ID. Harvest project from ASSET_HARVEST'
AS
SELECT a.ASSET_ID, a.ASSET_TITLE, a.ASSET_TYPE, a.WORK_TYPE, a.SKILL_TAGS, a.EFFORT_SAVING_HOURS,
       COALESCE(h.HARVEST_DATE, a.HARVESTED_DATE) AS HARVEST_DATE, h.SOURCE_PROJECT_ID, h.HARVESTED_BY_PERSON_ID,
       a.ASSET_STATUS, a.DESCRIPTION, a.SOURCE_SYSTEM
FROM ACOCO_L1.ASSETS.ASSET a
LEFT JOIN ACOCO_L1.ASSETS.ASSET_HARVEST h ON h.ASSET_ID = a.ASSET_ID;

-- AI tool / agent: AI assistants seen in telemetry (non-SAP) + S/4 AGT_* activity types (agents charged to projects).
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.ONTOLOGY.ENT_AI_TOOL
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Entity AI tool / agent (owner: AI telemetry + S/4 AGT_* activity types). Key AI_TOOL_ID'
AS
SELECT u.AI_TOOL_ID,
       DECODE(u.AI_TOOL_ID, 'OPENAI', 'ChatGPT Enterprise', 'ANTHROPIC', 'Claude for Work', 'CORTEX', 'Snowflake Cortex',
              u.AI_TOOL_ID) AS AI_TOOL_NAME,
       'ASSISTANT' AS TOOL_KIND,
       DECODE(u.AI_TOOL_ID, 'OPENAI', 'OpenAI', 'ANTHROPIC', 'Anthropic', 'CORTEX', 'Snowflake', NULL) AS VENDOR,
       NULL::VARCHAR AS ACTIVITY_TYPE, NULL::NUMBER(18,2) AS PLANNED_PRICE_PER_HOUR,
       u.SOURCE_SYSTEM
FROM (SELECT DISTINCT AI_TOOL_ID, SOURCE_SYSTEM FROM ACOCO_L1.AI_TELEMETRY.AI_USAGE_EVENT) u
UNION ALL
SELECT t.ACTIVITY_TYPE, t.ACTIVITY_TYPE_NAME, 'AGENT', 'ACoCo', t.ACTIVITY_TYPE, t.PLANNED_PRICE, t.SOURCE_SYSTEM
FROM ACOCO_L1.ORGANISATION.ACTIVITY_TYPE t
WHERE t.IS_AI_AGENT;

-- AI model (P6 spec 4.1): model served through each product, with the simulated list price.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.ONTOLOGY.ENT_AI_MODEL
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Entity AI model (owner: AI telemetry + model price list). Key AI_TOOL_ID, MODEL. Same model family can be served by a vendor tool and by Cortex'
AS
SELECT m.AI_TOOL_ID, m.PRODUCT,
       DECODE(m.PRODUCT, 'CLAUDE_CODE', 'Claude Code', 'CODEX', 'Codex', 'CORTEX', 'Cortex Code / AISQL', m.PRODUCT) AS PRODUCT_NAME,
       m.MODEL, m.MODEL_FAMILY, m.INPUT_USD_PER_MTOK, m.OUTPUT_USD_PER_MTOK,
       m.AI_TOOL_ID || '|' || m.MODEL AS AI_MODEL_ID,
       m.SOURCE_SYSTEM
FROM ACOCO_L1.AI_TELEMETRY.AI_MODEL m;

CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.ONTOLOGY.ENT_TIME_CATEGORY
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Entity Time category (owner: timesheet attendance type). Key TIME_CATEGORY. Bench = available minus booked'
AS
SELECT TIME_CATEGORY,
       DECODE(TIME_CATEGORY, 'DELIVERY', 1, 'BID', 2, 'LEARNING', 3, 'ADMIN', 4, 'BENCH', 5) AS SORT_ORDER,
       INITCAP(TIME_CATEGORY) AS TIME_CATEGORY_NAME,
       DECODE(TIME_CATEGORY,
              'DELIVERY', 'Billable client work; the largest share at every level',
              'BID',      'Pre-sales pursuit time; judged on win-rate',
              'LEARNING', 'Skill building; judged on shortening future delivery',
              'ADMIN',    'Internal administration; kept below 5 %',
              'BENCH',    'Available but unbooked; kept near zero') AS OBJECTIVE,
       TIME_CATEGORY <> 'BENCH' AS IS_BOOKED_CATEGORY,
       MIN(TARGET_PCT) AS TARGET_PCT_MIN, MAX(TARGET_PCT) AS TARGET_PCT_MAX,
       'ACOCO_CONFIG' AS SOURCE_SYSTEM
FROM ACOCO_L2.CORE.DT_TIME_TARGET
GROUP BY TIME_CATEGORY;
