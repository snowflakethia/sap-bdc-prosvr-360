-- CP-05  Mart PORTFOLIO_360 (PRD 7.2): the MD's one-page view, built from the other marts + CORE.
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_ACOCO_BUILD;
CREATE SCHEMA IF NOT EXISTS ACOCO_L2.PORTFOLIO_360 COMMENT = 'Mart: MD-group P&L, capacity mix, cross-pillar risk register';

-- MD group x level x month x time category: hours and share of available hours vs target (long form for charts).
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.PORTFOLIO_360.DT_CAPACITY_MIX_MONTH
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'MD group x level x month: available hours and Delivery / Bid / Learning / Admin / Bench hours (shares sum to 100 % of available)'
AS
SELECT MD_GROUP_ID, LEVEL, LEVEL_SORT, MONTH_START, FISCAL_YEAR, FISCAL_PERIOD,
       COUNT(DISTINCT PERSON_ID) AS PEOPLE,
       SUM(AVAILABLE_HOURS) AS AVAILABLE_HOURS,
       SUM(DELIVERY_HOURS) AS DELIVERY_HOURS, SUM(BID_HOURS) AS BID_HOURS, SUM(LEARNING_HOURS) AS LEARNING_HOURS,
       SUM(ADMIN_HOURS) AS ADMIN_HOURS, SUM(BENCH_HOURS) AS BENCH_HOURS, SUM(OVERBOOKED_HOURS) AS OVERBOOKED_HOURS,
       SUM(EXCESS_BENCH_HOURS) AS EXCESS_BENCH_HOURS, SUM(BENCH_COST) AS BENCH_COST,
       ANY_VALUE(TARGET_DELIVERY_PCT) AS TARGET_DELIVERY_PCT, ANY_VALUE(TARGET_BID_PCT) AS TARGET_BID_PCT,
       ANY_VALUE(TARGET_LEARNING_PCT) AS TARGET_LEARNING_PCT, ANY_VALUE(TARGET_ADMIN_PCT) AS TARGET_ADMIN_PCT,
       ANY_VALUE(TARGET_BENCH_PCT) AS TARGET_BENCH_PCT
FROM ACOCO_L2.WORKFORCE_PERFORMANCE.DT_PERSON_MONTH_SCORECARD
GROUP BY MD_GROUP_ID, LEVEL, LEVEL_SORT, MONTH_START, FISCAL_YEAR, FISCAL_PERIOD;

-- MD group x month: P&L, capacity, pipeline and AI in one row.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.PORTFOLIO_360.DT_PORTFOLIO_MONTH
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'MD group x month: revenue, cost, margin, billability, bench, headcount, attrition inputs, win-rate inputs, AI cost'
AS
WITH fin AS (
  SELECT MD_GROUP_ID, MONTH_START, SUM(REVENUE) AS REVENUE, SUM(PEOPLE_COST) AS PEOPLE_COST, SUM(AGENT_COST) AS AGENT_COST,
         SUM(OVERHEAD_COST) AS OVERHEAD_COST, SUM(TOTAL_COST) AS TOTAL_COST, SUM(MARGIN) AS MARGIN,
         SUM(IFF(SIZE_CLASS = 'Large', REVENUE, 0)) AS LARGE_PROJECT_REVENUE
  FROM ACOCO_L2.PROJECT_DELIVERY.DT_PROJECT_MONTH_FINANCIALS GROUP BY 1, 2
),
cap AS (
  SELECT MD_GROUP_ID, MONTH_START, SUM(AVAILABLE_HOURS) AS AVAILABLE_HOURS, SUM(DELIVERY_HOURS) AS DELIVERY_HOURS,
         SUM(BID_HOURS) AS BID_HOURS, SUM(LEARNING_HOURS) AS LEARNING_HOURS, SUM(ADMIN_HOURS) AS ADMIN_HOURS,
         SUM(BENCH_HOURS) AS BENCH_HOURS, SUM(BENCH_COST) AS BENCH_COST
  FROM ACOCO_L2.PORTFOLIO_360.DT_CAPACITY_MIX_MONTH GROUP BY 1, 2
),
hc AS (
  SELECT MD_GROUP_ID, MONTH_START, SUM(OPENING_HEADCOUNT) AS OPENING_HEADCOUNT, SUM(CLOSING_HEADCOUNT) AS CLOSING_HEADCOUNT,
         SUM(HIRES) AS HIRES, SUM(VOLUNTARY_LEAVERS) AS VOLUNTARY_LEAVERS
  FROM ACOCO_L2.WORKFORCE_PERFORMANCE.DT_HEADCOUNT_MONTH GROUP BY 1, 2
),
ai AS (SELECT MD_GROUP_ID, MONTH_START, SUM(AGENT_COST + ASSISTANT_COST) AS AI_COST FROM ACOCO_L2.AI_ADOPTION.DT_AI_COST_MONTH GROUP BY 1, 2)
SELECT pm.MD_GROUP_ID, pm.MONTH_START, pm.FISCAL_YEAR, pm.FISCAL_PERIOD,
       COALESCE(fin.REVENUE, 0) AS REVENUE, COALESCE(fin.PEOPLE_COST, 0) AS PEOPLE_COST, COALESCE(fin.AGENT_COST, 0) AS AGENT_COST,
       COALESCE(fin.OVERHEAD_COST, 0) AS OVERHEAD_COST, COALESCE(fin.TOTAL_COST, 0) AS TOTAL_COST, COALESCE(fin.MARGIN, 0) AS MARGIN,
       COALESCE(fin.LARGE_PROJECT_REVENUE, 0) AS LARGE_PROJECT_REVENUE,
       COALESCE(cap.AVAILABLE_HOURS, 0) AS AVAILABLE_HOURS, COALESCE(cap.DELIVERY_HOURS, 0) AS DELIVERY_HOURS,
       COALESCE(cap.BID_HOURS, 0) AS BID_HOURS, COALESCE(cap.LEARNING_HOURS, 0) AS LEARNING_HOURS,
       COALESCE(cap.ADMIN_HOURS, 0) AS ADMIN_HOURS, COALESCE(cap.BENCH_HOURS, 0) AS BENCH_HOURS, COALESCE(cap.BENCH_COST, 0) AS BENCH_COST,
       COALESCE(hc.OPENING_HEADCOUNT, 0) AS OPENING_HEADCOUNT, COALESCE(hc.CLOSING_HEADCOUNT, 0) AS CLOSING_HEADCOUNT,
       COALESCE(hc.HIRES, 0) AS HIRES, COALESCE(hc.VOLUNTARY_LEAVERS, 0) AS VOLUNTARY_LEAVERS,
       pm.WON, pm.LOST, pm.WON_VALUE, pm.PURSUIT_COST_DECIDED, pm.OPPORTUNITIES_CREATED,
       COALESCE(ai.AI_COST, 0) AS AI_COST
FROM ACOCO_L2.PIPELINE_PRESALES.DT_PRESALES_MONTH pm
LEFT JOIN fin ON fin.MD_GROUP_ID = pm.MD_GROUP_ID AND fin.MONTH_START = pm.MONTH_START
LEFT JOIN cap ON cap.MD_GROUP_ID = pm.MD_GROUP_ID AND cap.MONTH_START = pm.MONTH_START
LEFT JOIN hc  ON hc.MD_GROUP_ID  = pm.MD_GROUP_ID AND hc.MONTH_START  = pm.MONTH_START
LEFT JOIN ai  ON ai.MD_GROUP_ID  = pm.MD_GROUP_ID AND ai.MONTH_START  = pm.MONTH_START;

-- Cross-pillar risk register as of the as-of date: one row per risk item, ranked by money at stake.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.PORTFOLIO_360.DT_RISK_REGISTER
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Risk items: loss-making projects (Operational), roll-off without successor (People), open bids with low skill fit (Value). USD at stake ranks them'
AS
WITH r AS (
  SELECT 'OPERATIONAL' AS PILLAR, 'PROJECT_FORECAST_LOSS' AS RISK_TYPE, MD_GROUP_ID, PROJECT_ID AS OBJECT_ID, 'PROJECT' AS OBJECT_ENTITY,
         'Forecast margin ' || TO_CHAR(ROUND(100 * FORECAST_MARGIN_PCT, 1)) || ' %, CPI ' || TO_CHAR(ROUND(CPI, 2)) AS DETAIL,
         -FORECAST_MARGIN_PCT * CONTRACT_VALUE AS USD_AT_STAKE
  FROM ACOCO_L2.PROJECT_DELIVERY.DT_PROJECT_HEALTH WHERE STATUS_AS_OF = 'ACTIVE' AND FORECAST_MARGIN_PCT < 0
  UNION ALL
  SELECT 'PEOPLE', 'ROLL_OFF_NO_SUCCESSOR', MD_GROUP_ID, PERSON_ID, 'PERSON',
         LEVEL || ' rolls off ' || ROLL_OFF_DATE::VARCHAR || IFF(BELOW_PIPELINE_AI_LEVEL, ', below pipeline AI level', ''),
         GREATEST(90 - DAYS_TO_ROLL_OFF, 0) * 5 / 7 * l.COST_PER_DAY   -- unbooked working days left in the 90-day window
  FROM ACOCO_L2.WORKFORCE_PERFORMANCE.DT_ROLL_OFF ro JOIN ACOCO_L2.ONTOLOGY.ENT_LEVEL l USING (LEVEL)
  UNION ALL
  SELECT 'VALUE', 'OPEN_BID_LOW_SKILL_FIT', MD_GROUP_ID, OPPORTUNITY_ID, 'OPPORTUNITY',
         'Skill fit ' || TO_CHAR(ROUND(SKILL_FIT, 2)) || ' on ' || SIZE_CLASS || ' bid',
         ESTIMATED_VALUE * (1 - COALESCE(SKILL_FIT, 0)) * 0.25
  FROM ACOCO_L2.PIPELINE_PRESALES.DT_OPPORTUNITY_FACT WHERE IS_OPEN_AS_OF AND COALESCE(SKILL_FIT, 0) < 0.5
)
SELECT r.*, ROW_NUMBER() OVER (PARTITION BY MD_GROUP_ID ORDER BY USD_AT_STAKE DESC) AS RANK_IN_GROUP,
       MD5(RISK_TYPE || '|' || OBJECT_ID) AS RISK_ID
FROM r;

-- MD group x level x month x time category (long form of the capacity mix) for the overlay chart.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.PORTFOLIO_360.DT_CAPACITY_MIX_LONG
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'MD group x level x month x time category: hours, available hours and level target %'
AS
SELECT m.MD_GROUP_ID, m.LEVEL, m.MONTH_START, m.FISCAL_YEAR, c.TIME_CATEGORY,
       DECODE(c.TIME_CATEGORY, 'DELIVERY', m.DELIVERY_HOURS, 'BID', m.BID_HOURS, 'LEARNING', m.LEARNING_HOURS,
              'ADMIN', m.ADMIN_HOURS, 'BENCH', m.BENCH_HOURS) AS HOURS,
       m.AVAILABLE_HOURS,
       DECODE(c.TIME_CATEGORY, 'DELIVERY', m.TARGET_DELIVERY_PCT, 'BID', m.TARGET_BID_PCT, 'LEARNING', m.TARGET_LEARNING_PCT,
              'ADMIN', m.TARGET_ADMIN_PCT, 'BENCH', m.TARGET_BENCH_PCT) AS TARGET_PCT
FROM ACOCO_L2.PORTFOLIO_360.DT_CAPACITY_MIX_MONTH m
CROSS JOIN ACOCO_L2.ONTOLOGY.ENT_TIME_CATEGORY c;
