-- CP-05  SERVING: the app interface (PRD 7.2, 8.4). Plain views over L2 only; the app never reads marts directly.
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_ACOCO_BUILD;
CREATE SCHEMA IF NOT EXISTS ACOCO_L2.SERVING COMMENT = 'App interface: views over L2 marts and ontology only';

-- Time mix by MD group x level x fiscal year: five shares of available hours (sum 100) vs targets (overlay figure).
CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_TIME_MIX_FY
  COMMENT = 'MD group x level x fiscal year: Delivery / Bid / Learning / Admin / Bench % of available hours (sum 100) and level targets'
AS
SELECT c.MD_GROUP_ID, g.MD_GROUP_NAME AS MD_GROUP, c.LEVEL, c.LEVEL_SORT, c.FISCAL_YEAR,
       MAX(c.PEOPLE) AS PEOPLE_MAX_MONTH,
       SUM(c.AVAILABLE_HOURS) AS AVAILABLE_HOURS,
       ROUND(100 * SUM(c.DELIVERY_HOURS) / NULLIF(SUM(c.AVAILABLE_HOURS), 0), 1) AS DELIVERY_PCT,
       ROUND(100 * SUM(c.BID_HOURS)      / NULLIF(SUM(c.AVAILABLE_HOURS), 0), 1) AS BID_PCT,
       ROUND(100 * SUM(c.LEARNING_HOURS) / NULLIF(SUM(c.AVAILABLE_HOURS), 0), 1) AS LEARNING_PCT,
       ROUND(100 * SUM(c.ADMIN_HOURS)    / NULLIF(SUM(c.AVAILABLE_HOURS), 0), 1) AS ADMIN_PCT,
       ROUND(100 * (SUM(c.AVAILABLE_HOURS) - SUM(c.DELIVERY_HOURS) - SUM(c.BID_HOURS) - SUM(c.LEARNING_HOURS) - SUM(c.ADMIN_HOURS))
             / NULLIF(SUM(c.AVAILABLE_HOURS), 0), 1) AS BENCH_PCT,
       ROUND(SUM(c.BENCH_COST), 0) AS BENCH_COST,
       ANY_VALUE(c.TARGET_DELIVERY_PCT) AS DELIVERY_TARGET_PCT, ANY_VALUE(c.TARGET_BID_PCT) AS BID_TARGET_PCT,
       ANY_VALUE(c.TARGET_LEARNING_PCT) AS LEARNING_TARGET_PCT, ANY_VALUE(c.TARGET_ADMIN_PCT) AS ADMIN_TARGET_PCT,
       ANY_VALUE(c.TARGET_BENCH_PCT) AS BENCH_TARGET_PCT
FROM ACOCO_L2.PORTFOLIO_360.DT_CAPACITY_MIX_MONTH c
JOIN ACOCO_L2.ONTOLOGY.ENT_MD_GROUP g ON g.MD_GROUP_ID = c.MD_GROUP_ID
GROUP BY c.MD_GROUP_ID, g.MD_GROUP_NAME, c.LEVEL, c.LEVEL_SORT, c.FISCAL_YEAR;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_PORTFOLIO_FY
  COMMENT = 'MD group x fiscal year: revenue, margin, billability, bench, attrition, win-rate, AI cost'
AS
SELECT p.MD_GROUP_ID, g.MD_GROUP_NAME AS MD_GROUP, p.FISCAL_YEAR,
       SUM(p.REVENUE) AS REVENUE, SUM(p.TOTAL_COST) AS TOTAL_COST, SUM(p.MARGIN) AS MARGIN,
       SUM(p.MARGIN) / NULLIF(SUM(p.REVENUE), 0) AS MARGIN_PCT,
       SUM(p.LARGE_PROJECT_REVENUE) / NULLIF(SUM(p.REVENUE), 0) AS LARGE_PROJECT_REVENUE_SHARE,
       SUM(p.DELIVERY_HOURS) / NULLIF(SUM(p.AVAILABLE_HOURS), 0) AS BILLABILITY,
       SUM(p.BENCH_HOURS) / NULLIF(SUM(p.AVAILABLE_HOURS), 0) AS BENCH_SHARE,
       SUM(p.BENCH_COST) AS BENCH_COST,
       SUM(p.VOLUNTARY_LEAVERS) / NULLIF(AVG(p.CLOSING_HEADCOUNT), 0) AS VOLUNTARY_ATTRITION,
       MAX_BY(p.CLOSING_HEADCOUNT, p.MONTH_START) AS CLOSING_HEADCOUNT,
       SUM(p.WON) AS WON, SUM(p.LOST) AS LOST, SUM(p.WON) / NULLIF(SUM(p.WON) + SUM(p.LOST), 0) AS WIN_RATE,
       SUM(p.WON_VALUE) AS WON_VALUE, SUM(p.PURSUIT_COST_DECIDED) / NULLIF(SUM(p.WON_VALUE), 0) AS PURSUIT_COST_PER_WON_USD,
       SUM(p.AI_COST) AS AI_COST
FROM ACOCO_L2.PORTFOLIO_360.DT_PORTFOLIO_MONTH p
JOIN ACOCO_L2.ONTOLOGY.ENT_MD_GROUP g ON g.MD_GROUP_ID = p.MD_GROUP_ID
GROUP BY p.MD_GROUP_ID, g.MD_GROUP_NAME, p.FISCAL_YEAR;

-- FY27 pacing: closed FY26 run-rate vs FY27 months elapsed (as-of = FY27 day 1, so pacing starts at zero).
CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_PORTFOLIO_PACING
  COMMENT = 'MD group: last closed fiscal year totals and the current fiscal year to date (as-of date)'
AS
SELECT f.MD_GROUP_ID, f.MD_GROUP, a.CURRENT_FISCAL_YEAR, a.LAST_CLOSED_FISCAL_YEAR,
       f.REVENUE AS LAST_FY_REVENUE, f.MARGIN_PCT AS LAST_FY_MARGIN_PCT, f.BILLABILITY AS LAST_FY_BILLABILITY,
       f.WIN_RATE AS LAST_FY_WIN_RATE,
       COALESCE(c.REVENUE, 0) AS CURRENT_FY_REVENUE_TD
FROM ACOCO_L2.SERVING.VW_PORTFOLIO_FY f
CROSS JOIN ACOCO_L2.CORE.VW_AS_OF a
LEFT JOIN ACOCO_L2.SERVING.VW_PORTFOLIO_FY c ON c.MD_GROUP_ID = f.MD_GROUP_ID AND c.FISCAL_YEAR = a.CURRENT_FISCAL_YEAR
WHERE f.FISCAL_YEAR = a.LAST_CLOSED_FISCAL_YEAR;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_PROJECT_HEALTH_NOW
  COMMENT = 'Active projects as of the as-of date with CPI, SPI, EAC, LD exposure, forecast margin, reuse'
AS
SELECT h.*, c.CUSTOMER_NAME, g.MD_GROUP_NAME AS MD_GROUP
FROM ACOCO_L2.PROJECT_DELIVERY.DT_PROJECT_HEALTH h
LEFT JOIN ACOCO_L2.ONTOLOGY.ENT_CUSTOMER c ON c.CUSTOMER_ID = h.CUSTOMER_ID
JOIN ACOCO_L2.ONTOLOGY.ENT_MD_GROUP g ON g.MD_GROUP_ID = h.MD_GROUP_ID
WHERE h.STATUS_AS_OF = 'ACTIVE';

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_ROLL_OFF_90D
  COMMENT = 'People rolling off in the next 90 days with no later assignment; AI-skill level vs pipeline need'
AS
SELECT r.*, g.MD_GROUP_NAME AS MD_GROUP
FROM ACOCO_L2.WORKFORCE_PERFORMANCE.DT_ROLL_OFF r
JOIN ACOCO_L2.ONTOLOGY.ENT_MD_GROUP g ON g.MD_GROUP_ID = r.MD_GROUP_ID;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_PERSON_LAST_CLOSED_MONTH
  COMMENT = 'Active people: last closed month time mix, productivity, AI-skill level and roll-off date'
AS
SELECT p.PERSON_ID, p.DISPLAY_NAME, p.MD_GROUP_ID, p.LEVEL, p.LEVEL_SORT, p.BILL_CODE, p.TENURE_MONTHS, p.SOURCE_SYSTEM,
       s.MONTH_START, s.AVAILABLE_HOURS, s.DELIVERY_HOURS, s.BID_HOURS, s.LEARNING_HOURS, s.ADMIN_HOURS, s.BENCH_HOURS,
       s.DELIVERY_HOURS / NULLIF(s.AVAILABLE_HOURS, 0) AS BILLABILITY, s.PRODUCTIVITY_INDEX,
       r.ROLL_OFF_DATE, r.AI_SKILL_LEVEL
FROM ACOCO_L2.ONTOLOGY.ENT_PERSON p
CROSS JOIN ACOCO_L2.CORE.VW_AS_OF a
LEFT JOIN ACOCO_L2.WORKFORCE_PERFORMANCE.DT_PERSON_MONTH_SCORECARD s
  ON s.PERSON_ID = p.PERSON_ID AND s.MONTH_START = a.LAST_CLOSED_MONTH_START
LEFT JOIN ACOCO_L2.WORKFORCE_PERFORMANCE.DT_ROLL_OFF r ON r.PERSON_ID = p.PERSON_ID
WHERE p.IS_ACTIVE_AS_OF;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_RISK_REGISTER
  COMMENT = 'Cross-pillar risk items ranked within MD group by USD at stake'
AS
SELECT r.*, g.MD_GROUP_NAME AS MD_GROUP
FROM ACOCO_L2.PORTFOLIO_360.DT_RISK_REGISTER r
JOIN ACOCO_L2.ONTOLOGY.ENT_MD_GROUP g ON g.MD_GROUP_ID = r.MD_GROUP_ID;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_PIPELINE_OPEN
  COMMENT = 'Open opportunities as of the as-of date: value, probability, pursuit cost so far, team skill fit'
AS
SELECT o.*, c.CUSTOMER_NAME, g.MD_GROUP_NAME AS MD_GROUP
FROM ACOCO_L2.PIPELINE_PRESALES.DT_OPPORTUNITY_FACT o
LEFT JOIN ACOCO_L2.ONTOLOGY.ENT_CUSTOMER c ON c.CUSTOMER_ID = o.CUSTOMER_ID
JOIN ACOCO_L2.ONTOLOGY.ENT_MD_GROUP g ON g.MD_GROUP_ID = o.MD_GROUP_ID
WHERE o.IS_OPEN_AS_OF;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_AI_ADOPTION_FY
  COMMENT = 'MD group x fiscal year: AI-active share, productivity AI-active vs rest (unstratified headline), AI cost'
AS
SELECT d.MD_GROUP_ID, g.MD_GROUP_NAME AS MD_GROUP, d.FISCAL_YEAR,
       COUNT(DISTINCT d.PERSON_ID) AS DELIVERY_PEOPLE,
       COUNT(DISTINCT IFF(d.AI_ACTIVE, d.PERSON_ID, NULL)) AS AI_ACTIVE_PEOPLE,
       COUNT(DISTINCT IFF(d.AI_SKILLED_INACTIVE, d.PERSON_ID, NULL)) AS AI_SKILLED_INACTIVE_PEOPLE,
       SUM(IFF(d.AI_ACTIVE, d.EARNED_HOURS, 0)) / NULLIF(SUM(IFF(d.AI_ACTIVE, d.DELIVERY_HOURS, 0)), 0) AS PI_AI_ACTIVE,
       SUM(IFF(NOT d.AI_ACTIVE, d.EARNED_HOURS, 0)) / NULLIF(SUM(IFF(NOT d.AI_ACTIVE, d.DELIVERY_HOURS, 0)), 0) AS PI_REST,
       SUM(d.AI_COST_USD) AS ASSISTANT_COST_USD
FROM ACOCO_L2.AI_ADOPTION.DT_AI_PRODUCTIVITY d
JOIN ACOCO_L2.ONTOLOGY.ENT_MD_GROUP g ON g.MD_GROUP_ID = d.MD_GROUP_ID
GROUP BY d.MD_GROUP_ID, g.MD_GROUP_NAME, d.FISCAL_YEAR;
