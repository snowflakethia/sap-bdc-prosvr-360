-- P6  Workforce Productivity Score (WPS) and its exposure marts (spec docs/spec_p6_productivity.md v0.4, 2.1-2.6).
-- Grain person x fiscal quarter (V9), closed quarters only. Reads ACOCO_L1 + ACOCO_L2 ONTOLOGY / CORE / marts 10-12.
-- Level = the person's level at the as-of date (same convention as DT_PERSON_MONTH_SCORECARD).
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_ACOCO_BUILD;

-- Person x quarter x product x model family: tokens (Q3 / Q4 exposure), cost and active days.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.AI_ADOPTION.DT_AI_TOKENS_PERSON_QUARTER
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Person x fiscal quarter x AI product x model family: tokens (input / output), cost, active days; delivery hours for tokens per delivery hour'
AS
WITH a AS (SELECT AS_OF_DATE FROM ACOCO_L2.CORE.VW_AS_OF),
u AS (
  SELECT e.PERSON_ID, f.FISCAL_YEAR, f.FISCAL_QUARTER, e.AI_TOOL_ID, e.PRODUCT, COALESCE(m.MODEL_FAMILY, 'UNKNOWN') AS MODEL_FAMILY,
         SUM(e.TOKENS) AS TOKENS, SUM(e.INPUT_TOKENS) AS INPUT_TOKENS, SUM(e.OUTPUT_TOKENS) AS OUTPUT_TOKENS,
         SUM(e.SESSIONS) AS SESSIONS, SUM(e.COST_USD) AS COST_USD, COUNT(DISTINCT e.USAGE_DATE) AS ACTIVE_DAYS
  FROM ACOCO_L1.AI_TELEMETRY.AI_USAGE_EVENT e
  JOIN ACOCO_L2.CORE.DT_FISCAL_MONTH f ON f.MONTH_START = DATE_TRUNC(month, e.USAGE_DATE)
  LEFT JOIN ACOCO_L2.ONTOLOGY.ENT_AI_MODEL m ON m.AI_TOOL_ID = e.AI_TOOL_ID AND m.MODEL = e.MODEL
  CROSS JOIN a
  WHERE e.PERSON_ID IS NOT NULL AND e.USAGE_DATE < DATE_TRUNC(month, a.AS_OF_DATE)
  GROUP BY 1, 2, 3, 4, 5, 6
),
d AS (
  SELECT PERSON_ID, FISCAL_YEAR, CEIL(FISCAL_PERIOD / 3) AS FISCAL_QUARTER, SUM(DELIVERY_HOURS) AS DELIVERY_HOURS
  FROM ACOCO_L2.WORKFORCE_PERFORMANCE.DT_PERSON_MONTH_SCORECARD GROUP BY 1, 2, 3
)
SELECT u.PERSON_ID, u.FISCAL_YEAR, u.FISCAL_QUARTER, p.LEVEL, p.LEVEL_SORT, p.MD_GROUP_ID,
       u.AI_TOOL_ID, u.PRODUCT, u.MODEL_FAMILY, u.TOKENS, u.INPUT_TOKENS, u.OUTPUT_TOKENS, u.SESSIONS, u.COST_USD, u.ACTIVE_DAYS,
       d.DELIVERY_HOURS,
       IFF(d.DELIVERY_HOURS > 0, u.TOKENS / d.DELIVERY_HOURS, NULL) AS TOKENS_PER_DELIVERY_HOUR,
       u.PERSON_ID || '|' || u.FISCAL_YEAR || 'Q' || u.FISCAL_QUARTER || '|' || u.PRODUCT || '|' || u.MODEL_FAMILY AS ROW_ID
FROM u
JOIN ACOCO_L2.ONTOLOGY.ENT_PERSON p ON p.PERSON_ID = u.PERSON_ID
LEFT JOIN d ON d.PERSON_ID = u.PERSON_ID AND d.FISCAL_YEAR = u.FISCAL_YEAR AND d.FISCAL_QUARTER = u.FISCAL_QUARTER;

-- Person x quarter x curriculum: learning hours, completions, assessment score (Q5 / Q6 exposure).
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.WORKFORCE_PERFORMANCE.DT_LEARNING_PERSON_QUARTER
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Person x fiscal quarter x curriculum: learning hours, completions, mean assessment score, whether required at the person level'
AS
WITH a AS (SELECT AS_OF_DATE FROM ACOCO_L2.CORE.VW_AS_OF),
c AS (
  SELECT lc.PERSON_ID, f.FISCAL_YEAR, f.FISCAL_QUARTER, li.CURRICULUM, li.IS_AI_CURRICULUM,
         SUM(lc.LEARNING_HOURS) AS LEARNING_HOURS, COUNT(*) AS COMPLETIONS, AVG(lc.ASSESSMENT_SCORE) AS AVG_ASSESSMENT_SCORE
  FROM ACOCO_L1.TALENT.LEARNING_COMPLETION lc
  JOIN ACOCO_L1.TALENT.LEARNING_ITEM li ON li.LEARNING_ITEM_ID = lc.LEARNING_ITEM_ID
  JOIN ACOCO_L2.CORE.DT_FISCAL_MONTH f ON f.MONTH_START = DATE_TRUNC(month, lc.COMPLETION_DATE)
  CROSS JOIN a
  WHERE lc.COMPLETION_STATUS = 'COMPLETED' AND lc.COMPLETION_DATE < DATE_TRUNC(month, a.AS_OF_DATE)
  GROUP BY 1, 2, 3, 4, 5
)
SELECT c.PERSON_ID, c.FISCAL_YEAR, c.FISCAL_QUARTER, p.LEVEL, p.LEVEL_SORT, p.MD_GROUP_ID,
       c.CURRICULUM, c.IS_AI_CURRICULUM, k.TARGET_PILLAR, k.TARGET_INPUT,
       c.LEARNING_HOURS, c.COMPLETIONS, c.AVG_ASSESSMENT_SCORE,
       EXISTS (SELECT 1 FROM ACOCO_L1.TALENT.LEVEL_REQUIRED_CURRICULUM r
                WHERE r.LEVEL = p.LEVEL AND (r.CURRICULUM = c.CURRICULUM OR (r.CURRICULUM = 'AI_ANY' AND c.IS_AI_CURRICULUM)))
         AS IS_REQUIRED_AT_LEVEL,
       c.PERSON_ID || '|' || c.FISCAL_YEAR || 'Q' || c.FISCAL_QUARTER || '|' || c.CURRICULUM AS ROW_ID
FROM c
JOIN ACOCO_L2.ONTOLOGY.ENT_PERSON p ON p.PERSON_ID = c.PERSON_ID
LEFT JOIN ACOCO_L2.ONTOLOGY.ENT_LEARNING_CATEGORY k ON k.CURRICULUM = c.CURRICULUM;

-- Workforce Productivity Score: raw inputs -> scores within level x fiscal year (50 = level average) -> pillars -> WPS.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.WORKFORCE_PERFORMANCE.DT_PERSON_QUARTER_WPS
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Person x fiscal quarter: WPS inputs (WIN, EFF, SCHED, BILL, UTIL, LEARN, ACREATE, AREUSE, TEAM), scores 0-100 within level x FY, pillars VC / OE / PD / TM, WPS, WPS_EX_LEARN. Population: >= 80 available hours'
AS
WITH a AS (SELECT AS_OF_DATE FROM ACOCO_L2.CORE.VW_AS_OF),
q AS (
  SELECT FISCAL_YEAR, FISCAL_QUARTER, FISCAL_YEAR * 4 + FISCAL_QUARTER AS QIDX,
         MIN(MONTH_START) AS Q_START, MAX(MONTH_END) AS Q_END
  FROM ACOCO_L2.CORE.DT_FISCAL_MONTH GROUP BY 1, 2
),
mq AS (SELECT f.MONTH_START, q.* FROM ACOCO_L2.CORE.DT_FISCAL_MONTH f
       JOIN q ON q.FISCAL_YEAR = f.FISCAL_YEAR AND q.FISCAL_QUARTER = f.FISCAL_QUARTER),
pq AS (   -- person x quarter hours (scorecard = closed months)
  SELECT s.PERSON_ID, mq.FISCAL_YEAR, mq.FISCAL_QUARTER, mq.QIDX, mq.Q_START, mq.Q_END,
         ANY_VALUE(s.LEVEL) AS LEVEL, ANY_VALUE(s.LEVEL_SORT) AS LEVEL_SORT, ANY_VALUE(s.MD_GROUP_ID) AS MD_GROUP_ID,
         SUM(s.AVAILABLE_HOURS) AS AVAILABLE_HOURS, SUM(s.DELIVERY_HOURS) AS DELIVERY_HOURS, SUM(s.BID_HOURS) AS BID_HOURS,
         SUM(s.LEARNING_HOURS) AS LEARNING_HOURS, SUM(s.EARNED_HOURS) AS EARNED_HOURS,
         SUM(s.ASSET_CONTRIBUTION_HOURS) AS ASSET_CONTRIBUTION_HOURS,
         ANY_VALUE(s.TARGET_DELIVERY_PCT) / 100 AS BILL_TARGET,
         (ANY_VALUE(s.TARGET_DELIVERY_PCT) + ANY_VALUE(s.TARGET_BID_PCT)) / 100 AS UTIL_TARGET,
         ANY_VALUE(s.TARGET_LEARNING_PCT) / 100 AS LEARN_TARGET,
         COUNT(*) AS MONTHS
  FROM ACOCO_L2.WORKFORCE_PERFORMANCE.DT_PERSON_MONTH_SCORECARD s
  JOIN mq ON mq.MONTH_START = s.MONTH_START
  CROSS JOIN a
  WHERE mq.Q_END < a.AS_OF_DATE
  GROUP BY 1, 2, 3, 4, 5, 6
),
t4 AS (   -- trailing 4 quarters (this quarter and the 3 before) per person-quarter
  SELECT p.PERSON_ID, p.QIDX, SUM(x.AVAILABLE_HOURS) AS AVAILABLE_T4Q, SUM(x.LEARNING_HOURS) AS LEARNING_T4Q,
         SUM(x.DELIVERY_HOURS) AS DELIVERY_T4Q
  FROM pq p JOIN pq x ON x.PERSON_ID = p.PERSON_ID AND x.QIDX BETWEEN p.QIDX - 3 AND p.QIDX
  GROUP BY 1, 2
),
-- SCHED: hours-weighted schedule score of the work packages worked in the quarter
wp AS (
  SELECT WBS_ID, GREATEST(DATEDIFF(week, PLANNED_START, PLANNED_END), 1) AS PLAN_WKS,
         DATEDIFF(week, PLANNED_END, COALESCE(ACTUAL_END, FORECAST_END, PLANNED_END)) AS SLIP_WKS
  FROM ACOCO_L2.ONTOLOGY.ENT_WORK_PACKAGE
),
sched AS (
  SELECT t.PERSON_ID, mq.QIDX,
         SUM(t.HOURS * CASE WHEN w.SLIP_WKS < 0 THEN 1 + LEAST(-w.SLIP_WKS / w.PLAN_WKS, 0.2)
                            WHEN w.SLIP_WKS = 0 THEN 1
                            ELSE GREATEST(0, 1 - w.SLIP_WKS / w.PLAN_WKS) END) / NULLIF(SUM(t.HOURS), 0) AS SCHED
  FROM ACOCO_L1.TIME.TIMESHEET_RECORD t
  JOIN wp w ON w.WBS_ID = t.WBS_ID
  JOIN mq ON mq.MONTH_START = DATE_TRUNC(month, t.WEEK_START)
  WHERE t.TIME_CATEGORY = 'DELIVERY'
  GROUP BY 1, 2
),
-- WIN: closed bids the person is named on (LEAD / MEMBER / SUPPORT), trailing 4 quarters, shrunk to the level rate (k = 3)
mem AS (
  SELECT tm.PERSON_ID, mq.QIDX AS QIDX_C, IFF(o.STATUS_AS_OF = 'WON', 1, 0) AS WON
  FROM ACOCO_L2.ONTOLOGY.REL_PURSUIT_TEAM tm
  JOIN ACOCO_L2.ONTOLOGY.ENT_OPPORTUNITY o ON o.OPPORTUNITY_ID = tm.OPPORTUNITY_ID AND o.STATUS_AS_OF IN ('WON', 'LOST')
  JOIN mq ON mq.MONTH_START = DATE_TRUNC(month, o.CLOSED_DATE)
),
bids AS (
  SELECT p.PERSON_ID, p.QIDX, COUNT(m.QIDX_C) AS BIDS, COALESCE(SUM(m.WON), 0) AS WINS
  FROM pq p LEFT JOIN mem m ON m.PERSON_ID = p.PERSON_ID AND m.QIDX_C BETWEEN p.QIDX - 3 AND p.QIDX
  GROUP BY 1, 2
),
lvl_win AS (
  SELECT p.LEVEL, b.QIDX, SUM(b.WINS) / NULLIF(SUM(b.BIDS), 0) AS LEVEL_WIN_RATE
  FROM bids b JOIN pq p ON p.PERSON_ID = b.PERSON_ID AND p.QIDX = b.QIDX
  GROUP BY 1, 2
),
-- LEARN: required curricula completed in the trailing 4 quarters (AI_ANY = any AI curriculum)
req AS (
  SELECT LEVEL, COUNT(*) AS REQUIRED FROM ACOCO_L1.TALENT.LEVEL_REQUIRED_CURRICULUM GROUP BY 1
),
lc AS (
  SELECT lc.PERSON_ID, mq.QIDX AS QIDX_C, li.CURRICULUM, li.IS_AI_CURRICULUM
  FROM ACOCO_L1.TALENT.LEARNING_COMPLETION lc
  JOIN ACOCO_L1.TALENT.LEARNING_ITEM li ON li.LEARNING_ITEM_ID = lc.LEARNING_ITEM_ID
  JOIN mq ON mq.MONTH_START = DATE_TRUNC(month, lc.COMPLETION_DATE)
  WHERE lc.COMPLETION_STATUS = 'COMPLETED'
),
req_done AS (
  SELECT p.PERSON_ID, p.QIDX, COUNT(DISTINCT r.CURRICULUM) AS REQUIRED_DONE
  FROM pq p
  JOIN ACOCO_L1.TALENT.LEVEL_REQUIRED_CURRICULUM r ON r.LEVEL = p.LEVEL
  JOIN lc ON lc.PERSON_ID = p.PERSON_ID AND lc.QIDX_C BETWEEN p.QIDX - 3 AND p.QIDX
         AND (lc.CURRICULUM = r.CURRICULUM OR (r.CURRICULUM = 'AI_ANY' AND lc.IS_AI_CURRICULUM))
  GROUP BY 1, 2
),
-- ACREATE: role-weighted quality of assets contributed to in the trailing 4 quarters; quality as of the quarter end
contrib AS (
  SELECT p.PERSON_ID, p.QIDX, p.Q_END, c.ASSET_ID, c.ROLE_WEIGHT
  FROM pq p
  JOIN ACOCO_L2.ONTOLOGY.REL_PERSON_CONTRIBUTES_ASSET c ON c.PERSON_ID = p.PERSON_ID
  JOIN mq ON mq.MONTH_START = DATE_TRUNC(month, c.CONTRIBUTION_DATE) AND mq.QIDX BETWEEN p.QIDX - 3 AND p.QIDX
),
aq AS (
  SELECT c.PERSON_ID, c.QIDX, c.ASSET_ID, c.ROLE_WEIGHT,
         GREATEST(COALESCE(AVG(u.RATING), 3) / 5 * LN(1 + COUNT(DISTINCT u.WBS_ID)), 0.2) AS QUALITY
  FROM contrib c
  LEFT JOIN ACOCO_L2.ONTOLOGY.REL_ASSET_USE u ON u.ASSET_ID = c.ASSET_ID AND u.USE_DATE <= c.Q_END
  GROUP BY 1, 2, 3, 4
),
acreate AS (SELECT PERSON_ID, QIDX, SUM(ROLE_WEIGHT * QUALITY) AS ACREATE, COUNT(*) AS ASSETS_CONTRIBUTED FROM aq GROUP BY 1, 2),
-- AREUSE: hours saved by reusing firm assets on own work / delivery hours, trailing 4 quarters
reuse AS (
  SELECT p.PERSON_ID, p.QIDX, SUM(r.HOURS_SAVED_ESTIMATED) AS HOURS_SAVED_T4Q, COUNT(*) AS ASSET_REUSES_T4Q
  FROM pq p
  JOIN ACOCO_L2.ONTOLOGY.REL_PERSON_REUSES_ASSET r ON r.PERSON_ID = p.PERSON_ID
  JOIN mq ON mq.MONTH_START = DATE_TRUNC(month, r.USE_DATE) AND mq.QIDX BETWEEN p.QIDX - 3 AND p.QIDX
  GROUP BY 1, 2
),
raw AS (
  SELECT p.*,
         t4.AVAILABLE_T4Q, t4.LEARNING_T4Q, t4.DELIVERY_T4Q,
         b.BIDS AS BIDS_T4Q, b.WINS AS WINS_T4Q, COALESCE(lw.LEVEL_WIN_RATE, 0.4) AS LEVEL_WIN_RATE,
         (b.WINS + 3 * COALESCE(lw.LEVEL_WIN_RATE, 0.4)) / (b.BIDS + 3) AS WIN,
         IFF(p.DELIVERY_HOURS > 0, p.EARNED_HOURS / p.DELIVERY_HOURS, NULL) AS EFF,
         s.SCHED,
         p.DELIVERY_HOURS / p.AVAILABLE_HOURS AS BILLABILITY,
         (p.DELIVERY_HOURS + p.BID_HOURS + p.ASSET_CONTRIBUTION_HOURS) / p.AVAILABLE_HOURS AS UTILIZATION,
         p.DELIVERY_HOURS / p.AVAILABLE_HOURS / NULLIF(p.BILL_TARGET, 0) AS BILL,
         (p.DELIVERY_HOURS + p.BID_HOURS + p.ASSET_CONTRIBUTION_HOURS) / p.AVAILABLE_HOURS / NULLIF(p.UTIL_TARGET, 0) AS UTIL,
         COALESCE(rd.REQUIRED_DONE, 0) AS REQUIRED_DONE, rq.REQUIRED,
         0.7 * LEAST(t4.LEARNING_T4Q / NULLIF(p.LEARN_TARGET * t4.AVAILABLE_T4Q, 0), 1.2)
           + 0.3 * COALESCE(rd.REQUIRED_DONE, 0) / NULLIF(rq.REQUIRED, 0) AS LEARN,
         COALESCE(ac.ACREATE, 0) AS ACREATE, COALESCE(ac.ASSETS_CONTRIBUTED, 0) AS ASSETS_CONTRIBUTED_T4Q,
         COALESCE(r.HOURS_SAVED_T4Q, 0) AS HOURS_SAVED_T4Q, COALESCE(r.ASSET_REUSES_T4Q, 0) AS ASSET_REUSES_T4Q,
         IFF(t4.DELIVERY_T4Q > 0, COALESCE(r.HOURS_SAVED_T4Q, 0) / t4.DELIVERY_T4Q, NULL) AS AREUSE
  FROM pq p
  JOIN t4 ON t4.PERSON_ID = p.PERSON_ID AND t4.QIDX = p.QIDX
  JOIN bids b ON b.PERSON_ID = p.PERSON_ID AND b.QIDX = p.QIDX
  LEFT JOIN lvl_win lw ON lw.LEVEL = p.LEVEL AND lw.QIDX = p.QIDX
  LEFT JOIN sched s ON s.PERSON_ID = p.PERSON_ID AND s.QIDX = p.QIDX
  LEFT JOIN req rq ON rq.LEVEL = p.LEVEL
  LEFT JOIN req_done rd ON rd.PERSON_ID = p.PERSON_ID AND rd.QIDX = p.QIDX
  LEFT JOIN acreate ac ON ac.PERSON_ID = p.PERSON_ID AND ac.QIDX = p.QIDX
  LEFT JOIN reuse r ON r.PERSON_ID = p.PERSON_ID AND r.QIDX = p.QIDX
  WHERE p.AVAILABLE_HOURS >= 80 AND p.LEVEL IS NOT NULL
),
-- Scaling rule (spec 2.2): z within level x fiscal year, clipped to +/-3, score = 50 + 15 z in [0, 100]; missing -> 50
sc AS (
  SELECT r.*,
    IFF(r.WIN IS NULL OR STDDEV(r.WIN) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR) = 0, 50, LEAST(100, GREATEST(0, 50 + 15 * LEAST(3, GREATEST(-3,
      (r.WIN - AVG(r.WIN) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR)) / STDDEV(r.WIN) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR)))))) AS S_WIN,
    IFF(r.EFF IS NULL OR STDDEV(r.EFF) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR) = 0, 50, LEAST(100, GREATEST(0, 50 + 15 * LEAST(3, GREATEST(-3,
      (r.EFF - AVG(r.EFF) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR)) / STDDEV(r.EFF) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR)))))) AS S_EFF,
    IFF(r.SCHED IS NULL OR STDDEV(r.SCHED) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR) = 0, 50, LEAST(100, GREATEST(0, 50 + 15 * LEAST(3, GREATEST(-3,
      (r.SCHED - AVG(r.SCHED) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR)) / STDDEV(r.SCHED) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR)))))) AS S_SCHED,
    IFF(r.BILL IS NULL OR STDDEV(r.BILL) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR) = 0, 50, LEAST(100, GREATEST(0, 50 + 15 * LEAST(3, GREATEST(-3,
      (r.BILL - AVG(r.BILL) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR)) / STDDEV(r.BILL) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR)))))) AS S_BILL,
    IFF(r.UTIL IS NULL OR STDDEV(r.UTIL) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR) = 0, 50, LEAST(100, GREATEST(0, 50 + 15 * LEAST(3, GREATEST(-3,
      (r.UTIL - AVG(r.UTIL) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR)) / STDDEV(r.UTIL) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR)))))) AS S_UTIL,
    IFF(r.LEARN IS NULL OR STDDEV(r.LEARN) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR) = 0, 50, LEAST(100, GREATEST(0, 50 + 15 * LEAST(3, GREATEST(-3,
      (r.LEARN - AVG(r.LEARN) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR)) / STDDEV(r.LEARN) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR)))))) AS S_LEARN,
    IFF(r.ACREATE IS NULL OR STDDEV(r.ACREATE) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR) = 0, 50, LEAST(100, GREATEST(0, 50 + 15 * LEAST(3, GREATEST(-3,
      (r.ACREATE - AVG(r.ACREATE) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR)) / STDDEV(r.ACREATE) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR)))))) AS S_ACREATE,
    IFF(r.AREUSE IS NULL OR STDDEV(r.AREUSE) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR) = 0, 50, LEAST(100, GREATEST(0, 50 + 15 * LEAST(3, GREATEST(-3,
      (r.AREUSE - AVG(r.AREUSE) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR)) / STDDEV(r.AREUSE) OVER (PARTITION BY r.LEVEL, r.FISCAL_YEAR)))))) AS S_AREUSE
  FROM raw r
),
w AS (   -- WPS weights by level (OPS.WPS_WEIGHTS / WPS_INPUT_WEIGHTS via L1 ORGANISATION.WPS_WEIGHT)
  SELECT LEVEL,
         MAX(IFF(PILLAR = 'VC', PILLAR_WEIGHT, NULL)) AS PW_VC, MAX(IFF(PILLAR = 'OE', PILLAR_WEIGHT, NULL)) AS PW_OE,
         MAX(IFF(PILLAR = 'PD', PILLAR_WEIGHT, NULL)) AS PW_PD, MAX(IFF(PILLAR = 'TM', PILLAR_WEIGHT, NULL)) AS PW_TM,
         MAX(IFF(PILLAR = 'VC' AND INPUT = 'WIN', INPUT_WEIGHT, 0)) AS VC_WIN, MAX(IFF(PILLAR = 'VC' AND INPUT = 'EFF', INPUT_WEIGHT, 0)) AS VC_EFF,
         MAX(IFF(PILLAR = 'OE' AND INPUT = 'SCHED', INPUT_WEIGHT, 0)) AS OE_SCHED, MAX(IFF(PILLAR = 'OE' AND INPUT = 'EFF', INPUT_WEIGHT, 0)) AS OE_EFF,
         MAX(IFF(PILLAR = 'PD' AND INPUT = 'BILL', INPUT_WEIGHT, 0)) AS PD_BILL, MAX(IFF(PILLAR = 'PD' AND INPUT = 'UTIL', INPUT_WEIGHT, 0)) AS PD_UTIL,
         MAX(IFF(PILLAR = 'PD' AND INPUT = 'AREUSE', INPUT_WEIGHT, 0)) AS PD_AREUSE, MAX(IFF(PILLAR = 'PD' AND INPUT = 'LEARN', INPUT_WEIGHT, 0)) AS PD_LEARN,
         MAX(IFF(PILLAR = 'PD' AND INPUT = 'ACREATE', INPUT_WEIGHT, 0)) AS PD_ACREATE
  FROM ACOCO_L1.ORGANISATION.WPS_WEIGHT GROUP BY LEVEL
),
pil AS (
  SELECT s.*, w.PW_VC, w.PW_OE, w.PW_PD, w.PW_TM,
         (w.VC_WIN * s.S_WIN + w.VC_EFF * s.S_EFF) / NULLIF(w.VC_WIN + w.VC_EFF, 0) AS VC,
         (w.OE_SCHED * s.S_SCHED + w.OE_EFF * s.S_EFF) / NULLIF(w.OE_SCHED + w.OE_EFF, 0) AS OE,
         (w.PD_BILL * s.S_BILL + w.PD_UTIL * s.S_UTIL + w.PD_AREUSE * s.S_AREUSE + w.PD_LEARN * s.S_LEARN + w.PD_ACREATE * s.S_ACREATE)
           / NULLIF(w.PD_BILL + w.PD_UTIL + w.PD_AREUSE + w.PD_LEARN + w.PD_ACREATE, 0) AS PD,
         -- PD without the learning input: Q5 / Q6 test training against a score that does not contain it (spec 3)
         (w.PD_BILL * s.S_BILL + w.PD_UTIL * s.S_UTIL + w.PD_AREUSE * s.S_AREUSE + w.PD_ACREATE * s.S_ACREATE)
           / NULLIF(w.PD_BILL + w.PD_UTIL + w.PD_AREUSE + w.PD_ACREATE, 0) AS PD_EX_LEARN
  FROM sc s JOIN w ON w.LEVEL = s.LEVEL
),
ex AS (   -- WPS without the TM pillar (used for the manager's TEAM input, so TEAM never feeds on itself)
  SELECT p.*,
         (p.PW_VC * p.VC + p.PW_OE * p.OE + p.PW_PD * p.PD) / NULLIF(p.PW_VC + p.PW_OE + p.PW_PD, 0) AS WPS_EX_TM,
         (p.PW_VC * p.VC + p.PW_OE * p.OE + p.PW_PD * p.PD_EX_LEARN) / NULLIF(p.PW_VC + p.PW_OE + p.PW_PD, 0) AS WPS_EX_LEARN_EX_TM
  FROM pil p
),
team AS (   -- TEAM: mean WPS (excluding TM) of the team in the quarter; >= 3 scored members. Manager: direct reports;
            -- Senior Manager+: whole reporting tree (direct + indirect, depth <= 4) - decision 2026-11-05, D-P6-17
  SELECT r.MANAGER_ID AS PERSON_ID, e.QIDX, COUNT(*) AS DIRECT_REPORTS, AVG(e.WPS_EX_TM) AS TEAM,
         IFF(ANY_VALUE(r.MANAGER_LEVEL_SORT) >= 4, 'REPORTING_TREE', 'DIRECT_REPORTS') AS TEAM_SCOPE
  FROM ACOCO_L2.ONTOLOGY.REL_PERSON_REPORTING_LINE r
  JOIN ex e ON e.PERSON_ID = r.PERSON_ID
  WHERE r.MANAGER_LEVEL_SORT >= 4 OR (r.MANAGER_LEVEL_SORT = 3 AND r.DEPTH = 1)
  GROUP BY 1, 2
  HAVING COUNT(*) >= 3
),
tm AS (
  SELECT e.*, t.DIRECT_REPORTS, t.TEAM, t.TEAM_SCOPE,
         IFF(t.TEAM IS NULL, NULL,
             IFF(COALESCE(STDDEV(t.TEAM) OVER (PARTITION BY e.LEVEL, e.FISCAL_YEAR), 0) = 0, 50,
                 LEAST(100, GREATEST(0, 50 + 15 * LEAST(3, GREATEST(-3,
                   (t.TEAM - AVG(t.TEAM) OVER (PARTITION BY e.LEVEL, e.FISCAL_YEAR))
                   / STDDEV(t.TEAM) OVER (PARTITION BY e.LEVEL, e.FISCAL_YEAR))))))) AS TM
  FROM ex e
  LEFT JOIN team t ON t.PERSON_ID = e.PERSON_ID AND t.QIDX = e.QIDX AND e.LEVEL_SORT >= 3
)
SELECT PERSON_ID, FISCAL_YEAR, FISCAL_QUARTER, 'FY' || RIGHT(FISCAL_YEAR::VARCHAR, 2) || ' Q' || FISCAL_QUARTER AS FISCAL_QUARTER_LABEL,
       Q_START, Q_END, LEVEL, LEVEL_SORT, MD_GROUP_ID,
       AVAILABLE_HOURS, DELIVERY_HOURS, BID_HOURS, LEARNING_HOURS, EARNED_HOURS, ASSET_CONTRIBUTION_HOURS,
       BILLABILITY, UTILIZATION, BILL_TARGET, UTIL_TARGET, LEARN_TARGET,
       BIDS_T4Q, WINS_T4Q, LEVEL_WIN_RATE, LEARNING_T4Q, AVAILABLE_T4Q, REQUIRED_DONE, REQUIRED,
       ASSETS_CONTRIBUTED_T4Q, ASSET_REUSES_T4Q, HOURS_SAVED_T4Q, DIRECT_REPORTS AS TEAM_MEMBERS_SCORED, TEAM_SCOPE,
       WIN, EFF, SCHED, BILL, UTIL, LEARN, ACREATE, AREUSE, TEAM,
       S_WIN, S_EFF, S_SCHED, S_BILL, S_UTIL, S_LEARN, S_ACREATE, S_AREUSE, TM AS S_TEAM,
       VC, OE, PD, PD_EX_LEARN, TM, TM IS NOT NULL AND PW_TM > 0 AS TM_APPLIES,
       PW_VC, PW_OE, PW_PD, PW_TM,
       WPS_EX_TM,
       IFF(TM IS NOT NULL AND PW_TM > 0, (PW_VC * VC + PW_OE * OE + PW_PD * PD + PW_TM * TM) / (PW_VC + PW_OE + PW_PD + PW_TM),
           WPS_EX_TM) AS WPS,
       IFF(TM IS NOT NULL AND PW_TM > 0,
           (PW_VC * VC + PW_OE * OE + PW_PD * PD_EX_LEARN + PW_TM * TM) / (PW_VC + PW_OE + PW_PD + PW_TM),
           WPS_EX_LEARN_EX_TM) AS WPS_EX_LEARN,
       PERSON_ID || '|' || FISCAL_YEAR || 'Q' || FISCAL_QUARTER AS PERSON_QUARTER_ID
FROM tm;
