-- CP-05  QUALITY (PRD 7.2): build-time snapshots so the app never reads L0 / L1. Filled by tools/snapshot_quality.py
-- and tools/gate.py (gate results, SC360 guard pattern).
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_ACOCO_BUILD;
CREATE SCHEMA IF NOT EXISTS ACOCO_L2.QUALITY COMMENT = 'Gate results, freshness, completeness, lineage row counts (build-time snapshots)';

CREATE TABLE IF NOT EXISTS ACOCO_L2.QUALITY.Q_CHECK_RESULTS (
  RUN_AT TIMESTAMP_TZ, CHECKPOINT VARCHAR, CHECK_ID VARCHAR, DESCRIPTION VARCHAR, EXPECTED VARCHAR, ACTUAL VARCHAR,
  RESULT VARCHAR
) COMMENT = 'Every gate check run (tools/gate.py): PASS / FAIL with expected and actual';

CREATE TABLE IF NOT EXISTS ACOCO_L2.QUALITY.Q_LINEAGE_COUNTS (
  SNAPSHOT_AT TIMESTAMP_TZ, LAYER VARCHAR, OBJECT_NAME VARCHAR, OBJECT_KIND VARCHAR, SOURCE_SYSTEM VARCHAR, ROW_COUNT NUMBER
) COMMENT = 'Row counts per L0 CLD / ACOCO_SIM table, L1 view (by SOURCE_SYSTEM) and L2 object';

CREATE TABLE IF NOT EXISTS ACOCO_L2.QUALITY.Q_FRESHNESS (
  SNAPSHOT_AT TIMESTAMP_TZ, OBJECT_NAME VARCHAR, DATE_COLUMN VARCHAR, MIN_DATE DATE, MAX_DATE DATE, SOURCE_SYSTEM VARCHAR
) COMMENT = 'Date coverage of the key L1 facts by SOURCE_SYSTEM, and the as-of date they are read against';

CREATE TABLE IF NOT EXISTS ACOCO_L2.QUALITY.Q_COMPLETENESS (
  SNAPSHOT_AT TIMESTAMP_TZ, OBJECT_NAME VARCHAR, COLUMN_NAME VARCHAR, ROW_COUNT NUMBER, NULL_COUNT NUMBER, NULL_PCT FLOAT
) COMMENT = 'Null rate of the conformed ontology keys in each L1 object';

CREATE TABLE IF NOT EXISTS ACOCO_L2.QUALITY.Q_ACCESS_SNAPSHOT (
  SNAPSHOT_AT TIMESTAMP_TZ, CHECK_NAME VARCHAR, VALUE VARCHAR
) COMMENT = 'Access evidence: writes by the build user to CLDs / connector (must be 0)';
