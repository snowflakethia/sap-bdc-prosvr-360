-- CP-04  L2 ONTOLOGY relationship bridges (PRD 5.3, 7.2): the many-to-many edges between entities.
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_ACOCO_BUILD;

-- Person holds Skill: latest assessment on or before the as-of date, with the first one for growth.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.ONTOLOGY.REL_PERSON_SKILL
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Person holds Skill (proficiency 1-5). Key PERSON_ID, SKILL_ID. Latest assessment <= as-of'
AS
SELECT s.PERSON_ID, s.SKILL_ID, s.PROFICIENCY, s.ASSESSED_DATE, s.ASSESSMENT_SOURCE,
       FIRST_VALUE(s.PROFICIENCY) OVER (PARTITION BY s.PERSON_ID, s.SKILL_ID ORDER BY s.ASSESSED_DATE) AS FIRST_PROFICIENCY,
       FIRST_VALUE(s.ASSESSED_DATE) OVER (PARTITION BY s.PERSON_ID, s.SKILL_ID ORDER BY s.ASSESSED_DATE) AS FIRST_ASSESSED_DATE,
       s.SOURCE_SYSTEM
FROM ACOCO_L1.TALENT.PERSON_SKILL s
WHERE s.ASSESSED_DATE <= (SELECT AS_OF_DATE FROM ACOCO_L2.CORE.VW_AS_OF)
QUALIFY ROW_NUMBER() OVER (PARTITION BY s.PERSON_ID, s.SKILL_ID ORDER BY s.ASSESSED_DATE DESC) = 1;

-- Person is assigned to Project / Work package.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.ONTOLOGY.REL_PERSON_ASSIGNMENT
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Person is assigned to Project / Work package. Key ASSIGNMENT_ID'
AS
SELECT r.ASSIGNMENT_ID, r.PERSON_ID, r.PROJECT_ID, r.WBS_ID, r.ASSIGNMENT_ROLE, r.ALLOCATION,
       r.ASSIGNMENT_START, r.ASSIGNMENT_END,
       r.ASSIGNMENT_START <= a.AS_OF_DATE AND r.ASSIGNMENT_END >= a.AS_OF_DATE AS IS_CURRENT_AS_OF,
       r.SOURCE_SYSTEM
FROM ACOCO_L1.PROJECTS.RESOURCE_ASSIGNMENT r
CROSS JOIN (SELECT AS_OF_DATE FROM ACOCO_L2.CORE.VW_AS_OF) a;

-- Person pursues Opportunity (bid team).
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.ONTOLOGY.REL_PURSUIT_TEAM
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Person pursues Opportunity (bid team). Key OPPORTUNITY_ID, PERSON_ID'
AS
SELECT OPPORTUNITY_ID, PERSON_ID,
       MIN(TEAM_ROLE) AS TEAM_ROLE,                -- LEAD sorts before MEMBER before SUPPORT
       ANY_VALUE(SOURCE_SYSTEM) AS SOURCE_SYSTEM
FROM ACOCO_L1.SALES.OPPORTUNITY_TEAM
GROUP BY OPPORTUNITY_ID, PERSON_ID;

CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.ONTOLOGY.REL_WP_SKILL
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Work package requires Skill. Key WBS_ID, SKILL_ID'
AS
SELECT WBS_ID, SKILL_ID, REQUIRED_PROFICIENCY, SOURCE_SYSTEM
FROM ACOCO_L1.PROJECTS.WORK_PACKAGE_SKILL_REQUIREMENT;

CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.ONTOLOGY.REL_OPPORTUNITY_SKILL
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Opportunity requires Skill. Key OPPORTUNITY_ID, SKILL_ID'
AS
SELECT OPPORTUNITY_ID, SKILL_ID, SOURCE_SYSTEM
FROM ACOCO_L1.SALES.OPPORTUNITY_SKILL_REQUIREMENT;

-- Asset embodies Skill: the asset's comma-separated skill tags.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.ONTOLOGY.REL_ASSET_SKILL
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Asset embodies Skill (from skill tags). Key ASSET_ID, SKILL_ID'
AS
SELECT DISTINCT a.ASSET_ID, TRIM(t.VALUE)::VARCHAR AS SKILL_ID, a.SOURCE_SYSTEM
FROM ACOCO_L1.ASSETS.ASSET a,
     LATERAL SPLIT_TO_TABLE(a.SKILL_TAGS, ',') t
WHERE TRIM(t.VALUE) <> '';

-- Project / Opportunity reuses Asset. P6: one row per team member using the asset on the work package (D-P6-7).
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.ONTOLOGY.REL_ASSET_USE
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Project / Work package / Opportunity reuses Asset, per using person. Key ASSET_USE_ID'
AS
SELECT MD5(CONCAT_WS('|', ASSET_ID, COALESCE(PROJECT_ID, ''), COALESCE(WBS_ID, ''), COALESCE(OPPORTUNITY_ID, ''),
                     COALESCE(USE_DATE::VARCHAR, ''), COALESCE(USED_BY_PERSON_ID, ''))) AS ASSET_USE_ID,
       ASSET_ID, PROJECT_ID, WBS_ID, OPPORTUNITY_ID, USE_DATE, HOURS_SAVED_ESTIMATED, USED_BY_PERSON_ID, RATING,
       IFF(OPPORTUNITY_ID IS NOT NULL, 'BID', 'DELIVERY') AS USE_CONTEXT,
       SOURCE_SYSTEM
FROM ACOCO_L1.ASSETS.ASSET_USAGE;

-- Person reports to Person (line manager, latest job record <= as-of; P6 TEAM input).
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.ONTOLOGY.REL_PERSON_REPORTS_TO
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Person reports to Person (line manager). Key PERSON_ID. Manager must be a known person'
AS
SELECT p.PERSON_ID, p.MANAGER_ID, m.LEVEL AS MANAGER_LEVEL, m.LEVEL_SORT AS MANAGER_LEVEL_SORT,
       p.MD_GROUP_ID = m.MD_GROUP_ID AS SAME_MD_GROUP, p.SOURCE_SYSTEM
FROM ACOCO_L2.ONTOLOGY.ENT_PERSON p
JOIN ACOCO_L2.ONTOLOGY.ENT_PERSON m ON m.PERSON_ID = p.MANAGER_ID
WHERE p.MANAGER_ID IS NOT NULL AND p.MANAGER_ID <> p.PERSON_ID;

-- Person is in the reporting tree of Person (direct and indirect, up to 4 levels; P6 TEAM for Senior Manager+, D-P6-17).
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.ONTOLOGY.REL_PERSON_REPORTING_LINE
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Person reports (directly or indirectly, depth 1-4) to Person. Key PERSON_ID, MANAGER_ID; DEPTH = shortest path'
AS
WITH d1 AS (SELECT PERSON_ID, MANAGER_ID FROM ACOCO_L2.ONTOLOGY.REL_PERSON_REPORTS_TO),
paths AS (
  SELECT PERSON_ID, MANAGER_ID, 1 AS DEPTH FROM d1
  UNION ALL SELECT a.PERSON_ID, b.MANAGER_ID, 2 FROM d1 a JOIN d1 b ON b.PERSON_ID = a.MANAGER_ID
  UNION ALL SELECT a.PERSON_ID, c.MANAGER_ID, 3 FROM d1 a JOIN d1 b ON b.PERSON_ID = a.MANAGER_ID
                                                         JOIN d1 c ON c.PERSON_ID = b.MANAGER_ID
  UNION ALL SELECT a.PERSON_ID, e.MANAGER_ID, 4 FROM d1 a JOIN d1 b ON b.PERSON_ID = a.MANAGER_ID
                                                         JOIN d1 c ON c.PERSON_ID = b.MANAGER_ID
                                                         JOIN d1 e ON e.PERSON_ID = c.MANAGER_ID
)
SELECT p.PERSON_ID, p.MANAGER_ID, MIN(p.DEPTH) AS DEPTH, ANY_VALUE(m.LEVEL) AS MANAGER_LEVEL,
       ANY_VALUE(m.LEVEL_SORT) AS MANAGER_LEVEL_SORT, ANY_VALUE(m.SOURCE_SYSTEM) AS SOURCE_SYSTEM
FROM paths p
JOIN ACOCO_L2.ONTOLOGY.ENT_PERSON m ON m.PERSON_ID = p.MANAGER_ID
WHERE p.PERSON_ID <> p.MANAGER_ID
GROUP BY p.PERSON_ID, p.MANAGER_ID;

-- Person contributes to Asset (author / contributor / reviewer; hours recorded, not budgeted - D-P6-2).
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.ONTOLOGY.REL_PERSON_CONTRIBUTES_ASSET
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Person contributes to Asset (AUTHOR / CONTRIBUTOR / REVIEWER). Key ASSET_ID, PERSON_ID'
AS
SELECT ASSET_ID, PERSON_ID, CONTRIBUTION_ROLE,
       DECODE(CONTRIBUTION_ROLE, 'AUTHOR', 1.0, 'CONTRIBUTOR', 0.5, 'REVIEWER', 0.25) AS ROLE_WEIGHT,
       HOURS, CONTRIBUTION_DATE, SOURCE_SYSTEM
FROM ACOCO_L1.ASSETS.ASSET_CONTRIBUTION;

-- Person reuses Asset on their own work (from the per-person asset usage).
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.ONTOLOGY.REL_PERSON_REUSES_ASSET
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Person reuses Asset on a work package (with rating 1-5). Key ASSET_USE_ID'
AS
SELECT ASSET_USE_ID, USED_BY_PERSON_ID AS PERSON_ID, ASSET_ID, PROJECT_ID, WBS_ID, USE_DATE, HOURS_SAVED_ESTIMATED, RATING,
       SOURCE_SYSTEM
FROM ACOCO_L2.ONTOLOGY.REL_ASSET_USE
WHERE USED_BY_PERSON_ID IS NOT NULL;
