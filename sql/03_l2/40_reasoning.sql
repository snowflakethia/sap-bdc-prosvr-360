-- CP-06  L2 REASONING (PRD 7.2, section 9): features, embeddings, matching views, search services.
-- Model training, forecasting and the R13 / R14 statistics run in tools/build_reasoning.py (they need procedures).
-- Reads ACOCO_L2 only (marts + ONTOLOGY), except the person-year features which read L1 history through L2 marts.
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_ACOCO_BUILD;
CREATE SCHEMA IF NOT EXISTS ACOCO_L2.REASONING COMMENT = 'Models, forecasts, matching and search over L2 (PRD section 9)';

-- Person x fiscal-year snapshot (state at FY end) with the label "voluntarily left in the next fiscal year".
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.REASONING.DT_ATTRITION_FEATURES
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Person x FY snapshot: time mix, productivity, performance, compa-ratio, AI skill, tenure; LEFT_NEXT_FY label (simulated voluntary leavers)'
AS
WITH y AS (
  SELECT PERSON_ID, FISCAL_YEAR,
         SUM(AVAILABLE_HOURS) AS AVAILABLE_HOURS,
         SUM(DELIVERY_HOURS) / NULLIF(SUM(AVAILABLE_HOURS), 0) AS BILLABILITY,
         SUM(BID_HOURS) / NULLIF(SUM(AVAILABLE_HOURS), 0) AS BID_SHARE,
         SUM(LEARNING_HOURS) / NULLIF(SUM(AVAILABLE_HOURS), 0) AS LEARNING_SHARE,
         SUM(BENCH_HOURS) / NULLIF(SUM(AVAILABLE_HOURS), 0) AS BENCH_SHARE,
         SUM(EARNED_HOURS) / NULLIF(SUM(DELIVERY_HOURS), 0) AS PRODUCTIVITY_INDEX,
         COUNT(*) AS MONTHS_WORKED
  FROM ACOCO_L2.WORKFORCE_PERFORMANCE.DT_PERSON_MONTH_SCORECARD
  GROUP BY 1, 2
),
fy AS (SELECT FISCAL_YEAR, MAX(MONTH_END) AS FY_END FROM ACOCO_L2.CORE.DT_FISCAL_MONTH GROUP BY 1),
ai AS (
  SELECT ps.PERSON_ID, f.FISCAL_YEAR, MAX(ps.PROFICIENCY) AS AI_SKILL_LEVEL
  FROM ACOCO_L1.TALENT.PERSON_SKILL ps
  JOIN ACOCO_L2.ONTOLOGY.ENT_SKILL s ON s.SKILL_ID = ps.SKILL_ID AND s.IS_AGENTIC_AI
  JOIN fy f ON ps.ASSESSED_DATE <= f.FY_END AND ps.ASSESSED_DATE > DATEADD(year, -1, f.FY_END)
  GROUP BY 1, 2
)
SELECT y.PERSON_ID, y.FISCAL_YEAR, p.MD_GROUP_ID, p.LEVEL, p.LEVEL_SORT, p.BILL_CODE,
       DATEDIFF(month, p.HIRE_DATE, f.FY_END) AS TENURE_MONTHS,
       y.MONTHS_WORKED, y.BILLABILITY, y.BID_SHARE, y.LEARNING_SHARE, y.BENCH_SHARE, y.PRODUCTIVITY_INDEX,
       pr.PERFORMANCE_RATING, c.COMPA_RATIO, COALESCE(ai.AI_SKILL_LEVEL, 0) AS AI_SKILL_LEVEL,
       COALESCE(p.TERMINATION_DATE > f.FY_END AND p.TERMINATION_DATE <= DATEADD(year, 1, f.FY_END), FALSE) AS LEFT_NEXT_FY,
       p.TERMINATION_DATE IS NULL OR p.TERMINATION_DATE > f.FY_END AS ACTIVE_AT_FY_END,
       p.SOURCE_SYSTEM
FROM y
JOIN fy f ON f.FISCAL_YEAR = y.FISCAL_YEAR
JOIN ACOCO_L2.ONTOLOGY.ENT_PERSON p ON p.PERSON_ID = y.PERSON_ID
LEFT JOIN ACOCO_L1.WORKFORCE.PERFORMANCE_RATING pr ON pr.PERSON_ID = y.PERSON_ID AND pr.FISCAL_YEAR = y.FISCAL_YEAR
LEFT JOIN ACOCO_L1.WORKFORCE.COMPENSATION_SUMMARY c ON c.PERSON_ID = y.PERSON_ID
LEFT JOIN ai ON ai.PERSON_ID = y.PERSON_ID AND ai.FISCAL_YEAR = y.FISCAL_YEAR
WHERE y.FISCAL_YEAR BETWEEN 2022 AND 2026 AND y.MONTHS_WORKED >= 6;

-- Monthly delivery demand (hours) by skill family: delivery hours on work packages requiring a skill of that family.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.REASONING.DT_DEMAND_BY_SKILL_MONTH
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Skill family x month: delivery hours on work packages that require the family (forecast input)'
AS
SELECT s.SKILL_FAMILY, f.MONTH_START, SUM(f.DELIVERY_HOURS) AS DEMAND_HOURS
FROM ACOCO_L2.PROJECT_DELIVERY.DT_PROJECT_MONTH_FINANCIALS f
JOIN (SELECT DISTINCT r.WBS_ID, k.SKILL_FAMILY FROM ACOCO_L2.ONTOLOGY.REL_WP_SKILL r
      JOIN ACOCO_L2.ONTOLOGY.ENT_SKILL k ON k.SKILL_ID = r.SKILL_ID) s ON s.WBS_ID = f.WBS_ID
WHERE f.MONTH_START >= '2021-10-01'
GROUP BY 1, 2;

-- R1 inputs: people free in the next 90 days (roll-off) and open opportunities, as text profiles + embeddings.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.REASONING.DT_PERSON_PROFILE
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Active people rolling off in 90 days: skills held at >= 3 as text + AI_EMBED vector (R1)'
AS
SELECT r.PERSON_ID, r.DISPLAY_NAME, r.MD_GROUP_ID, r.LEVEL, r.ROLL_OFF_DATE, r.AI_SKILL_LEVEL,
       LISTAGG(DISTINCT k.SKILL_NAME, ', ') WITHIN GROUP (ORDER BY k.SKILL_NAME) AS SKILLS_TEXT,
       ARRAY_AGG(DISTINCT ps.SKILL_ID) AS SKILL_IDS,
       AI_EMBED('snowflake-arctic-embed-m-v1.5',
                r.LEVEL || ' with skills: ' || LISTAGG(DISTINCT k.SKILL_NAME, ', ') WITHIN GROUP (ORDER BY k.SKILL_NAME)) AS PROFILE_VECTOR
FROM ACOCO_L2.WORKFORCE_PERFORMANCE.DT_ROLL_OFF r
JOIN ACOCO_L2.ONTOLOGY.REL_PERSON_SKILL ps ON ps.PERSON_ID = r.PERSON_ID AND ps.PROFICIENCY >= 3
JOIN ACOCO_L2.ONTOLOGY.ENT_SKILL k ON k.SKILL_ID = ps.SKILL_ID
GROUP BY r.PERSON_ID, r.DISPLAY_NAME, r.MD_GROUP_ID, r.LEVEL, r.ROLL_OFF_DATE, r.AI_SKILL_LEVEL;

CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.REASONING.DT_OPPORTUNITY_PROFILE
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Open opportunities: required skills as text + AI_EMBED vector (R1)'
AS
SELECT o.OPPORTUNITY_ID, o.MD_GROUP_ID, o.SIZE_CLASS, o.WORK_TYPE, o.ESTIMATED_VALUE, o.EXPECTED_START_DATE,
       o.REQUIRED_AI_SKILL_LEVEL,
       LISTAGG(DISTINCT k.SKILL_NAME, ', ') WITHIN GROUP (ORDER BY k.SKILL_NAME) AS REQUIRED_SKILLS_TEXT,
       ARRAY_AGG(DISTINCT rs.SKILL_ID) AS REQUIRED_SKILL_IDS,
       AI_EMBED('snowflake-arctic-embed-m-v1.5',
                o.WORK_TYPE || ' engagement needing: ' || LISTAGG(DISTINCT k.SKILL_NAME, ', ') WITHIN GROUP (ORDER BY k.SKILL_NAME)) AS NEED_VECTOR
FROM ACOCO_L2.ONTOLOGY.ENT_OPPORTUNITY o
JOIN ACOCO_L2.ONTOLOGY.REL_OPPORTUNITY_SKILL rs ON rs.OPPORTUNITY_ID = o.OPPORTUNITY_ID
JOIN ACOCO_L2.ONTOLOGY.ENT_SKILL k ON k.SKILL_ID = rs.SKILL_ID
WHERE o.IS_OPEN_AS_OF
GROUP BY o.OPPORTUNITY_ID, o.MD_GROUP_ID, o.SIZE_CLASS, o.WORK_TYPE, o.ESTIMATED_VALUE, o.EXPECTED_START_DATE, o.REQUIRED_AI_SKILL_LEVEL;

-- R1: roll-off person x open opportunity, ranked by semantic similarity and exact skill coverage (same group first).
CREATE OR REPLACE VIEW ACOCO_L2.REASONING.VW_BENCH_TO_PIPELINE_MATCH
  COMMENT = 'R1: people rolling off in 90 days x open opportunities - cosine similarity of skill profiles, exact coverage, AI-level fit; top 5 per person'
AS
SELECT p.PERSON_ID, p.DISPLAY_NAME, p.MD_GROUP_ID, p.LEVEL, p.ROLL_OFF_DATE, p.AI_SKILL_LEVEL,
       o.OPPORTUNITY_ID, o.MD_GROUP_ID AS OPPORTUNITY_MD_GROUP_ID, o.SIZE_CLASS, o.WORK_TYPE, o.ESTIMATED_VALUE,
       o.EXPECTED_START_DATE, o.REQUIRED_AI_SKILL_LEVEL, o.REQUIRED_SKILLS_TEXT, p.SKILLS_TEXT,
       VECTOR_COSINE_SIMILARITY(p.PROFILE_VECTOR, o.NEED_VECTOR) AS SIMILARITY,
       ARRAY_SIZE(ARRAY_INTERSECTION(p.SKILL_IDS, o.REQUIRED_SKILL_IDS)) / NULLIF(ARRAY_SIZE(o.REQUIRED_SKILL_IDS), 0) AS SKILL_COVERAGE,
       p.AI_SKILL_LEVEL >= o.REQUIRED_AI_SKILL_LEVEL AS MEETS_AI_LEVEL,
       0.6 * VECTOR_COSINE_SIMILARITY(p.PROFILE_VECTOR, o.NEED_VECTOR)
         + 0.4 * ARRAY_SIZE(ARRAY_INTERSECTION(p.SKILL_IDS, o.REQUIRED_SKILL_IDS)) / NULLIF(ARRAY_SIZE(o.REQUIRED_SKILL_IDS), 0) AS MATCH_SCORE,
       ROW_NUMBER() OVER (PARTITION BY p.PERSON_ID ORDER BY (p.MD_GROUP_ID = o.MD_GROUP_ID) DESC,
                          0.6 * VECTOR_COSINE_SIMILARITY(p.PROFILE_VECTOR, o.NEED_VECTOR)
                          + 0.4 * ARRAY_SIZE(ARRAY_INTERSECTION(p.SKILL_IDS, o.REQUIRED_SKILL_IDS)) / NULLIF(ARRAY_SIZE(o.REQUIRED_SKILL_IDS), 0) DESC) AS RANK_FOR_PERSON
FROM ACOCO_L2.REASONING.DT_PERSON_PROFILE p
JOIN ACOCO_L2.REASONING.DT_OPPORTUNITY_PROFILE o ON o.EXPECTED_START_DATE >= p.ROLL_OFF_DATE - 30
QUALIFY RANK_FOR_PERSON <= 5;

-- R12 inputs: asset and active work-package text + embeddings.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.REASONING.DT_ASSET_PROFILE
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Assets: title, description and skill tags as text + AI_EMBED vector (R12, CSS_ASSET_LIBRARY source)'
AS
SELECT a.ASSET_ID, a.ASSET_TITLE, a.ASSET_TYPE, a.WORK_TYPE, a.SKILL_TAGS, a.EFFORT_SAVING_HOURS, a.HARVEST_DATE,
       a.SOURCE_PROJECT_ID, a.DESCRIPTION,
       a.ASSET_TITLE || '. ' || a.DESCRIPTION || ' Work type: ' || a.WORK_TYPE || '. Skills: ' || REPLACE(a.SKILL_TAGS, ',', ', ') AS SEARCH_TEXT,
       AI_EMBED('snowflake-arctic-embed-m-v1.5', a.WORK_TYPE || ' asset: ' || a.DESCRIPTION) AS ASSET_VECTOR,
       a.SOURCE_SYSTEM
FROM ACOCO_L2.ONTOLOGY.ENT_ASSET a;

CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.REASONING.DT_WORK_PACKAGE_PROFILE
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Active / not-started work packages: work type and required skills as text + AI_EMBED vector (R12)'
AS
SELECT w.WBS_ID, w.PROJECT_ID, p.MD_GROUP_ID, w.WORK_TYPE, w.PLANNED_START, w.PLANNED_HOURS, w.REUSED_ASSET_ID,
       p.IS_STORY_PROJECT,
       LISTAGG(DISTINCT k.SKILL_NAME, ', ') WITHIN GROUP (ORDER BY k.SKILL_NAME) AS REQUIRED_SKILLS_TEXT,
       AI_EMBED('snowflake-arctic-embed-m-v1.5',
                w.WORK_TYPE || ' work needing: ' || LISTAGG(DISTINCT k.SKILL_NAME, ', ') WITHIN GROUP (ORDER BY k.SKILL_NAME)) AS NEED_VECTOR
FROM ACOCO_L2.ONTOLOGY.ENT_WORK_PACKAGE w
JOIN ACOCO_L2.ONTOLOGY.ENT_PROJECT p ON p.PROJECT_ID = w.PROJECT_ID AND p.STATUS_AS_OF IN ('ACTIVE', 'NOT_STARTED')
JOIN ACOCO_L2.ONTOLOGY.REL_WP_SKILL r ON r.WBS_ID = w.WBS_ID
JOIN ACOCO_L2.ONTOLOGY.ENT_SKILL k ON k.SKILL_ID = r.SKILL_ID
GROUP BY w.WBS_ID, w.PROJECT_ID, p.MD_GROUP_ID, w.WORK_TYPE, w.PLANNED_START, w.PLANNED_HOURS, w.REUSED_ASSET_ID, p.IS_STORY_PROJECT;

-- R12: assets harvested before a work package started that match it but were not reused (missed reuse).
CREATE OR REPLACE VIEW ACOCO_L2.REASONING.VW_ASSET_MATCH
  COMMENT = 'R12: active work package x asset available at its start - similarity, same work type, reused or MISSED; top 3 per work package'
AS
SELECT w.WBS_ID, w.PROJECT_ID, w.MD_GROUP_ID, w.WORK_TYPE, w.IS_STORY_PROJECT, w.PLANNED_START,
       a.ASSET_ID, a.ASSET_TITLE, a.ASSET_TYPE, a.WORK_TYPE AS ASSET_WORK_TYPE, a.EFFORT_SAVING_HOURS, a.SOURCE_PROJECT_ID,
       VECTOR_COSINE_SIMILARITY(w.NEED_VECTOR, a.ASSET_VECTOR) AS SIMILARITY,
       a.WORK_TYPE = w.WORK_TYPE AS SAME_WORK_TYPE,
       w.REUSED_ASSET_ID = a.ASSET_ID AS WAS_REUSED,
       IFF(w.REUSED_ASSET_ID = a.ASSET_ID, 'REUSED', 'MISSED') AS REUSE_STATUS,
       ROW_NUMBER() OVER (PARTITION BY w.WBS_ID ORDER BY VECTOR_COSINE_SIMILARITY(w.NEED_VECTOR, a.ASSET_VECTOR) DESC) AS RANK_FOR_WP
FROM ACOCO_L2.REASONING.DT_WORK_PACKAGE_PROFILE w
JOIN ACOCO_L2.REASONING.DT_ASSET_PROFILE a ON a.HARVEST_DATE <= w.PLANNED_START
QUALIFY RANK_FOR_WP <= 3;

-- Search corpora: L2 copies of PM commentary (with project context) and the asset library.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.REASONING.DT_PROJECT_NOTE_DOC
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'PM status notes with project context - corpus of CSS_PROJECT_COMMENTARY'
AS
SELECT n.NOTE_ID, n.PROJECT_ID, n.NOTE_DATE, n.RAG_STATUS, n.NOTE_TEXT,
       p.MD_GROUP_ID, p.CUSTOMER_ID, p.SIZE_CLASS, p.WORK_TYPE, p.CONTRACT_TYPE, p.STATUS_AS_OF, p.IS_STORY_PROJECT,
       p.PROJECT_ID || ' (' || p.SIZE_CLASS || ' ' || p.WORK_TYPE || ', ' || p.CONTRACT_TYPE || ', ' || p.MD_GROUP_ID || ') '
         || TO_CHAR(n.NOTE_DATE, 'YYYY-MM-DD') || ' ' || n.RAG_STATUS || ': ' || n.NOTE_TEXT AS SEARCH_TEXT,
       n.SOURCE_SYSTEM
FROM ACOCO_L1.PROJECTS.PROJECT_STATUS_NOTE n
JOIN ACOCO_L2.ONTOLOGY.ENT_PROJECT p ON p.PROJECT_ID = n.PROJECT_ID
WHERE n.NOTE_DATE < (SELECT AS_OF_DATE FROM ACOCO_L2.CORE.VW_AS_OF);

-- Cortex Search needs change tracking on its source, which FULL-refresh DTs cannot give: index build-time table
-- copies (refreshed by every L2 rebuild, D-06-6).
CREATE OR REPLACE TABLE ACOCO_L2.REASONING.CSS_DOC_PROJECT_NOTE CHANGE_TRACKING = TRUE
  COMMENT = 'Build-time copy of DT_PROJECT_NOTE_DOC indexed by CSS_PROJECT_COMMENTARY'
AS SELECT * FROM ACOCO_L2.REASONING.DT_PROJECT_NOTE_DOC;

CREATE OR REPLACE TABLE ACOCO_L2.REASONING.CSS_DOC_ASSET CHANGE_TRACKING = TRUE
  COMMENT = 'Build-time copy of DT_ASSET_PROFILE (text columns) indexed by CSS_ASSET_LIBRARY'
AS SELECT ASSET_ID, ASSET_TITLE, ASSET_TYPE, WORK_TYPE, SKILL_TAGS, EFFORT_SAVING_HOURS, HARVEST_DATE, SOURCE_PROJECT_ID,
          SEARCH_TEXT, SOURCE_SYSTEM
   FROM ACOCO_L2.REASONING.DT_ASSET_PROFILE;

CREATE OR REPLACE CORTEX SEARCH SERVICE ACOCO_L2.REASONING.CSS_PROJECT_COMMENTARY
  ON SEARCH_TEXT
  ATTRIBUTES PROJECT_ID, MD_GROUP_ID, RAG_STATUS, WORK_TYPE, CONTRACT_TYPE, STATUS_AS_OF
  WAREHOUSE = WH_ACOCO_BUILD
  TARGET_LAG = '1 day'
  COMMENT = 'Why questions over PM status notes (PRD section 9); filter by PROJECT_ID / MD_GROUP_ID / RAG_STATUS'
AS
SELECT SEARCH_TEXT, NOTE_ID, PROJECT_ID, NOTE_DATE::VARCHAR AS NOTE_DATE, RAG_STATUS, MD_GROUP_ID, WORK_TYPE, CONTRACT_TYPE,
       STATUS_AS_OF, IS_STORY_PROJECT::VARCHAR AS IS_STORY_PROJECT
FROM ACOCO_L2.REASONING.CSS_DOC_PROJECT_NOTE;

CREATE OR REPLACE CORTEX SEARCH SERVICE ACOCO_L2.REASONING.CSS_ASSET_LIBRARY
  ON SEARCH_TEXT
  ATTRIBUTES ASSET_TYPE, WORK_TYPE
  WAREHOUSE = WH_ACOCO_BUILD
  TARGET_LAG = '1 day'
  COMMENT = 'Find reusable assets by need (R12); filter by WORK_TYPE / ASSET_TYPE'
AS
SELECT SEARCH_TEXT, ASSET_ID, ASSET_TITLE, ASSET_TYPE, WORK_TYPE, SKILL_TAGS, EFFORT_SAVING_HOURS::VARCHAR AS EFFORT_SAVING_HOURS,
       SOURCE_PROJECT_ID, HARVEST_DATE::VARCHAR AS HARVEST_DATE
FROM ACOCO_L2.REASONING.CSS_DOC_ASSET;
