-- CP-04  L2 CORE: calendar, as-of and time targets (PRD 7.2). Reads L1 and ACOCO_DB.OPS only.
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_ACOCO_BUILD;

CREATE DATABASE IF NOT EXISTS ACOCO_L2 COMMENT = 'ACoCo L2: data assets (core, ontology, marts, reasoning, semantic, serving, quality)';
CREATE SCHEMA IF NOT EXISTS ACOCO_L2.CORE      COMMENT = 'Shared calendar, as-of date and time targets';
CREATE SCHEMA IF NOT EXISTS ACOCO_L2.ONTOLOGY  COMMENT = 'Conformed entities (ENT_*), relationship bridges (REL_*), registry (ONT_*)';

-- "Today" for every L2 object. Never CURRENT_DATE (PRD 7.2 DT rules).
CREATE OR REPLACE VIEW ACOCO_L2.CORE.VW_AS_OF
  COMMENT = 'Demo as-of date (override in ACOCO_DB.OPS.AS_OF_CONTROL); last closed month and fiscal year derived'
AS
SELECT AS_OF_DATE,
       DATEADD(day, -1, DATE_TRUNC(month, AS_OF_DATE))                         AS LAST_CLOSED_MONTH_END,
       DATE_TRUNC(month, DATEADD(month, -1, AS_OF_DATE))                       AS LAST_CLOSED_MONTH_START,
       YEAR(DATEADD(month, 3, AS_OF_DATE))                                     AS CURRENT_FISCAL_YEAR,
       YEAR(DATEADD(month, 3, AS_OF_DATE)) - 1                                 AS LAST_CLOSED_FISCAL_YEAR
FROM ACOCO_DB.OPS.AS_OF_CONTROL;

-- V9 fiscal months FY2021-FY2026 from S/4, plus FY27 forward months (V9 = Oct-Sep, so FY27 = FY26 + 1 year).
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.CORE.DT_FISCAL_MONTH
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'One row per V9 fiscal month FY2021-FY2027 (FY27 generated forward); MONTH_START is the join key'
AS
WITH p AS (
  SELECT FISCAL_YEAR, FISCAL_PERIOD, PERIOD_START, PERIOD_END, 'BDC_CLD' AS SOURCE_SYSTEM
  FROM ACOCO_L1.ORGANISATION.FISCAL_PERIOD
  UNION ALL
  SELECT FISCAL_YEAR + 1, FISCAL_PERIOD, DATEADD(year, 1, PERIOD_START), LAST_DAY(DATEADD(year, 1, PERIOD_START)), 'GENERATED_FORWARD'
  FROM ACOCO_L1.ORGANISATION.FISCAL_PERIOD
  WHERE FISCAL_YEAR = (SELECT MAX(FISCAL_YEAR) FROM ACOCO_L1.ORGANISATION.FISCAL_PERIOD)
)
SELECT PERIOD_START                                       AS MONTH_START,
       PERIOD_END                                         AS MONTH_END,
       FISCAL_YEAR,
       FISCAL_PERIOD,
       'FY' || RIGHT(FISCAL_YEAR::VARCHAR, 2)             AS FISCAL_YEAR_LABEL,
       'FY' || RIGHT(FISCAL_YEAR::VARCHAR, 2) || ' P' || LPAD(FISCAL_PERIOD::VARCHAR, 2, '0') AS FISCAL_PERIOD_LABEL,
       CEIL(FISCAL_PERIOD / 3)                            AS FISCAL_QUARTER,
       TO_CHAR(PERIOD_START, 'MON YYYY')                  AS MONTH_LABEL,
       DATEDIFF(day, PERIOD_START, PERIOD_END) + 1        AS CALENDAR_DAYS,
       SOURCE_SYSTEM
FROM p;

-- Level x time category design targets (PRD 2.1), long form.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.CORE.DT_TIME_TARGET
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Design target share of available hours per level and time category (Delivery, Bid, Learning, Admin, Bench)'
AS
SELECT LEVEL, LEVEL_SORT, 'DELIVERY' AS TIME_CATEGORY, TARGET_DELIVERY_PCT AS TARGET_PCT FROM ACOCO_L1.ORGANISATION.LEVEL
UNION ALL SELECT LEVEL, LEVEL_SORT, 'BID',      TARGET_BID_PCT      FROM ACOCO_L1.ORGANISATION.LEVEL
UNION ALL SELECT LEVEL, LEVEL_SORT, 'LEARNING', TARGET_LEARNING_PCT FROM ACOCO_L1.ORGANISATION.LEVEL
UNION ALL SELECT LEVEL, LEVEL_SORT, 'ADMIN',    TARGET_ADMIN_PCT    FROM ACOCO_L1.ORGANISATION.LEVEL
UNION ALL SELECT LEVEL, LEVEL_SORT, 'BENCH',    TARGET_BENCH_PCT    FROM ACOCO_L1.ORGANISATION.LEVEL;
