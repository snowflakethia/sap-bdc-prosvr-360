-- CP-05  Mart AI_ADOPTION (PRD 7.2, 2.7, R13, R14): AI usage, AI cost, the AI-productivity test and learning payback.
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_ACOCO_BUILD;
CREATE SCHEMA IF NOT EXISTS ACOCO_L2.AI_ADOPTION COMMENT = 'Mart: AI usage and cost, AI productivity uplift (R13), learning payback (R14)';

-- Person x day x AI tool (events with no mapped person are kept with PERSON_ID NULL for cost totals).
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.AI_ADOPTION.DT_AI_USAGE_DAILY
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Person x day x AI tool: sessions, tokens, cost (USD); PERSON_MAPPED = FALSE for telemetry users with no People Intelligence identity'
AS
SELECT u.USAGE_DATE, u.AI_TOOL_ID, u.PRODUCT, u.MODEL, u.AI_TOOL_ID || '|' || u.MODEL AS AI_MODEL_ID,
       p.PERSON_ID, p.PERSON_ID IS NOT NULL AS PERSON_MAPPED,
       p.MD_GROUP_ID, p.LEVEL,
       SUM(u.SESSIONS) AS SESSIONS, SUM(u.TOKENS) AS TOKENS, SUM(u.COST_USD) AS COST_USD,
       SUM(u.INPUT_TOKENS) AS INPUT_TOKENS, SUM(u.OUTPUT_TOKENS) AS OUTPUT_TOKENS,
       COUNT(DISTINCT u.WBS_ID) AS WORK_PACKAGES,
       ANY_VALUE(u.SOURCE_SYSTEM) AS SOURCE_SYSTEM
FROM ACOCO_L1.AI_TELEMETRY.AI_USAGE_EVENT u
LEFT JOIN ACOCO_L2.ONTOLOGY.ENT_PERSON p ON p.PERSON_ID = u.PERSON_ID
WHERE u.USAGE_DATE < (SELECT AS_OF_DATE FROM ACOCO_L2.CORE.VW_AS_OF)
GROUP BY 1, 2, 3, 4, 5, 6, 7, 8, 9;

-- Project x month x agent: AI-agent cost charged to projects (S/4 AGT_* activity allocations) + assistant spend.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.AI_ADOPTION.DT_AI_COST_MONTH
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'MD group x month x AI tool: agent cost and hours charged to projects (journal AGT_*) and assistant subscription spend (telemetry)'
AS
WITH agent AS (
  SELECT p.MD_GROUP_ID, DATE_TRUNC(month, j.POSTING_DATE) AS MONTH_START, j.ACTIVITY_TYPE AS AI_TOOL_ID,
         SUM(j.AMOUNT) AS AGENT_COST, SUM(j.QUANTITY) AS AGENT_HOURS, COUNT(DISTINCT w.PROJECT_ID) AS PROJECTS
  FROM ACOCO_L1.FINANCE.JOURNAL_ENTRY_ITEM j
  JOIN ACOCO_L2.ONTOLOGY.ENT_WORK_PACKAGE w ON w.WBS_ID = j.WBS_ID
  JOIN ACOCO_L2.ONTOLOGY.ENT_PROJECT p ON p.PROJECT_ID = w.PROJECT_ID
  WHERE j.ACTIVITY_TYPE LIKE 'AGT%' AND j.DEBIT_CREDIT = 'S'
  GROUP BY 1, 2, 3
),
asst AS (
  SELECT MD_GROUP_ID, DATE_TRUNC(month, USAGE_DATE) AS MONTH_START, AI_TOOL_ID,
         SUM(COST_USD) AS ASSISTANT_COST, COUNT(DISTINCT PERSON_ID) AS ACTIVE_USERS, SUM(SESSIONS) AS SESSIONS
  FROM ACOCO_L2.AI_ADOPTION.DT_AI_USAGE_DAILY
  GROUP BY 1, 2, 3
)
SELECT COALESCE(a.MD_GROUP_ID, s.MD_GROUP_ID) AS MD_GROUP_ID, COALESCE(a.MONTH_START, s.MONTH_START) AS MONTH_START,
       f.FISCAL_YEAR, COALESCE(a.AI_TOOL_ID, s.AI_TOOL_ID) AS AI_TOOL_ID, t.TOOL_KIND,
       COALESCE(a.AGENT_COST, 0) AS AGENT_COST, COALESCE(a.AGENT_HOURS, 0) AS AGENT_HOURS, COALESCE(a.PROJECTS, 0) AS PROJECTS,
       COALESCE(s.ASSISTANT_COST, 0) AS ASSISTANT_COST, COALESCE(s.ACTIVE_USERS, 0) AS ACTIVE_USERS,
       COALESCE(s.SESSIONS, 0) AS SESSIONS,
       COALESCE(t.SOURCE_SYSTEM, 'SIMULATED') AS SOURCE_SYSTEM
FROM agent a
FULL OUTER JOIN asst s ON 1 = 0          -- agent and assistant rows are different tools: stack, never match
JOIN ACOCO_L2.CORE.DT_FISCAL_MONTH f ON f.MONTH_START = COALESCE(a.MONTH_START, s.MONTH_START)
LEFT JOIN ACOCO_L2.ONTOLOGY.ENT_AI_TOOL t ON t.AI_TOOL_ID = COALESCE(a.AI_TOOL_ID, s.AI_TOOL_ID)
WHERE COALESCE(a.MONTH_START, s.MONTH_START) < (SELECT DATE_TRUNC(month, AS_OF_DATE) FROM ACOCO_L2.CORE.VW_AS_OF);

-- R13 input: person x fiscal quarter x work type. AI-active = AI-skill >= 3 at quarter end AND AI use on >= 50 % of
-- working days in the quarter. Productivity index = earned / actual delivery hours. The uplift is compared within
-- level x work type strata (bootstrap CI computed by the reasoning layer / validate.py).
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.AI_ADOPTION.DT_AI_PRODUCTIVITY
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Person x fiscal quarter x work type: delivery hours, productivity index, AI-skill level, AI-use share of working days, AI_ACTIVE / AI_SKILLED_INACTIVE flags'
AS
WITH q AS (
  SELECT MONTH_START, FISCAL_YEAR, FISCAL_QUARTER,
         MIN(MONTH_START) OVER (PARTITION BY FISCAL_YEAR, FISCAL_QUARTER) AS Q_START,
         MAX(MONTH_END) OVER (PARTITION BY FISCAL_YEAR, FISCAL_QUARTER) AS Q_END
  FROM ACOCO_L2.CORE.DT_FISCAL_MONTH
),
d AS (
  SELECT t.PERSON_ID, q.FISCAL_YEAR, q.FISCAL_QUARTER, q.Q_START, q.Q_END, w.WORK_TYPE,
         SUM(t.HOURS) AS DELIVERY_HOURS, SUM(t.EARNED_HOURS) AS EARNED_HOURS, SUM(t.AI_ASSISTED_HOURS) AS AI_ASSISTED_HOURS
  FROM ACOCO_L1.TIME.TIMESHEET_RECORD t
  JOIN ACOCO_L2.ONTOLOGY.ENT_WORK_PACKAGE w ON w.WBS_ID = t.WBS_ID
  JOIN q ON q.MONTH_START = DATE_TRUNC(month, t.WEEK_START)
  WHERE t.TIME_CATEGORY = 'DELIVERY'
  GROUP BY 1, 2, 3, 4, 5, 6
),
workdays AS (
  SELECT e.PERSON_ID, q.FISCAL_YEAR, q.FISCAL_QUARTER, COUNT_IF(e.AVAILABLE_HOURS > 0) AS WORKING_DAYS
  FROM ACOCO_L1.TIME.EMPLOYEE_AVAILABILITY e
  JOIN q ON q.MONTH_START = DATE_TRUNC(month, e.WORK_DATE)
  WHERE e.PERSON_ID IS NOT NULL
  GROUP BY 1, 2, 3
),
ai_use AS (
  SELECT u.PERSON_ID, q.FISCAL_YEAR, q.FISCAL_QUARTER, COUNT(DISTINCT u.USAGE_DATE) AS AI_USE_DAYS, SUM(u.COST_USD) AS AI_COST_USD
  FROM ACOCO_L2.AI_ADOPTION.DT_AI_USAGE_DAILY u
  JOIN q ON q.MONTH_START = DATE_TRUNC(month, u.USAGE_DATE)
  WHERE u.PERSON_MAPPED
  GROUP BY 1, 2, 3
),
skill AS (   -- AI-skill level = max proficiency over the Agentic-AI family, latest assessment <= quarter end
  SELECT d.PERSON_ID, d.FISCAL_YEAR, d.FISCAL_QUARTER, ps.PROFICIENCY AS AI_SKILL_LEVEL
  FROM (SELECT DISTINCT PERSON_ID, FISCAL_YEAR, FISCAL_QUARTER, Q_END FROM d) d
  JOIN ACOCO_L1.TALENT.PERSON_SKILL ps ON ps.PERSON_ID = d.PERSON_ID AND ps.ASSESSED_DATE <= d.Q_END
  JOIN ACOCO_L2.ONTOLOGY.ENT_SKILL s ON s.SKILL_ID = ps.SKILL_ID AND s.IS_AGENTIC_AI
  QUALIFY ROW_NUMBER() OVER (PARTITION BY d.PERSON_ID, d.FISCAL_YEAR, d.FISCAL_QUARTER, ps.SKILL_ID ORDER BY ps.ASSESSED_DATE DESC) = 1
),
skill_q AS (SELECT PERSON_ID, FISCAL_YEAR, FISCAL_QUARTER, MAX(AI_SKILL_LEVEL) AS AI_SKILL_LEVEL FROM skill GROUP BY 1, 2, 3)
SELECT d.PERSON_ID, d.FISCAL_YEAR, d.FISCAL_QUARTER, d.Q_START AS QUARTER_START, d.WORK_TYPE,
       p.LEVEL, p.LEVEL_SORT, p.MD_GROUP_ID,
       d.DELIVERY_HOURS, d.EARNED_HOURS, d.AI_ASSISTED_HOURS,
       d.EARNED_HOURS / NULLIF(d.DELIVERY_HOURS, 0) AS PRODUCTIVITY_INDEX,
       COALESCE(sk.AI_SKILL_LEVEL, 0) AS AI_SKILL_LEVEL,
       COALESCE(wd.WORKING_DAYS, 0) AS WORKING_DAYS, COALESCE(u.AI_USE_DAYS, 0) AS AI_USE_DAYS,
       COALESCE(u.AI_USE_DAYS, 0) / NULLIF(wd.WORKING_DAYS, 0) AS AI_USE_SHARE,
       COALESCE(u.AI_COST_USD, 0) AS AI_COST_USD,
       COALESCE(sk.AI_SKILL_LEVEL, 0) >= 3 AND COALESCE(u.AI_USE_DAYS, 0) >= 0.5 * NULLIF(wd.WORKING_DAYS, 0) AS AI_ACTIVE,
       COALESCE(sk.AI_SKILL_LEVEL, 0) >= 3 AND COALESCE(u.AI_USE_DAYS, 0) = 0 AS AI_SKILLED_INACTIVE,
       p.LEVEL || ' | ' || d.WORK_TYPE AS STRATUM,
       p.SOURCE_SYSTEM
FROM d
JOIN ACOCO_L2.ONTOLOGY.ENT_PERSON p ON p.PERSON_ID = d.PERSON_ID
LEFT JOIN workdays wd ON wd.PERSON_ID = d.PERSON_ID AND wd.FISCAL_YEAR = d.FISCAL_YEAR AND wd.FISCAL_QUARTER = d.FISCAL_QUARTER
LEFT JOIN ai_use u ON u.PERSON_ID = d.PERSON_ID AND u.FISCAL_YEAR = d.FISCAL_YEAR AND u.FISCAL_QUARTER = d.FISCAL_QUARTER
LEFT JOIN skill_q sk ON sk.PERSON_ID = d.PERSON_ID AND sk.FISCAL_YEAR = d.FISCAL_YEAR AND sk.FISCAL_QUARTER = d.FISCAL_QUARTER
WHERE d.Q_END < (SELECT AS_OF_DATE FROM ACOCO_L2.CORE.VW_AS_OF);

-- R14 input: one row per completion with the learner's productivity 6 months before and after, and the same change
-- for non-learners in the same level x completion month (the matched comparison group).
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.AI_ADOPTION.DT_LEARNING_PAYBACK
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Learning episode (first completion per person x curriculum x FY): productivity index 6 months before / after vs same-level people who did not complete that curriculum in +/- 6 months; payback = learner change - comparison change'
AS
WITH c AS (
  SELECT lc.PERSON_ID, lc.LEARNING_ITEM_ID, lc.COMPLETION_DATE, DATE_TRUNC(month, lc.COMPLETION_DATE) AS COMPLETION_MONTH,
         li.CURRICULUM, li.IS_AI_CURRICULUM, li.LEARNING_HOURS, p.LEVEL, p.MD_GROUP_ID
  FROM ACOCO_L1.TALENT.LEARNING_COMPLETION lc
  JOIN ACOCO_L2.ONTOLOGY.ENT_LEARNING_ITEM li ON li.LEARNING_ITEM_ID = lc.LEARNING_ITEM_ID
  JOIN ACOCO_L2.ONTOLOGY.ENT_PERSON p ON p.PERSON_ID = lc.PERSON_ID
  WHERE lc.COMPLETION_STATUS = 'COMPLETED'
    AND lc.COMPLETION_DATE <= DATEADD(month, -6, (SELECT AS_OF_DATE FROM ACOCO_L2.CORE.VW_AS_OF))
  -- one episode per person x curriculum x fiscal year: its first completion (a learner completes many items a year)
  QUALIFY ROW_NUMBER() OVER (PARTITION BY lc.PERSON_ID, li.CURRICULUM, YEAR(DATEADD(month, 3, lc.COMPLETION_DATE))
                             ORDER BY lc.COMPLETION_DATE, lc.LEARNING_ITEM_ID) = 1
),
pm AS (   -- person x month delivery productivity
  SELECT PERSON_ID, MONTH_START, LEVEL, DELIVERY_HOURS, EARNED_HOURS
  FROM ACOCO_L2.WORKFORCE_PERFORMANCE.DT_PERSON_MONTH_SCORECARD WHERE DELIVERY_HOURS > 0
),
learner AS (
  SELECT c.PERSON_ID, c.LEARNING_ITEM_ID, c.COMPLETION_MONTH,
         SUM(IFF(pm.MONTH_START <  c.COMPLETION_MONTH, pm.EARNED_HOURS, 0)) / NULLIF(SUM(IFF(pm.MONTH_START <  c.COMPLETION_MONTH, pm.DELIVERY_HOURS, 0)), 0) AS PI_BEFORE,
         SUM(IFF(pm.MONTH_START >  c.COMPLETION_MONTH, pm.EARNED_HOURS, 0)) / NULLIF(SUM(IFF(pm.MONTH_START >  c.COMPLETION_MONTH, pm.DELIVERY_HOURS, 0)), 0) AS PI_AFTER,
         SUM(IFF(pm.MONTH_START >  c.COMPLETION_MONTH, pm.DELIVERY_HOURS, 0)) AS HOURS_AFTER
  FROM c JOIN pm ON pm.PERSON_ID = c.PERSON_ID
   AND pm.MONTH_START BETWEEN DATEADD(month, -6, c.COMPLETION_MONTH) AND DATEADD(month, 6, c.COMPLETION_MONTH)
  GROUP BY 1, 2, 3
),
lm AS (SELECT DISTINCT PERSON_ID, CURRICULUM, COMPLETION_MONTH FROM c),
cohort AS (   -- comparison: same level, no completion of the same curriculum within +/- 6 months
  SELECT cm.LEVEL, cm.CURRICULUM, cm.COMPLETION_MONTH,
         SUM(IFF(pm.MONTH_START <  cm.COMPLETION_MONTH, pm.EARNED_HOURS, 0)) / NULLIF(SUM(IFF(pm.MONTH_START <  cm.COMPLETION_MONTH, pm.DELIVERY_HOURS, 0)), 0) AS CMP_PI_BEFORE,
         SUM(IFF(pm.MONTH_START >  cm.COMPLETION_MONTH, pm.EARNED_HOURS, 0)) / NULLIF(SUM(IFF(pm.MONTH_START >  cm.COMPLETION_MONTH, pm.DELIVERY_HOURS, 0)), 0) AS CMP_PI_AFTER
  FROM (SELECT DISTINCT LEVEL, CURRICULUM, COMPLETION_MONTH FROM c) cm
  JOIN pm ON pm.LEVEL = cm.LEVEL
   AND pm.MONTH_START BETWEEN DATEADD(month, -6, cm.COMPLETION_MONTH) AND DATEADD(month, 6, cm.COMPLETION_MONTH)
  WHERE NOT EXISTS (SELECT 1 FROM lm WHERE lm.PERSON_ID = pm.PERSON_ID AND lm.CURRICULUM = cm.CURRICULUM
                     AND lm.COMPLETION_MONTH BETWEEN DATEADD(month, -6, cm.COMPLETION_MONTH) AND DATEADD(month, 6, cm.COMPLETION_MONTH))
  GROUP BY 1, 2, 3
)
SELECT c.PERSON_ID, c.LEARNING_ITEM_ID, c.COMPLETION_DATE, c.COMPLETION_MONTH, c.CURRICULUM, c.IS_AI_CURRICULUM,
       c.LEARNING_HOURS, c.LEVEL, c.MD_GROUP_ID,
       l.PI_BEFORE, l.PI_AFTER, l.PI_AFTER - l.PI_BEFORE AS LEARNER_CHANGE,
       k.CMP_PI_BEFORE, k.CMP_PI_AFTER, k.CMP_PI_AFTER - k.CMP_PI_BEFORE AS COMPARISON_CHANGE,
       (l.PI_AFTER - l.PI_BEFORE) - (k.CMP_PI_AFTER - k.CMP_PI_BEFORE) AS PAYBACK,
       ((l.PI_AFTER - l.PI_BEFORE) - (k.CMP_PI_AFTER - k.CMP_PI_BEFORE)) * l.HOURS_AFTER AS HOURS_SAVED,
       'SIMULATED' AS SOURCE_SYSTEM
FROM c
JOIN learner l ON l.PERSON_ID = c.PERSON_ID AND l.LEARNING_ITEM_ID = c.LEARNING_ITEM_ID AND l.COMPLETION_MONTH = c.COMPLETION_MONTH
LEFT JOIN cohort k ON k.LEVEL = c.LEVEL AND k.CURRICULUM = c.CURRICULUM AND k.COMPLETION_MONTH = c.COMPLETION_MONTH
WHERE l.PI_BEFORE IS NOT NULL AND l.PI_AFTER IS NOT NULL;

-- Project x AI agent x month: agent hours and cost charged to the project (journal AGT_* allocations) - the
-- "Project consumes AI agent" relationship (PRD 5.3).
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.AI_ADOPTION.DT_AI_AGENT_PROJECT_MONTH
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Project x AI agent (AGT_* activity type) x month: agent hours and cost posted to the project WBS'
AS
SELECT w.PROJECT_ID, j.ACTIVITY_TYPE AS AI_TOOL_ID, DATE_TRUNC(month, j.POSTING_DATE) AS MONTH_START,
       SUM(j.QUANTITY) AS AGENT_HOURS, SUM(j.AMOUNT) AS AGENT_COST,
       w.PROJECT_ID || '|' || j.ACTIVITY_TYPE || '|' || DATE_TRUNC(month, j.POSTING_DATE)::VARCHAR AS AGENT_PROJECT_MONTH_ID,
       ANY_VALUE(j.SOURCE_SYSTEM) AS SOURCE_SYSTEM
FROM ACOCO_L1.FINANCE.JOURNAL_ENTRY_ITEM j
JOIN ACOCO_L2.ONTOLOGY.ENT_WORK_PACKAGE w ON w.WBS_ID = j.WBS_ID
WHERE j.ACTIVITY_TYPE LIKE 'AGT%' AND j.DEBIT_CREDIT = 'S'
  AND DATE_TRUNC(month, j.POSTING_DATE) < (SELECT DATE_TRUNC(month, AS_OF_DATE) FROM ACOCO_L2.CORE.VW_AS_OF)
GROUP BY w.PROJECT_ID, j.ACTIVITY_TYPE, DATE_TRUNC(month, j.POSTING_DATE);
