-- CP-05  Mart WORKFORCE_PERFORMANCE (PRD 7.2, 2.7). Reads ACOCO_L1 + ACOCO_L2.ONTOLOGY / CORE only.
-- Month convention: weekly timesheets and daily availability are both bucketed by the fiscal month of the ISO week
-- start (Monday), so booked and available hours always cover the same days (OD-11).
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_ACOCO_BUILD;
CREATE SCHEMA IF NOT EXISTS ACOCO_L2.WORKFORCE_PERFORMANCE COMMENT = 'Mart: time mix, headcount, attrition, roll-off';

-- One row per person x month: available hours (Employee Availability, all days) and the five-way time mix vs target.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.WORKFORCE_PERFORMANCE.DT_PERSON_MONTH_SCORECARD
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Person x month: available hours and Delivery / Bid / Learning / Admin / Bench hours and shares vs level target. Closed months only'
AS
WITH a AS (SELECT AS_OF_DATE FROM ACOCO_L2.CORE.VW_AS_OF),
av AS (
  SELECT e.PERSON_ID,
         DATE_TRUNC(month, DATEADD(day, 1 - DAYOFWEEKISO(e.WORK_DATE), e.WORK_DATE)) AS MONTH_START,
         SUM(e.AVAILABLE_HOURS) AS AVAILABLE_HOURS,
         SUM(e.PLANNED_HOURS)   AS PLANNED_HOURS,
         SUM(e.ABSENCE_HOURS)   AS ABSENCE_HOURS
  FROM ACOCO_L1.TIME.EMPLOYEE_AVAILABILITY e
  WHERE e.PERSON_ID IS NOT NULL
  GROUP BY 1, 2
),
ts AS (
  SELECT t.PERSON_ID, DATE_TRUNC(month, t.WEEK_START) AS MONTH_START,
         SUM(IFF(t.TIME_CATEGORY = 'DELIVERY', t.HOURS, 0)) AS DELIVERY_HOURS,
         SUM(IFF(t.TIME_CATEGORY = 'BID',      t.HOURS, 0)) AS BID_HOURS,
         SUM(IFF(t.TIME_CATEGORY = 'LEARNING', t.HOURS, 0)) AS LEARNING_HOURS,
         SUM(IFF(t.TIME_CATEGORY = 'ADMIN',    t.HOURS, 0)) AS ADMIN_HOURS,
         SUM(t.HOURS)                                       AS BOOKED_HOURS,
         SUM(IFF(t.TIME_CATEGORY = 'DELIVERY', t.EARNED_HOURS, 0)) AS EARNED_HOURS,
         SUM(t.AI_ASSISTED_HOURS) AS AI_ASSISTED_HOURS,
         SUM(t.AI_HOURS_SAVED)    AS AI_HOURS_SAVED
  FROM ACOCO_L1.TIME.TIMESHEET_RECORD t
  GROUP BY 1, 2
),
m AS (
  SELECT COALESCE(av.PERSON_ID, ts.PERSON_ID) AS PERSON_ID, COALESCE(av.MONTH_START, ts.MONTH_START) AS MONTH_START,
         COALESCE(av.AVAILABLE_HOURS, 0) AS AVAILABLE_HOURS, COALESCE(av.ABSENCE_HOURS, 0) AS ABSENCE_HOURS,
         COALESCE(ts.DELIVERY_HOURS, 0) AS DELIVERY_HOURS, COALESCE(ts.BID_HOURS, 0) AS BID_HOURS,
         COALESCE(ts.LEARNING_HOURS, 0) AS LEARNING_HOURS, COALESCE(ts.ADMIN_HOURS, 0) AS ADMIN_HOURS,
         COALESCE(ts.BOOKED_HOURS, 0) AS BOOKED_HOURS, COALESCE(ts.EARNED_HOURS, 0) AS EARNED_HOURS,
         COALESCE(ts.AI_ASSISTED_HOURS, 0) AS AI_ASSISTED_HOURS, COALESCE(ts.AI_HOURS_SAVED, 0) AS AI_HOURS_SAVED
  FROM av FULL OUTER JOIN ts ON ts.PERSON_ID = av.PERSON_ID AND ts.MONTH_START = av.MONTH_START
)
SELECT m.PERSON_ID, m.MONTH_START, f.FISCAL_YEAR, f.FISCAL_PERIOD,
       p.MD_GROUP_ID, p.LEVEL, p.LEVEL_SORT, p.BILL_CODE, p.SOURCE_SYSTEM AS PERSON_SOURCE,
       m.AVAILABLE_HOURS, m.ABSENCE_HOURS,
       m.DELIVERY_HOURS, m.BID_HOURS, m.LEARNING_HOURS, m.ADMIN_HOURS, m.BOOKED_HOURS,
       GREATEST(m.AVAILABLE_HOURS - m.BOOKED_HOURS, 0) AS BENCH_HOURS,
       GREATEST(m.BOOKED_HOURS - m.AVAILABLE_HOURS, 0) AS OVERBOOKED_HOURS,
       GREATEST(m.AVAILABLE_HOURS - m.BOOKED_HOURS - 0.02 * m.AVAILABLE_HOURS, 0) AS EXCESS_BENCH_HOURS,
       GREATEST(m.AVAILABLE_HOURS - m.BOOKED_HOURS, 0) * l.COST_PER_DAY / 8 AS BENCH_COST,
       m.EARNED_HOURS, m.AI_ASSISTED_HOURS, m.AI_HOURS_SAVED,
       IFF(m.DELIVERY_HOURS > 0, m.EARNED_HOURS / m.DELIVERY_HOURS, NULL) AS PRODUCTIVITY_INDEX,
       l.COST_PER_DAY / 8 AS COST_RATE_PER_HOUR,
       l.TARGET_DELIVERY_PCT, l.TARGET_BID_PCT, l.TARGET_LEARNING_PCT, l.TARGET_ADMIN_PCT, l.TARGET_BENCH_PCT,
       m.PERSON_ID || '|' || m.MONTH_START::VARCHAR AS PERSON_MONTH_ID
FROM m
CROSS JOIN a
JOIN ACOCO_L2.CORE.DT_FISCAL_MONTH f ON f.MONTH_START = m.MONTH_START
JOIN ACOCO_L2.ONTOLOGY.ENT_PERSON p ON p.PERSON_ID = m.PERSON_ID
LEFT JOIN ACOCO_L2.ONTOLOGY.ENT_LEVEL l ON l.LEVEL = p.LEVEL
WHERE m.MONTH_START >= '2021-10-01' AND m.MONTH_START < DATE_TRUNC(month, a.AS_OF_DATE)
  AND (m.AVAILABLE_HOURS > 0 OR m.BOOKED_HOURS > 0);

-- Group x level x month: headcount at month end, hires, voluntary leavers (current level / group of the person).
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.WORKFORCE_PERFORMANCE.DT_HEADCOUNT_MONTH
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'MD group x level x month: opening / closing headcount, hires, voluntary leavers. Attrition = leavers / average headcount'
AS
SELECT f.MONTH_START, f.FISCAL_YEAR, f.FISCAL_PERIOD, p.MD_GROUP_ID, p.LEVEL, p.LEVEL_SORT,
       COUNT_IF(p.HIRE_DATE < f.MONTH_START AND (p.TERMINATION_DATE IS NULL OR p.TERMINATION_DATE >= f.MONTH_START)) AS OPENING_HEADCOUNT,
       COUNT_IF(p.HIRE_DATE <= f.MONTH_END AND (p.TERMINATION_DATE IS NULL OR p.TERMINATION_DATE > f.MONTH_END)) AS CLOSING_HEADCOUNT,
       COUNT_IF(p.HIRE_DATE BETWEEN f.MONTH_START AND f.MONTH_END) AS HIRES,
       COUNT_IF(p.TERMINATION_DATE BETWEEN f.MONTH_START AND f.MONTH_END) AS LEAVERS,
       COUNT_IF(p.TERMINATION_DATE BETWEEN f.MONTH_START AND f.MONTH_END AND p.SOURCE_SYSTEM = 'SIMULATED') AS VOLUNTARY_LEAVERS
FROM ACOCO_L2.CORE.DT_FISCAL_MONTH f
CROSS JOIN ACOCO_L2.ONTOLOGY.ENT_PERSON p
WHERE f.MONTH_START >= '2021-10-01' AND f.MONTH_START < (SELECT DATE_TRUNC(month, AS_OF_DATE) FROM ACOCO_L2.CORE.VW_AS_OF)
GROUP BY ALL;

-- Roll-off: people whose last assignment ends within 90 days of the as-of date with no later assignment (2.7).
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.WORKFORCE_PERFORMANCE.DT_ROLL_OFF
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Active person whose last assignment ends in (as-of, as-of + 90 days] with nothing after it; AI-skill level vs pipeline need'
AS
WITH a AS (SELECT AS_OF_DATE FROM ACOCO_L2.CORE.VW_AS_OF),
last_asg AS (
  SELECT r.PERSON_ID, r.PROJECT_ID, r.WBS_ID, r.ASSIGNMENT_ROLE, r.ASSIGNMENT_END
  FROM ACOCO_L2.ONTOLOGY.REL_PERSON_ASSIGNMENT r
  QUALIFY ROW_NUMBER() OVER (PARTITION BY r.PERSON_ID ORDER BY r.ASSIGNMENT_END DESC, r.ASSIGNMENT_ID) = 1
),
ai AS (
  SELECT ps.PERSON_ID, MAX(ps.PROFICIENCY) AS AI_SKILL_LEVEL
  FROM ACOCO_L2.ONTOLOGY.REL_PERSON_SKILL ps JOIN ACOCO_L2.ONTOLOGY.ENT_SKILL s ON s.SKILL_ID = ps.SKILL_ID AND s.IS_AGENTIC_AI
  GROUP BY 1
),
need AS (
  SELECT MD_GROUP_ID, MEDIAN(REQUIRED_AI_SKILL_LEVEL) AS PIPELINE_REQUIRED_AI_LEVEL, COUNT(*) AS OPEN_OPPORTUNITIES
  FROM ACOCO_L2.ONTOLOGY.ENT_OPPORTUNITY WHERE IS_OPEN_AS_OF GROUP BY 1
)
SELECT p.PERSON_ID, p.DISPLAY_NAME, p.MD_GROUP_ID, p.LEVEL, p.LEVEL_SORT, p.BILL_CODE,
       l.PROJECT_ID, l.WBS_ID, l.ASSIGNMENT_ROLE, l.ASSIGNMENT_END AS ROLL_OFF_DATE,
       DATEDIFF(day, a.AS_OF_DATE, l.ASSIGNMENT_END) AS DAYS_TO_ROLL_OFF,
       COALESCE(ai.AI_SKILL_LEVEL, 0) AS AI_SKILL_LEVEL,
       n.PIPELINE_REQUIRED_AI_LEVEL, n.OPEN_OPPORTUNITIES,
       COALESCE(ai.AI_SKILL_LEVEL, 0) < COALESCE(n.PIPELINE_REQUIRED_AI_LEVEL, 0) AS BELOW_PIPELINE_AI_LEVEL,
       p.SOURCE_SYSTEM
FROM last_asg l
CROSS JOIN a
JOIN ACOCO_L2.ONTOLOGY.ENT_PERSON p ON p.PERSON_ID = l.PERSON_ID AND p.IS_ACTIVE_AS_OF
LEFT JOIN ai ON ai.PERSON_ID = l.PERSON_ID
LEFT JOIN need n ON n.MD_GROUP_ID = p.MD_GROUP_ID
WHERE l.ASSIGNMENT_END > a.AS_OF_DATE AND l.ASSIGNMENT_END <= DATEADD(day, 90, a.AS_OF_DATE);
