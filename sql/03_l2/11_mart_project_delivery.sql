-- CP-05  Mart PROJECT_DELIVERY (PRD 7.2, 2.7): project financials, team, pyramid, asset use, health.
-- Journal conventions (CP-02): revenue = credit on GL 0041000000 to a WBS; people cost = activity allocation Z6105xx
-- debited to a WBS (hours in QUANTITY); AI-agent cost = GL 0094308000 with AGT_* activity type; overhead = GL
-- 0094233007 debited to a WBS (35 % of people activity cost).
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_ACOCO_BUILD;
CREATE SCHEMA IF NOT EXISTS ACOCO_L2.PROJECT_DELIVERY COMMENT = 'Mart: project P&L, earned value, team, pyramid, asset reuse, health';

-- Work package x month: actuals from the journal, hours / earned hours from timesheets, planned value.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.PROJECT_DELIVERY.DT_PROJECT_MONTH_FINANCIALS
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Work package x month: revenue, people / agent / overhead cost, billable and agent hours, earned and planned value'
AS
WITH j AS (
  SELECT j.WBS_ID, DATE_TRUNC(month, j.POSTING_DATE) AS MONTH_START,
         SUM(IFF(g.ACOCO_ROLE = 'REVENUE', -j.AMOUNT, 0))                                AS REVENUE,
         SUM(IFF(g.ACOCO_ROLE = 'PEOPLE_COST', j.AMOUNT, 0))                             AS PEOPLE_COST,
         SUM(IFF(g.ACOCO_ROLE = 'PEOPLE_COST', j.QUANTITY, 0))                           AS BILLABLE_HOURS_POSTED,
         SUM(IFF(g.ACOCO_ROLE = 'PEOPLE_PLAN_AGENT_COST' AND j.ACTIVITY_TYPE LIKE 'AGT%', j.AMOUNT, 0))   AS AGENT_COST,
         SUM(IFF(g.ACOCO_ROLE = 'PEOPLE_PLAN_AGENT_COST' AND j.ACTIVITY_TYPE LIKE 'AGT%', j.QUANTITY, 0)) AS AGENT_HOURS,
         SUM(IFF(g.ACOCO_ROLE = 'OVERHEAD', j.AMOUNT, 0))                                AS OVERHEAD_COST
  FROM ACOCO_L1.FINANCE.JOURNAL_ENTRY_ITEM j
  JOIN ACOCO_L1.ORGANISATION.GL_ACCOUNT g ON g.GL_ACCOUNT = j.GL_ACCOUNT
  WHERE j.WBS_ID IS NOT NULL
  GROUP BY 1, 2
),
t AS (
  SELECT WBS_ID, DATE_TRUNC(month, WEEK_START) AS MONTH_START,
         SUM(HOURS) AS DELIVERY_HOURS, SUM(EARNED_HOURS) AS EARNED_HOURS,
         SUM(AI_ASSISTED_HOURS) AS AI_ASSISTED_HOURS, SUM(AI_HOURS_SAVED) AS AI_HOURS_SAVED
  FROM ACOCO_L1.TIME.TIMESHEET_RECORD
  WHERE TIME_CATEGORY = 'DELIVERY'
  GROUP BY 1, 2
),
k AS (
  SELECT COALESCE(j.WBS_ID, t.WBS_ID) AS WBS_ID, COALESCE(j.MONTH_START, t.MONTH_START) AS MONTH_START,
         j.REVENUE, j.PEOPLE_COST, j.BILLABLE_HOURS_POSTED, j.AGENT_COST, j.AGENT_HOURS, j.OVERHEAD_COST,
         t.DELIVERY_HOURS, t.EARNED_HOURS, t.AI_ASSISTED_HOURS, t.AI_HOURS_SAVED
  FROM j FULL OUTER JOIN t ON t.WBS_ID = j.WBS_ID AND t.MONTH_START = j.MONTH_START
)
SELECT k.WBS_ID, w.PROJECT_ID, p.MD_GROUP_ID, p.CUSTOMER_ID, k.MONTH_START, f.FISCAL_YEAR, f.FISCAL_PERIOD,
       COALESCE(k.REVENUE, 0) AS REVENUE,
       COALESCE(k.PEOPLE_COST, 0) AS PEOPLE_COST,
       COALESCE(k.AGENT_COST, 0) AS AGENT_COST,
       COALESCE(k.OVERHEAD_COST, 0) AS OVERHEAD_COST,
       COALESCE(k.PEOPLE_COST, 0) + COALESCE(k.AGENT_COST, 0) + COALESCE(k.OVERHEAD_COST, 0) AS TOTAL_COST,
       COALESCE(k.REVENUE, 0) - (COALESCE(k.PEOPLE_COST, 0) + COALESCE(k.AGENT_COST, 0) + COALESCE(k.OVERHEAD_COST, 0)) AS MARGIN,
       COALESCE(k.BILLABLE_HOURS_POSTED, 0) AS BILLABLE_HOURS_POSTED,
       COALESCE(k.AGENT_HOURS, 0) AS AGENT_HOURS,
       COALESCE(k.DELIVERY_HOURS, 0) AS DELIVERY_HOURS,
       COALESCE(k.EARNED_HOURS, 0) AS EARNED_HOURS,
       COALESCE(k.AI_ASSISTED_HOURS, 0) AS AI_ASSISTED_HOURS,
       COALESCE(k.AI_HOURS_SAVED, 0) AS AI_HOURS_SAVED,
       -- earned value = sold cost share of the WP x share of the WP's planned hours earned this month
       p.SOLD_COST * (w.PLANNED_HOURS / NULLIF(p.PLANNED_HOURS, 0)) * COALESCE(k.EARNED_HOURS, 0) / NULLIF(w.PLANNED_HOURS, 0) AS EARNED_VALUE,
       -- planned value = WP sold cost spread evenly over its planned calendar days
       p.SOLD_COST * (w.PLANNED_HOURS / NULLIF(p.PLANNED_HOURS, 0))
         * GREATEST(DATEDIFF(day, GREATEST(w.PLANNED_START, k.MONTH_START), LEAST(w.PLANNED_END, LAST_DAY(k.MONTH_START))) + 1, 0)
         / NULLIF(DATEDIFF(day, w.PLANNED_START, w.PLANNED_END) + 1, 0) AS PLANNED_VALUE,
       p.DELIVERY_MODEL, p.SIZE_CLASS, p.WORK_TYPE, p.CONTRACT_TYPE,
       w.SOURCE_SYSTEM
FROM k
JOIN ACOCO_L2.ONTOLOGY.ENT_WORK_PACKAGE w ON w.WBS_ID = k.WBS_ID
JOIN ACOCO_L2.ONTOLOGY.ENT_PROJECT p ON p.PROJECT_ID = w.PROJECT_ID
JOIN ACOCO_L2.CORE.DT_FISCAL_MONTH f ON f.MONTH_START = k.MONTH_START
WHERE k.MONTH_START < (SELECT DATE_TRUNC(month, AS_OF_DATE) FROM ACOCO_L2.CORE.VW_AS_OF);

-- Project x person: hours and cost on the project (people cost from the person's activity allocations).
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.PROJECT_DELIVERY.DT_PROJECT_TEAM
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Project x person: delivery hours, earned hours, AI-assisted hours, first / last week booked'
AS
SELECT w.PROJECT_ID, t.PERSON_ID, p.LEVEL, p.LEVEL_SORT, p.BILL_CODE, p.MD_GROUP_ID AS PERSON_MD_GROUP_ID,
       SUM(t.HOURS) AS DELIVERY_HOURS, SUM(t.EARNED_HOURS) AS EARNED_HOURS,
       SUM(t.AI_ASSISTED_HOURS) AS AI_ASSISTED_HOURS,
       MIN(t.WEEK_START) AS FIRST_WEEK, MAX(t.WEEK_START) AS LAST_WEEK,
       SUM(t.HOURS) * ANY_VALUE(l.COST_PER_DAY) / 8 AS COST_AT_STANDARD_RATE,
       ANY_VALUE(p.SOURCE_SYSTEM) AS SOURCE_SYSTEM
FROM ACOCO_L1.TIME.TIMESHEET_RECORD t
JOIN ACOCO_L2.ONTOLOGY.ENT_WORK_PACKAGE w ON w.WBS_ID = t.WBS_ID
JOIN ACOCO_L2.ONTOLOGY.ENT_PERSON p ON p.PERSON_ID = t.PERSON_ID
LEFT JOIN ACOCO_L2.ONTOLOGY.ENT_LEVEL l ON l.LEVEL = p.LEVEL
WHERE t.TIME_CATEGORY = 'DELIVERY' AND t.WEEK_START < (SELECT AS_OF_DATE FROM ACOCO_L2.CORE.VW_AS_OF)
GROUP BY w.PROJECT_ID, t.PERSON_ID, p.LEVEL, p.LEVEL_SORT, p.BILL_CODE, p.MD_GROUP_ID;

-- Project x level: sold vs actual pyramid (share of hours) and the margin effect of the drift.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.PROJECT_DELIVERY.DT_PROJECT_PYRAMID
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Project x level: sold vs actual share of hours; pyramid drift and its margin effect = drift x actual hours x (bill - cost rate)'
AS
WITH sold AS (
  SELECT w.PROJECT_ID, lp.LEVEL, SUM(lp.PLANNED_HOURS) AS SOLD_HOURS
  FROM ACOCO_L1.PROJECTS.WBS_LEVEL_PLAN lp JOIN ACOCO_L2.ONTOLOGY.ENT_WORK_PACKAGE w ON w.WBS_ID = lp.WBS_ID
  GROUP BY 1, 2
),
act AS (
  SELECT PROJECT_ID, LEVEL, SUM(DELIVERY_HOURS) AS ACTUAL_HOURS FROM ACOCO_L2.PROJECT_DELIVERY.DT_PROJECT_TEAM GROUP BY 1, 2
),
x AS (
  SELECT COALESCE(s.PROJECT_ID, a.PROJECT_ID) AS PROJECT_ID, COALESCE(s.LEVEL, a.LEVEL) AS LEVEL,
         COALESCE(s.SOLD_HOURS, 0) AS SOLD_HOURS, COALESCE(a.ACTUAL_HOURS, 0) AS ACTUAL_HOURS
  FROM sold s FULL OUTER JOIN act a ON a.PROJECT_ID = s.PROJECT_ID AND a.LEVEL = s.LEVEL
)
SELECT x.PROJECT_ID, p.MD_GROUP_ID, x.LEVEL, l.LEVEL_SORT, x.SOLD_HOURS, x.ACTUAL_HOURS,
       x.SOLD_HOURS / NULLIF(SUM(x.SOLD_HOURS) OVER (PARTITION BY x.PROJECT_ID), 0)     AS SOLD_SHARE,
       x.ACTUAL_HOURS / NULLIF(SUM(x.ACTUAL_HOURS) OVER (PARTITION BY x.PROJECT_ID), 0) AS ACTUAL_SHARE,
       COALESCE(x.ACTUAL_HOURS / NULLIF(SUM(x.ACTUAL_HOURS) OVER (PARTITION BY x.PROJECT_ID), 0), 0)
         - COALESCE(x.SOLD_HOURS / NULLIF(SUM(x.SOLD_HOURS) OVER (PARTITION BY x.PROJECT_ID), 0), 0) AS PYRAMID_DRIFT,
       -(COALESCE(x.ACTUAL_HOURS / NULLIF(SUM(x.ACTUAL_HOURS) OVER (PARTITION BY x.PROJECT_ID), 0), 0)
         - COALESCE(x.SOLD_HOURS / NULLIF(SUM(x.SOLD_HOURS) OVER (PARTITION BY x.PROJECT_ID), 0), 0))
         * SUM(x.ACTUAL_HOURS) OVER (PARTITION BY x.PROJECT_ID) * l.COST_PER_DAY / 8 AS DRIFT_MARGIN_EFFECT,
       p.SOURCE_SYSTEM
FROM x
JOIN ACOCO_L2.ONTOLOGY.ENT_PROJECT p ON p.PROJECT_ID = x.PROJECT_ID
LEFT JOIN ACOCO_L2.ONTOLOGY.ENT_LEVEL l ON l.LEVEL = x.LEVEL;

CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.PROJECT_DELIVERY.DT_ASSET_USAGE_MONTH
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Asset x month x context (DELIVERY / BID): uses and ESTIMATED hours saved'
AS
SELECT u.ASSET_ID, DATE_TRUNC(month, u.USE_DATE) AS MONTH_START, f.FISCAL_YEAR, u.USE_CONTEXT,
       COALESCE(p.MD_GROUP_ID, o.MD_GROUP_ID) AS MD_GROUP_ID,
       COUNT(*) AS USES, COUNT(DISTINCT u.PROJECT_ID) AS PROJECTS, COUNT(DISTINCT u.OPPORTUNITY_ID) AS OPPORTUNITIES,
       SUM(u.HOURS_SAVED_ESTIMATED) AS HOURS_SAVED_ESTIMATED,
       'ESTIMATED' AS HOURS_SAVED_BASIS,
       ANY_VALUE(u.SOURCE_SYSTEM) AS SOURCE_SYSTEM
FROM ACOCO_L2.ONTOLOGY.REL_ASSET_USE u
JOIN ACOCO_L2.CORE.DT_FISCAL_MONTH f ON f.MONTH_START = DATE_TRUNC(month, u.USE_DATE)
LEFT JOIN ACOCO_L2.ONTOLOGY.ENT_PROJECT p ON p.PROJECT_ID = u.PROJECT_ID
LEFT JOIN ACOCO_L2.ONTOLOGY.ENT_OPPORTUNITY o ON o.OPPORTUNITY_ID = u.OPPORTUNITY_ID
GROUP BY 1, 2, 3, 4, 5;

-- Project health as of the last closed month: CPI, SPI, EAC, LD exposure, forecast margin, reuse.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.PROJECT_DELIVERY.DT_PROJECT_HEALTH
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Project to date: revenue, cost, margin, CPI = EV / AC, SPI = EV / PV, EAC = sold cost / CPI, LD exposure, forecast margin (2.7)'
AS
WITH td AS (
  SELECT PROJECT_ID, SUM(REVENUE) AS REVENUE_TD, SUM(PEOPLE_COST) AS PEOPLE_COST_TD, SUM(AGENT_COST) AS AGENT_COST_TD,
         SUM(OVERHEAD_COST) AS OVERHEAD_COST_TD, SUM(TOTAL_COST) AS ACTUAL_COST_TD, SUM(MARGIN) AS MARGIN_TD,
         SUM(EARNED_VALUE) AS EARNED_VALUE_TD, SUM(PLANNED_VALUE) AS PLANNED_VALUE_TD,
         SUM(DELIVERY_HOURS) AS DELIVERY_HOURS_TD, SUM(EARNED_HOURS) AS EARNED_HOURS_TD, SUM(AGENT_HOURS) AS AGENT_HOURS_TD,
         MAX(IFF(REVENUE <> 0 OR TOTAL_COST <> 0, MONTH_START, NULL)) AS LAST_ACTIVE_MONTH
  FROM ACOCO_L2.PROJECT_DELIVERY.DT_PROJECT_MONTH_FINANCIALS GROUP BY 1
),
reuse AS (SELECT PROJECT_ID, COUNT(*) AS ASSET_USES FROM ACOCO_L2.ONTOLOGY.REL_ASSET_USE WHERE PROJECT_ID IS NOT NULL GROUP BY 1),
h AS (
  SELECT p.*, td.REVENUE_TD, td.PEOPLE_COST_TD, td.AGENT_COST_TD, td.OVERHEAD_COST_TD, td.ACTUAL_COST_TD, td.MARGIN_TD,
         td.EARNED_VALUE_TD, td.PLANNED_VALUE_TD, td.DELIVERY_HOURS_TD, td.EARNED_HOURS_TD, td.AGENT_HOURS_TD, td.LAST_ACTIVE_MONTH,
         td.EARNED_VALUE_TD / NULLIF(td.ACTUAL_COST_TD, 0) AS CPI,
         td.EARNED_VALUE_TD / NULLIF(td.PLANNED_VALUE_TD, 0) AS SPI,
         COALESCE(r.ASSET_USES, 0) AS ASSET_USES
  FROM ACOCO_L2.ONTOLOGY.ENT_PROJECT p
  LEFT JOIN td ON td.PROJECT_ID = p.PROJECT_ID
  LEFT JOIN reuse r ON r.PROJECT_ID = p.PROJECT_ID
)
SELECT PROJECT_ID, MD_GROUP_ID, CUSTOMER_ID, SIZE_CLASS, WORK_TYPE, CONTRACT_TYPE, IS_FIXED_PRICE, DELIVERY_MODEL,
       STATUS_AS_OF, IS_STORY_PROJECT, PLANNED_START, PLANNED_END, FORECAST_END, FORECAST_SLIP_WEEKS,
       CONTRACT_VALUE, SOLD_COST, SOLD_MARGIN_PCT,
       REVENUE_TD, PEOPLE_COST_TD, AGENT_COST_TD, OVERHEAD_COST_TD, ACTUAL_COST_TD, MARGIN_TD,
       MARGIN_TD / NULLIF(REVENUE_TD, 0) AS MARGIN_PCT_TD,
       EARNED_VALUE_TD, PLANNED_VALUE_TD, CPI, SPI,
       SOLD_COST / NULLIF(CPI, 0) AS EAC,
       IFF(IS_FIXED_PRICE, CONTRACT_VALUE * LD_RATE_PCT_PER_WEEK / 100 * GREATEST(COALESCE(FORECAST_SLIP_WEEKS, 0), 0), 0) AS LD_EXPOSURE,
       (CONTRACT_VALUE - SOLD_COST / NULLIF(CPI, 0)
         - IFF(IS_FIXED_PRICE, CONTRACT_VALUE * LD_RATE_PCT_PER_WEEK / 100 * GREATEST(COALESCE(FORECAST_SLIP_WEEKS, 0), 0), 0))
         / NULLIF(CONTRACT_VALUE, 0) AS FORECAST_MARGIN_PCT,
       DELIVERY_HOURS_TD, EARNED_HOURS_TD, AGENT_HOURS_TD,
       EARNED_HOURS_TD / NULLIF(DELIVERY_HOURS_TD, 0) AS PRODUCTIVITY_INDEX,
       ASSET_USES, ASSET_USES > 0 AS REUSED_ASSET,
       LAST_ACTIVE_MONTH, SOURCE_SYSTEM
FROM h;
