-- CP-05  Mart PIPELINE_PRESALES (PRD 7.2, 2.7): opportunity economics, pursuit teams, monthly pre-sales.
-- Pursuit cost = people activity allocations posted to the opportunity's internal order (non-billable).
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_ACOCO_BUILD;
CREATE SCHEMA IF NOT EXISTS ACOCO_L2.PIPELINE_PRESALES COMMENT = 'Mart: pursuit cost, intensity, win-rate, bid-team skill fit';

-- Opportunity x person: bid hours booked and the person's best proficiency on each required skill at decision time.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.PIPELINE_PRESALES.DT_PURSUIT_TEAM
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Opportunity x pursuit-team member: role, level, bid hours on the internal order, required skills held at >= 3'
AS
WITH o AS (SELECT * FROM ACOCO_L2.ONTOLOGY.ENT_OPPORTUNITY WHERE STATUS_AS_OF <> 'NOT_CREATED'),
hrs AS (
  SELECT t.ORDER_ID, t.PERSON_ID, SUM(t.HOURS) AS BID_HOURS
  FROM ACOCO_L1.TIME.TIMESHEET_RECORD t WHERE t.TIME_CATEGORY = 'BID' GROUP BY 1, 2
),
skill_at AS (   -- latest assessment on or before the decision date (close date, or as-of for open bids)
  SELECT tm.OPPORTUNITY_ID, tm.PERSON_ID, ps.SKILL_ID, ps.PROFICIENCY
  FROM ACOCO_L2.ONTOLOGY.REL_PURSUIT_TEAM tm
  JOIN o ON o.OPPORTUNITY_ID = tm.OPPORTUNITY_ID
  JOIN ACOCO_L2.ONTOLOGY.REL_OPPORTUNITY_SKILL rs ON rs.OPPORTUNITY_ID = tm.OPPORTUNITY_ID
  JOIN ACOCO_L1.TALENT.PERSON_SKILL ps ON ps.PERSON_ID = tm.PERSON_ID AND ps.SKILL_ID = rs.SKILL_ID
   AND ps.ASSESSED_DATE <= COALESCE(o.CLOSED_DATE, (SELECT AS_OF_DATE FROM ACOCO_L2.CORE.VW_AS_OF))
  QUALIFY ROW_NUMBER() OVER (PARTITION BY tm.OPPORTUNITY_ID, tm.PERSON_ID, ps.SKILL_ID ORDER BY ps.ASSESSED_DATE DESC) = 1
),
held AS (
  SELECT OPPORTUNITY_ID, PERSON_ID, COUNT_IF(PROFICIENCY >= 3) AS REQUIRED_SKILLS_HELD
  FROM skill_at GROUP BY 1, 2
)
SELECT tm.OPPORTUNITY_ID, tm.PERSON_ID, tm.TEAM_ROLE, p.LEVEL, p.LEVEL_SORT, p.BILL_CODE, p.MD_GROUP_ID AS PERSON_MD_GROUP_ID,
       COALESCE(h.BID_HOURS, 0) AS BID_HOURS,
       COALESCE(h.BID_HOURS, 0) * l.COST_PER_DAY / 8 AS BID_COST_AT_STANDARD_RATE,
       COALESCE(k.REQUIRED_SKILLS_HELD, 0) AS REQUIRED_SKILLS_HELD,
       tm.SOURCE_SYSTEM
FROM ACOCO_L2.ONTOLOGY.REL_PURSUIT_TEAM tm
JOIN o ON o.OPPORTUNITY_ID = tm.OPPORTUNITY_ID
JOIN ACOCO_L2.ONTOLOGY.ENT_PERSON p ON p.PERSON_ID = tm.PERSON_ID
LEFT JOIN ACOCO_L2.ONTOLOGY.ENT_LEVEL l ON l.LEVEL = p.LEVEL
LEFT JOIN hrs h ON h.ORDER_ID = o.ORDER_ID AND h.PERSON_ID = tm.PERSON_ID
LEFT JOIN held k ON k.OPPORTUNITY_ID = tm.OPPORTUNITY_ID AND k.PERSON_ID = tm.PERSON_ID;

-- One row per opportunity: pursuit hours / cost, intensity vs size-class median, team skill fit, outcome.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.PIPELINE_PRESALES.DT_OPPORTUNITY_FACT
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'Opportunity: pursuit hours and cost (journal on the internal order), intensity = cost / estimated value, bid-team skill fit, outcome'
AS
WITH o AS (SELECT * FROM ACOCO_L2.ONTOLOGY.ENT_OPPORTUNITY WHERE STATUS_AS_OF <> 'NOT_CREATED'),
cost AS (
  SELECT j.ORDER_ID, SUM(j.AMOUNT) AS PURSUIT_COST, SUM(j.QUANTITY) AS PURSUIT_HOURS_POSTED
  FROM ACOCO_L1.FINANCE.JOURNAL_ENTRY_ITEM j
  JOIN ACOCO_L1.ORGANISATION.GL_ACCOUNT g ON g.GL_ACCOUNT = j.GL_ACCOUNT AND g.ACOCO_ROLE = 'PEOPLE_COST'
  WHERE j.ORDER_ID IS NOT NULL AND j.DEBIT_CREDIT = 'S'
  GROUP BY 1
),
team AS (
  SELECT OPPORTUNITY_ID, COUNT(*) AS TEAM_SIZE,
         MAX(IFF(TEAM_ROLE = 'LEAD', PERSON_ID, NULL)) AS LEAD_PERSON_ID
  FROM ACOCO_L2.PIPELINE_PRESALES.DT_PURSUIT_TEAM GROUP BY 1
),
bid_ts AS (   -- every bid hour booked to the internal order, by team members or not
  SELECT ORDER_ID, SUM(HOURS) AS PURSUIT_HOURS, COUNT(DISTINCT PERSON_ID) AS PEOPLE_BOOKING
  FROM ACOCO_L1.TIME.TIMESHEET_RECORD WHERE TIME_CATEGORY = 'BID' GROUP BY 1
),
req AS (SELECT OPPORTUNITY_ID, COUNT(*) AS REQUIRED_SKILLS FROM ACOCO_L2.ONTOLOGY.REL_OPPORTUNITY_SKILL GROUP BY 1),
covered AS (   -- required skills held at >= 3 by at least one member at decision time
  SELECT OPPORTUNITY_ID, COUNT(DISTINCT SKILL_ID) AS SKILLS_COVERED
  FROM (
    SELECT rs.OPPORTUNITY_ID, rs.SKILL_ID, ps.PROFICIENCY
    FROM ACOCO_L2.ONTOLOGY.REL_OPPORTUNITY_SKILL rs
    JOIN o ON o.OPPORTUNITY_ID = rs.OPPORTUNITY_ID
    JOIN ACOCO_L2.ONTOLOGY.REL_PURSUIT_TEAM tm ON tm.OPPORTUNITY_ID = rs.OPPORTUNITY_ID
    JOIN ACOCO_L1.TALENT.PERSON_SKILL ps ON ps.PERSON_ID = tm.PERSON_ID AND ps.SKILL_ID = rs.SKILL_ID
     AND ps.ASSESSED_DATE <= COALESCE(o.CLOSED_DATE, (SELECT AS_OF_DATE FROM ACOCO_L2.CORE.VW_AS_OF))
    QUALIFY ROW_NUMBER() OVER (PARTITION BY rs.OPPORTUNITY_ID, tm.PERSON_ID, rs.SKILL_ID ORDER BY ps.ASSESSED_DATE DESC) = 1
  )
  WHERE PROFICIENCY >= 3
  GROUP BY 1
),
reuse AS (SELECT OPPORTUNITY_ID, COUNT(*) AS ASSET_USES FROM ACOCO_L2.ONTOLOGY.REL_ASSET_USE WHERE OPPORTUNITY_ID IS NOT NULL GROUP BY 1),
f AS (
  SELECT o.OPPORTUNITY_ID, o.CUSTOMER_ID, o.MD_GROUP_ID, o.SIZE_CLASS, o.WORK_TYPE, o.ESTIMATED_VALUE, o.IS_FIXED_PRICE,
         o.CREATED_DATE, o.CLOSED_DATE, o.EXPECTED_START_DATE, o.STAGE, o.PROBABILITY_PCT, o.STATUS_AS_OF, o.IS_OPEN_AS_OF,
         o.REQUIRED_AI_SKILL_LEVEL, o.ORDER_ID, o.PROJECT_ID,
         YEAR(DATEADD(month, 3, COALESCE(o.CLOSED_DATE, o.CREATED_DATE))) AS DECISION_FISCAL_YEAR,
         COALESCE(c.PURSUIT_COST, 0) AS PURSUIT_COST, COALESCE(bt.PURSUIT_HOURS, 0) AS PURSUIT_HOURS, bt.PEOPLE_BOOKING,
         COALESCE(c.PURSUIT_HOURS_POSTED, 0) AS PURSUIT_HOURS_POSTED,
         COALESCE(c.PURSUIT_COST, 0) / NULLIF(o.ESTIMATED_VALUE, 0) AS PURSUIT_INTENSITY,
         t.TEAM_SIZE, t.LEAD_PERSON_ID,
         r.REQUIRED_SKILLS, COALESCE(cv.SKILLS_COVERED, 0) AS SKILLS_COVERED,
         COALESCE(cv.SKILLS_COVERED, 0) / NULLIF(r.REQUIRED_SKILLS, 0) AS SKILL_FIT,
         COALESCE(ru.ASSET_USES, 0) AS ASSET_USES,
         o.STATUS_AS_OF IN ('WON', 'LOST') AS IS_CLOSED, o.STATUS_AS_OF = 'WON' AS IS_WON,
         o.SOURCE_SYSTEM
  FROM o
  LEFT JOIN cost c ON c.ORDER_ID = o.ORDER_ID
  LEFT JOIN team t ON t.OPPORTUNITY_ID = o.OPPORTUNITY_ID
  LEFT JOIN bid_ts bt ON bt.ORDER_ID = o.ORDER_ID
  LEFT JOIN req r ON r.OPPORTUNITY_ID = o.OPPORTUNITY_ID
  LEFT JOIN covered cv ON cv.OPPORTUNITY_ID = o.OPPORTUNITY_ID
  LEFT JOIN reuse ru ON ru.OPPORTUNITY_ID = o.OPPORTUNITY_ID
)
SELECT f.*,
       MEDIAN(IFF(IS_CLOSED, PURSUIT_INTENSITY, NULL)) OVER (PARTITION BY SIZE_CLASS) AS SIZE_CLASS_MEDIAN_INTENSITY,
       PURSUIT_INTENSITY > MEDIAN(IFF(IS_CLOSED, PURSUIT_INTENSITY, NULL)) OVER (PARTITION BY SIZE_CLASS) AS IS_ABOVE_MEDIAN_INTENSITY,
       CASE WHEN SKILL_FIT >= 0.8 THEN 'HIGH (>= 0.8)' WHEN SKILL_FIT >= 0.5 THEN 'MEDIUM (0.5-0.8)' ELSE 'LOW (< 0.5)' END AS SKILL_FIT_BAND
FROM f;

-- MD group x month: bids opened / decided, won value, pursuit cost.
CREATE OR REPLACE DYNAMIC TABLE ACOCO_L2.PIPELINE_PRESALES.DT_PRESALES_MONTH
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ACOCO_BUILD
  COMMENT = 'MD group x month: opportunities created, won, lost, won value, pursuit cost of decided bids. Win-rate = won / (won + lost)'
AS
WITH m AS (SELECT MONTH_START, MONTH_END, FISCAL_YEAR, FISCAL_PERIOD FROM ACOCO_L2.CORE.DT_FISCAL_MONTH
           WHERE MONTH_START >= '2021-10-01' AND MONTH_START < (SELECT DATE_TRUNC(month, AS_OF_DATE) FROM ACOCO_L2.CORE.VW_AS_OF)),
g AS (SELECT MD_GROUP_ID FROM ACOCO_L2.ONTOLOGY.ENT_MD_GROUP)
SELECT m.MONTH_START, m.FISCAL_YEAR, m.FISCAL_PERIOD, g.MD_GROUP_ID,
       COUNT_IF(o.CREATED_DATE BETWEEN m.MONTH_START AND m.MONTH_END) AS OPPORTUNITIES_CREATED,
       COUNT_IF(o.IS_WON AND o.CLOSED_DATE BETWEEN m.MONTH_START AND m.MONTH_END) AS WON,
       COUNT_IF(o.STATUS_AS_OF = 'LOST' AND o.CLOSED_DATE BETWEEN m.MONTH_START AND m.MONTH_END) AS LOST,
       SUM(IFF(o.IS_WON AND o.CLOSED_DATE BETWEEN m.MONTH_START AND m.MONTH_END, o.ESTIMATED_VALUE, 0)) AS WON_VALUE,
       SUM(IFF(o.IS_CLOSED AND o.CLOSED_DATE BETWEEN m.MONTH_START AND m.MONTH_END, o.PURSUIT_COST, 0)) AS PURSUIT_COST_DECIDED,
       SUM(IFF(o.IS_CLOSED AND o.CLOSED_DATE BETWEEN m.MONTH_START AND m.MONTH_END, o.PURSUIT_HOURS, 0)) AS PURSUIT_HOURS_DECIDED
FROM m CROSS JOIN g
LEFT JOIN ACOCO_L2.PIPELINE_PRESALES.DT_OPPORTUNITY_FACT o ON o.MD_GROUP_ID = g.MD_GROUP_ID
GROUP BY ALL;
