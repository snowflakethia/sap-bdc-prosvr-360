-- P0 / P3: group x month capacity, bench and admin vs ceilings.
CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_CAPACITY_MONTH
  COMMENT = 'MD group x month: available hours, five-way shares, bench cost, excess bench (above the 2 % allowance) cost'
AS
SELECT c.MD_GROUP_ID, c.MONTH_START, c.FISCAL_YEAR, c.FISCAL_PERIOD,
       SUM(c.AVAILABLE_HOURS) AS AVAILABLE_HOURS,
       ROUND(100 * SUM(c.DELIVERY_HOURS) / NULLIF(SUM(c.AVAILABLE_HOURS), 0), 1) AS DELIVERY_PCT,
       ROUND(100 * SUM(c.BID_HOURS) / NULLIF(SUM(c.AVAILABLE_HOURS), 0), 1) AS BID_PCT,
       ROUND(100 * SUM(c.LEARNING_HOURS) / NULLIF(SUM(c.AVAILABLE_HOURS), 0), 1) AS LEARNING_PCT,
       ROUND(100 * SUM(c.ADMIN_HOURS) / NULLIF(SUM(c.AVAILABLE_HOURS), 0), 1) AS ADMIN_PCT,
       ROUND(100 * SUM(c.BENCH_HOURS) / NULLIF(SUM(c.AVAILABLE_HOURS), 0), 1) AS BENCH_PCT,
       ROUND(SUM(c.BENCH_COST), 0) AS BENCH_COST,
       ROUND(SUM(c.BENCH_COST * c.EXCESS_BENCH_HOURS / NULLIF(c.BENCH_HOURS, 0)), 0) AS EXCESS_BENCH_COST
FROM ACOCO_L2.PORTFOLIO_360.DT_CAPACITY_MIX_MONTH c
GROUP BY c.MD_GROUP_ID, c.MONTH_START, c.FISCAL_YEAR, c.FISCAL_PERIOD;

-- P2: one project's months (plan vs actual, earned value).
CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_PROJECT_MONTH
  COMMENT = 'Project x month: revenue, cost, margin, planned / earned value, delivery / earned / agent hours'
AS
SELECT PROJECT_ID, MD_GROUP_ID, MONTH_START, FISCAL_YEAR,
       ROUND(SUM(REVENUE), 0) AS REVENUE, ROUND(SUM(TOTAL_COST), 0) AS TOTAL_COST, ROUND(SUM(MARGIN), 0) AS MARGIN,
       ROUND(SUM(PLANNED_VALUE), 0) AS PLANNED_VALUE, ROUND(SUM(EARNED_VALUE), 0) AS EARNED_VALUE,
       ROUND(SUM(DELIVERY_HOURS), 1) AS DELIVERY_HOURS, ROUND(SUM(EARNED_HOURS), 1) AS EARNED_HOURS,
       ROUND(SUM(AGENT_HOURS), 1) AS AGENT_HOURS
FROM ACOCO_L2.PROJECT_DELIVERY.DT_PROJECT_MONTH_FINANCIALS
GROUP BY PROJECT_ID, MD_GROUP_ID, MONTH_START, FISCAL_YEAR;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_PROJECT_WORK_PACKAGES
  COMMENT = 'Work packages of a project: plan, forecast slip, productivity, critical path, reused asset'
AS
SELECT WBS_ID, PROJECT_ID, WBS_NAME, WORK_TYPE, PLANNED_HOURS, PLANNED_START, PLANNED_END, FORECAST_END,
       FORECAST_SLIP_WEEKS, TEAM_PRODUCTIVITY, IS_CRITICAL_PATH, REUSED_ASSET_ID
FROM ACOCO_L2.ONTOLOGY.ENT_WORK_PACKAGE;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_PROJECT_PYRAMID
  COMMENT = 'Project x level: sold vs actual share of hours, pyramid drift and its margin effect'
AS
SELECT PROJECT_ID, LEVEL, LEVEL_SORT, ROUND(SOLD_HOURS, 0) AS SOLD_HOURS, ROUND(ACTUAL_HOURS, 0) AS ACTUAL_HOURS,
       ROUND(100 * SOLD_SHARE, 1) AS SOLD_SHARE_PCT, ROUND(100 * ACTUAL_SHARE, 1) AS ACTUAL_SHARE_PCT,
       ROUND(100 * PYRAMID_DRIFT, 1) AS DRIFT_PTS, ROUND(DRIFT_MARGIN_EFFECT, 0) AS DRIFT_MARGIN_EFFECT
FROM ACOCO_L2.PROJECT_DELIVERY.DT_PROJECT_PYRAMID;

-- P1: project revenue in a fiscal year (Pareto) and fixed-price watch list.
CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_PROJECT_REVENUE_FY
  COMMENT = 'Project x fiscal year: revenue and margin (Pareto input)'
AS
SELECT m.PROJECT_ID, m.MD_GROUP_ID, m.FISCAL_YEAR, p.SIZE_CLASS, p.CONTRACT_TYPE,
       ROUND(SUM(m.REVENUE), 0) AS REVENUE, ROUND(SUM(m.MARGIN), 0) AS MARGIN
FROM ACOCO_L2.PROJECT_DELIVERY.DT_PROJECT_MONTH_FINANCIALS m
JOIN ACOCO_L2.ONTOLOGY.ENT_PROJECT p ON p.PROJECT_ID = m.PROJECT_ID
GROUP BY m.PROJECT_ID, m.MD_GROUP_ID, m.FISCAL_YEAR, p.SIZE_CLASS, p.CONTRACT_TYPE;

-- P5: win-rate segments of decided bids.
CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_WIN_RATE_SEGMENTS
  COMMENT = 'Decided bids: win-rate by size class x above / below median pursuit intensity and by skill-fit band'
AS
SELECT MD_GROUP_ID, DECISION_FISCAL_YEAR AS FISCAL_YEAR, SIZE_CLASS,
       IFF(IS_ABOVE_MEDIAN_INTENSITY, 'Above median', 'Below median') AS INTENSITY_BAND, SKILL_FIT_BAND,
       COUNT(*) AS BIDS, SUM(IFF(IS_WON, 1, 0)) AS WON, ROUND(SUM(PURSUIT_COST), 0) AS PURSUIT_COST,
       ROUND(SUM(IFF(IS_WON, ESTIMATED_VALUE, 0)), 0) AS WON_VALUE
FROM ACOCO_L2.PIPELINE_PRESALES.DT_OPPORTUNITY_FACT
WHERE IS_CLOSED
GROUP BY MD_GROUP_ID, DECISION_FISCAL_YEAR, SIZE_CLASS, IS_ABOVE_MEDIAN_INTENSITY, SKILL_FIT_BAND;

-- P6: AI-skilled people with no AI use in the last closed quarter.
CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_AI_SKILLED_INACTIVE
  COMMENT = 'People with AI-skill >= 3 and no AI tool use in the quarter (FY26 Q4 = Jul-Sep 2026 is the latest)'
AS
SELECT d.PERSON_ID, p.DISPLAY_NAME, d.MD_GROUP_ID, d.LEVEL, d.FISCAL_YEAR, d.FISCAL_QUARTER, d.AI_SKILL_LEVEL,
       ROUND(SUM(d.DELIVERY_HOURS), 0) AS DELIVERY_HOURS,
       ROUND(SUM(d.EARNED_HOURS) / NULLIF(SUM(d.DELIVERY_HOURS), 0), 3) AS PRODUCTIVITY_INDEX
FROM ACOCO_L2.AI_ADOPTION.DT_AI_PRODUCTIVITY d
JOIN ACOCO_L2.ONTOLOGY.ENT_PERSON p ON p.PERSON_ID = d.PERSON_ID AND p.IS_ACTIVE_AS_OF
WHERE d.AI_SKILLED_INACTIVE
GROUP BY d.PERSON_ID, p.DISPLAY_NAME, d.MD_GROUP_ID, d.LEVEL, d.FISCAL_YEAR, d.FISCAL_QUARTER, d.AI_SKILL_LEVEL;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_DELIVERY_MODEL_FY
  COMMENT = 'MD group x fiscal year x delivery model: revenue, margin %, median CPI of projects active that year'
AS
SELECT m.MD_GROUP_ID, m.FISCAL_YEAR, p.DELIVERY_MODEL,
       ROUND(SUM(m.REVENUE), 0) AS REVENUE, ROUND(100 * SUM(m.MARGIN) / NULLIF(SUM(m.REVENUE), 0), 1) AS MARGIN_PCT,
       COUNT(DISTINCT m.PROJECT_ID) AS PROJECTS,
       ROUND(MEDIAN(h.CPI), 3) AS MEDIAN_CPI
FROM ACOCO_L2.PROJECT_DELIVERY.DT_PROJECT_MONTH_FINANCIALS m
JOIN ACOCO_L2.ONTOLOGY.ENT_PROJECT p ON p.PROJECT_ID = m.PROJECT_ID
JOIN ACOCO_L2.PROJECT_DELIVERY.DT_PROJECT_HEALTH h ON h.PROJECT_ID = m.PROJECT_ID
GROUP BY m.MD_GROUP_ID, m.FISCAL_YEAR, p.DELIVERY_MODEL;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_AI_COST_FY
  COMMENT = 'MD group x fiscal year x AI tool: assistant spend and agent cost charged to projects'
AS
SELECT MD_GROUP_ID, FISCAL_YEAR, AI_TOOL_ID, TOOL_KIND,
       ROUND(SUM(ASSISTANT_COST), 0) AS ASSISTANT_COST, ROUND(SUM(AGENT_COST), 0) AS AGENT_COST,
       ROUND(SUM(AGENT_HOURS), 0) AS AGENT_HOURS
FROM ACOCO_L2.AI_ADOPTION.DT_AI_COST_MONTH
GROUP BY MD_GROUP_ID, FISCAL_YEAR, AI_TOOL_ID, TOOL_KIND;

-- P4: skill supply (people at >= 3) by family and group.
CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_SKILL_SUPPLY
  COMMENT = 'MD group x skill: active people holding the skill at proficiency >= 3 (latest assessment)'
AS
SELECT p.MD_GROUP_ID, s.SKILL_FAMILY, s.SKILL_NAME, COUNT(DISTINCT ps.PERSON_ID) AS PEOPLE_AT_3_PLUS
FROM ACOCO_L2.ONTOLOGY.REL_PERSON_SKILL ps
JOIN ACOCO_L2.ONTOLOGY.ENT_PERSON p ON p.PERSON_ID = ps.PERSON_ID AND p.IS_ACTIVE_AS_OF
JOIN ACOCO_L2.ONTOLOGY.ENT_SKILL s ON s.SKILL_ID = ps.SKILL_ID
WHERE ps.PROFICIENCY >= 3
GROUP BY p.MD_GROUP_ID, s.SKILL_FAMILY, s.SKILL_NAME;

-- P11: harvest and reuse by fiscal year, CPI with / without reuse.
CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_ASSET_FY
  COMMENT = 'MD group x fiscal year (of forecast end): closed projects, harvested, harvest rate, reuse rate, median CPI with / without reuse'
AS
WITH h AS (SELECT DISTINCT SOURCE_PROJECT_ID FROM ACOCO_L2.ONTOLOGY.ENT_ASSET)
SELECT p.MD_GROUP_ID, YEAR(DATEADD(month, 3, COALESCE(p.FORECAST_END, p.PLANNED_END))) AS FISCAL_YEAR,
       COUNT_IF(p.STATUS_AS_OF = 'CLOSED') AS CLOSED_PROJECTS,
       COUNT_IF(p.STATUS_AS_OF = 'CLOSED' AND h.SOURCE_PROJECT_ID IS NOT NULL) AS HARVESTED,
       ROUND(100 * COUNT_IF(p.STATUS_AS_OF = 'CLOSED' AND h.SOURCE_PROJECT_ID IS NOT NULL) / NULLIF(COUNT_IF(p.STATUS_AS_OF = 'CLOSED'), 0), 1) AS HARVEST_RATE_PCT,
       ROUND(100 * AVG(IFF(x.REUSED_ASSET, 1, 0)), 1) AS REUSE_RATE_PCT,
       ROUND(MEDIAN(IFF(x.REUSED_ASSET, x.CPI, NULL)), 3) AS MEDIAN_CPI_WITH_REUSE,
       ROUND(MEDIAN(IFF(NOT x.REUSED_ASSET, x.CPI, NULL)), 3) AS MEDIAN_CPI_WITHOUT_REUSE
FROM ACOCO_L2.ONTOLOGY.ENT_PROJECT p
JOIN ACOCO_L2.PROJECT_DELIVERY.DT_PROJECT_HEALTH x ON x.PROJECT_ID = p.PROJECT_ID
LEFT JOIN h ON h.SOURCE_PROJECT_ID = p.PROJECT_ID
WHERE p.STATUS_AS_OF <> 'NOT_STARTED'
GROUP BY 1, 2;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_ASSET_TOP_REUSED
  COMMENT = 'Assets by recorded uses and ESTIMATED hours saved'
AS
SELECT a.ASSET_ID, a.ASSET_TITLE, a.ASSET_TYPE, a.WORK_TYPE, a.SOURCE_PROJECT_ID, COUNT(u.ASSET_USE_ID) AS USES,
       ROUND(SUM(u.HOURS_SAVED_ESTIMATED), 0) AS HOURS_SAVED_ESTIMATED
FROM ACOCO_L2.ONTOLOGY.ENT_ASSET a
LEFT JOIN ACOCO_L2.ONTOLOGY.REL_ASSET_USE u ON u.ASSET_ID = a.ASSET_ID
GROUP BY a.ASSET_ID, a.ASSET_TITLE, a.ASSET_TYPE, a.WORK_TYPE, a.SOURCE_PROJECT_ID;

-- C4 / P8: ontology graph and lineage.
