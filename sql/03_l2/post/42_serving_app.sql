-- P0 / C1: pillar scorecard per fiscal year for each MD group and the firm (SCOPE = group id or 'ALL').
CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_SCORECARD_FY
  COMMENT = 'Scope (MD group id or ALL) x fiscal year: the three-pillar scorecard; ratios computed from sums, so ALL is correct firm-wide'
AS
WITH b AS (
  SELECT MD_GROUP_ID, FISCAL_YEAR, MONTH_START, REVENUE, MARGIN, AVAILABLE_HOURS, DELIVERY_HOURS, BID_HOURS, LEARNING_HOURS,
         ADMIN_HOURS, BENCH_HOURS, BENCH_COST, CLOSING_HEADCOUNT, VOLUNTARY_LEAVERS, WON, LOST, WON_VALUE, PURSUIT_COST_DECIDED, AI_COST
  FROM ACOCO_L2.PORTFOLIO_360.DT_PORTFOLIO_MONTH
),
s AS (
  SELECT MD_GROUP_ID AS SCOPE, b.* EXCLUDE (MD_GROUP_ID) FROM b
  UNION ALL SELECT 'ALL', b.* EXCLUDE (MD_GROUP_ID) FROM b
),
risk AS (SELECT MD_GROUP_ID, COUNT_IF(RISK_TYPE = 'PROJECT_FORECAST_LOSS') AS LOSS_PROJECTS FROM ACOCO_L2.PORTFOLIO_360.DT_RISK_REGISTER GROUP BY 1),
reuse AS (SELECT MD_GROUP_ID, FISCAL_YEAR, REUSE_RATE_PCT, HARVEST_RATE_PCT FROM ACOCO_L2.SERVING.VW_ASSET_FY)
SELECT s.SCOPE, s.FISCAL_YEAR,
       ROUND(SUM(s.REVENUE), 0) AS REVENUE,
       ROUND(100 * SUM(s.MARGIN) / NULLIF(SUM(s.REVENUE), 0), 1) AS MARGIN_PCT,
       ROUND(100 * SUM(s.DELIVERY_HOURS) / NULLIF(SUM(s.AVAILABLE_HOURS), 0), 1) AS DELIVERY_PCT,
       ROUND(100 * SUM(s.BID_HOURS) / NULLIF(SUM(s.AVAILABLE_HOURS), 0), 1) AS BID_PCT,
       ROUND(100 * SUM(s.LEARNING_HOURS) / NULLIF(SUM(s.AVAILABLE_HOURS), 0), 1) AS LEARNING_PCT,
       ROUND(100 * SUM(s.ADMIN_HOURS) / NULLIF(SUM(s.AVAILABLE_HOURS), 0), 1) AS ADMIN_PCT,
       ROUND(100 * SUM(s.BENCH_HOURS) / NULLIF(SUM(s.AVAILABLE_HOURS), 0), 1) AS BENCH_PCT,
       ROUND(SUM(s.BENCH_COST), 0) AS BENCH_COST,
       ROUND(100 * SUM(s.VOLUNTARY_LEAVERS) / NULLIF(SUM(s.CLOSING_HEADCOUNT) / COUNT(DISTINCT s.MONTH_START), 0), 1) AS ATTRITION_PCT,
       ROUND(SUM(IFF(s.MONTH_START = (SELECT MAX(MONTH_START) FROM b x WHERE x.FISCAL_YEAR = s.FISCAL_YEAR), s.CLOSING_HEADCOUNT, 0)), 0) AS HEADCOUNT_END,
       ROUND(100 * SUM(s.WON) / NULLIF(SUM(s.WON) + SUM(s.LOST), 0), 1) AS WIN_RATE_PCT,
       ROUND(SUM(s.PURSUIT_COST_DECIDED) / NULLIF(SUM(s.WON_VALUE), 0), 4) AS PURSUIT_COST_PER_WON_USD,
       ROUND(SUM(s.WON_VALUE), 0) AS WON_VALUE,
       ROUND(SUM(s.AI_COST), 0) AS AI_COST,
       ANY_VALUE(IFF(s.SCOPE = 'ALL', NULL, r.REUSE_RATE_PCT)) AS REUSE_RATE_PCT
FROM s
LEFT JOIN reuse r ON r.MD_GROUP_ID = s.SCOPE AND r.FISCAL_YEAR = s.FISCAL_YEAR
GROUP BY s.SCOPE, s.FISCAL_YEAR;
