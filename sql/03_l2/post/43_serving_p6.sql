USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_ACOCO_BUILD;

-- Q2: WPS, pillars, billability and utilization by level; firm per FY and pooled, MD groups pooled FY24-26 (spec 3.1).
CREATE OR REPLACE VIEW ACOCO_L2.REASONING.WPS_BY_LEVEL
  COMMENT = 'Q2: median / P25 / P75 WPS and pillars, median billability and utilization, TM coverage by level; SCOPE = FIRM or MD group (groups pooled FY24-26); cells < 15 people or < 30 person-quarters flagged'
AS
WITH w AS (
  SELECT * FROM ACOCO_L2.WORKFORCE_PERFORMANCE.DT_PERSON_QUARTER_WPS WHERE FISCAL_YEAR BETWEEN 2024 AND 2026
),
cells AS (
  SELECT 'FIRM' AS SCOPE, 'FY' || RIGHT(FISCAL_YEAR::VARCHAR, 2) AS FISCAL_YEARS, w.* FROM w
  UNION ALL SELECT 'FIRM', 'FY24-26', w.* FROM w
  UNION ALL SELECT MD_GROUP_ID, 'FY24-26 pooled', w.* FROM w
)
SELECT SCOPE, FISCAL_YEARS, LEVEL, LEVEL_SORT,
       COUNT(DISTINCT PERSON_ID) AS PEOPLE, COUNT(*) AS PERSON_QUARTERS,
       IFF(COUNT(DISTINCT PERSON_ID) >= 15 AND COUNT(*) >= 30, 'OK',
           'INSUFFICIENT_DATA (' || COUNT(DISTINCT PERSON_ID) || ' people)') AS CELL_STATUS,
       MEDIAN(WPS) AS WPS_MEDIAN, PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY WPS) AS WPS_P25,
       PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY WPS) AS WPS_P75,
       MEDIAN(VC) AS VC_MEDIAN, MEDIAN(OE) AS OE_MEDIAN, MEDIAN(PD) AS PD_MEDIAN, MEDIAN(TM) AS TM_MEDIAN,
       PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY VC) AS VC_P25, PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY VC) AS VC_P75,
       PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY OE) AS OE_P25, PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY OE) AS OE_P75,
       PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY PD) AS PD_P25, PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY PD) AS PD_P75,
       MEDIAN(BILLABILITY) AS BILLABILITY_MEDIAN, MEDIAN(UTILIZATION) AS UTILIZATION_MEDIAN,
       ANY_VALUE(BILL_TARGET) AS BILLABILITY_TARGET, ANY_VALUE(UTIL_TARGET) AS UTILIZATION_TARGET,
       COUNT_IF(TM_APPLIES) / COUNT(*) AS TM_COVERAGE,
       -- the page discloses that EFF feeds both VC and OE (spec 2.4)
       CORR(VC, OE) AS VC_OE_CORRELATION
FROM cells
GROUP BY SCOPE, FISCAL_YEARS, LEVEL, LEVEL_SORT;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_WPS_BY_LEVEL
  COMMENT = 'Q2 / P6 section B: WPS and pillars by level (median, IQR), billability vs utilization, TM coverage'
AS SELECT * FROM ACOCO_L2.REASONING.WPS_BY_LEVEL;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_PERSON_QUARTER_WPS
  COMMENT = 'P6 / P4: person x quarter WPS with inputs, scores and pillars, with name and group'
AS
SELECT w.*, p.DISPLAY_NAME, g.MD_GROUP_NAME AS MD_GROUP
FROM ACOCO_L2.WORKFORCE_PERFORMANCE.DT_PERSON_QUARTER_WPS w
JOIN ACOCO_L2.ONTOLOGY.ENT_PERSON p ON p.PERSON_ID = w.PERSON_ID
JOIN ACOCO_L2.ONTOLOGY.ENT_MD_GROUP g ON g.MD_GROUP_ID = w.MD_GROUP_ID;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_TOKEN_WPS_TEST
  COMMENT = 'R15 (Q3): token intensity vs WPS within level, rho with 90 % CI; associated with, not causes'
AS
SELECT SCOPE, FISCAL_YEARS, STRATUM, EXPOSURE, OUTCOME, ROUND(RHO, 4) AS RHO, ROUND(CI_LOW, 4) AS CI_LOW,
       ROUND(CI_HIGH, 4) AS CI_HIGH, CI_EXCLUDES_ZERO, SIGNIFICANT, EFFECT_SIZE, PEOPLE, PERSON_QUARTERS, CELL_STATUS
FROM ACOCO_L2.REASONING.TOKEN_WPS_TEST;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_TOKEN_WPS_QUINTILE
  COMMENT = 'R15 (Q3): mean WPS by token-intensity quintile within level (FY24-26, firm)'
AS SELECT * FROM ACOCO_L2.REASONING.TOKEN_WPS_QUINTILE;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_VENDOR_WPS_TEST
  COMMENT = 'R16 (Q4): product / Cortex model family token intensity vs WPS, OE and WIN within level (partial rho, other products held constant), 90 % CI'
AS
SELECT SCOPE, FISCAL_YEARS, STRATUM, EXPOSURE, EXPOSURE_KIND, OUTCOME, ROUND(RHO, 4) AS RHO, ROUND(CI_LOW, 4) AS CI_LOW,
       ROUND(CI_HIGH, 4) AS CI_HIGH, CI_EXCLUDES_ZERO, SIGNIFICANT, EFFECT_SIZE, PEOPLE, PERSON_QUARTERS, CELL_STATUS
FROM ACOCO_L2.REASONING.VENDOR_WPS_TEST;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_TRAINING_WPS_TEST
  COMMENT = 'R17 (Q5): training hours (2 prior quarters) vs WPS excluding learning within level, 90 % CI'
AS
SELECT SCOPE, FISCAL_YEARS, STRATUM, EXPOSURE, OUTCOME, ROUND(RHO, 4) AS RHO, ROUND(CI_LOW, 4) AS CI_LOW,
       ROUND(CI_HIGH, 4) AS CI_HIGH, CI_EXCLUDES_ZERO, SIGNIFICANT, EFFECT_SIZE, PEOPLE, PERSON_QUARTERS, CELL_STATUS
FROM ACOCO_L2.REASONING.TRAINING_WPS_TEST;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_TRAINING_WPS_QUINTILE
  COMMENT = 'R17 (Q5): mean WPS (excl. learning) by prior-2-quarter training-hours quintile within level'
AS SELECT * FROM ACOCO_L2.REASONING.TRAINING_WPS_QUINTILE;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_CURRICULUM_WPS_TEST
  COMMENT = 'R18 (Q6): curriculum hours (2 prior quarters) vs WPS excl. learning and vs the curriculum target input, within level (partial rho), 90 % CI'
AS
SELECT t.SCOPE, t.FISCAL_YEARS, t.STRATUM, t.CURRICULUM, c.CURRICULUM_NAME, c.TARGET_PILLAR, t.TARGET_INPUT, t.OUTCOME,
       ROUND(t.RHO, 4) AS RHO, ROUND(t.CI_LOW, 4) AS CI_LOW, ROUND(t.CI_HIGH, 4) AS CI_HIGH, t.CI_EXCLUDES_ZERO, t.SIGNIFICANT, t.EFFECT_SIZE, t.PEOPLE,
       t.PERSON_QUARTERS, t.CELL_STATUS
FROM ACOCO_L2.REASONING.CURRICULUM_WPS_TEST t
LEFT JOIN ACOCO_L2.ONTOLOGY.ENT_LEARNING_CATEGORY c ON c.CURRICULUM = t.CURRICULUM;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_AI_WPS_TEST
  COMMENT = 'R13 re-based: WPS uplift of AI-active person-quarters vs the rest within level x group x FY, 90 % CI'
AS
SELECT SCOPE, FISCAL_YEARS, STRATUM, PEOPLE_ACTIVE, PEOPLE, ROUND(UPLIFT_WPS, 2) AS UPLIFT_WPS, ROUND(CI_LOW, 2) AS CI_LOW,
       ROUND(CI_HIGH, 2) AS CI_HIGH, SIGNIFICANT, CELL_STATUS
FROM ACOCO_L2.REASONING.AI_WPS_TEST;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_LEARNING_WPS_PAYBACK_TEST
  COMMENT = 'R14 re-based: WPS (excl. learning) payback of a curriculum episode vs matched comparison, 90 % CI'
AS
SELECT t.SCOPE, t.CURRICULUM, c.CURRICULUM_NAME, c.IS_AI_CURRICULUM, t.EPISODES, t.PEOPLE, ROUND(t.PAYBACK_WPS, 2) AS PAYBACK_WPS,
       ROUND(t.CI_LOW, 2) AS CI_LOW, ROUND(t.CI_HIGH, 2) AS CI_HIGH, t.SIGNIFICANT
FROM ACOCO_L2.REASONING.LEARNING_WPS_PAYBACK_TEST t
LEFT JOIN ACOCO_L2.ONTOLOGY.ENT_LEARNING_CATEGORY c ON c.CURRICULUM = t.CURRICULUM;
