-- CP-06  SERVING views over the reasoning outputs. Run by tools/build_reasoning.py after the models / tests are
-- (re)built - these read tables that only exist once that step has run.
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_ACOCO_BUILD;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_AI_PRODUCTIVITY_TEST
  COMMENT = 'R13: AI-band productivity uplift vs the non-active rest within level x work type, 90 % bootstrap CI; SCOPE = FIRM or MD group'
AS
SELECT SCOPE, FISCAL_YEAR, STRATUM, AI_BAND, PEOPLE_IN_BAND, PEOPLE_TOTAL,
       ROUND(UPLIFT, 4) AS UPLIFT, ROUND(CI_LOW, 4) AS CI_LOW, ROUND(CI_HIGH, 4) AS CI_HIGH, SIGNIFICANT
FROM ACOCO_L2.REASONING.AI_PRODUCTIVITY_TEST;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_LEARNING_PAYBACK_TEST
  COMMENT = 'R14: productivity payback of a curriculum episode vs matched comparison, 90 % bootstrap CI, hours saved'
AS
SELECT SCOPE, CURRICULUM, IS_AI_CURRICULUM, EPISODES, PEOPLE, ROUND(PAYBACK, 4) AS PAYBACK,
       ROUND(CI_LOW, 4) AS CI_LOW, ROUND(CI_HIGH, 4) AS CI_HIGH, SIGNIFICANT, ROUND(HOURS_SAVED, 0) AS HOURS_SAVED
FROM ACOCO_L2.REASONING.LEARNING_PAYBACK_TEST;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_ATTRITION_RISK
  COMMENT = 'Active people with modelled attrition risk (FY26 snapshot), risk decile and global top drivers'
AS
SELECT r.*, p.DISPLAY_NAME, g.MD_GROUP_NAME AS MD_GROUP
FROM ACOCO_L2.REASONING.DT_ATTRITION_RISK r
JOIN ACOCO_L2.ONTOLOGY.ENT_PERSON p ON p.PERSON_ID = r.PERSON_ID
JOIN ACOCO_L2.ONTOLOGY.ENT_MD_GROUP g ON g.MD_GROUP_ID = r.MD_GROUP_ID;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_DEMAND_FORECAST
  COMMENT = 'Delivery demand by skill family: 24 months actual + 12 months forecast with 95 % interval'
AS
SELECT SKILL_FAMILY, MONTH_START, DEMAND_HOURS, NULL::FLOAT AS LOWER_BOUND, NULL::FLOAT AS UPPER_BOUND, 'ACTUAL' AS SERIES_TYPE
FROM ACOCO_L2.REASONING.DT_DEMAND_BY_SKILL_MONTH
WHERE MONTH_START >= DATEADD(month, -24, (SELECT DATE_TRUNC(month, AS_OF_DATE) FROM ACOCO_L2.CORE.VW_AS_OF))
  AND MONTH_START <  (SELECT DATE_TRUNC(month, AS_OF_DATE) FROM ACOCO_L2.CORE.VW_AS_OF)
UNION ALL
SELECT SKILL_FAMILY, MONTH_START, DEMAND_HOURS_FORECAST, LOWER_BOUND, UPPER_BOUND, 'FORECAST'
FROM ACOCO_L2.REASONING.FC_DEMAND_BY_SKILL;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_BENCH_TO_PIPELINE
  COMMENT = 'R1: people rolling off in 90 days and their 5 best open opportunities'
AS SELECT * FROM ACOCO_L2.REASONING.VW_BENCH_TO_PIPELINE_MATCH;

CREATE OR REPLACE VIEW ACOCO_L2.SERVING.VW_ASSET_MATCH
  COMMENT = 'R12: active work packages and the 3 most similar assets available at their start (REUSED / MISSED)'
AS SELECT * FROM ACOCO_L2.REASONING.VW_ASSET_MATCH;
